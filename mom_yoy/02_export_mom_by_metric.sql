/* MANUAL MOM REVIEW: run one numbered SELECT at a time in SQL Assistant.
   READ ONLY: saved view-94 results only; no new objects or profiling/source scan.
   Replace DQ_DB with LAB_T_ORION_MVT in your copy.
   Every section uses project RDS and the confirmed successful runs:
   17 for numeric, 18 for categorical/date/identifier. Edit IN (17,18) for other runs.
   Keep both RUN_NUMBER and PROJECT_ID filters. Different runs remain separate.
   Export sections 01-08 into separate Excel tabs first; count sections 09-16
   are optional because the user has already reviewed counts.
   Only MODERATE/HIGH relative movement and ZERO_BASE_MOVEMENT are selected.
   Existing flags are review triggers, not automatic DQ failures.
   Rates and relative changes are fractions; CHANGE_PP is percentage points.
   ABSOLUTE_CHANGE is signed current minus previous, despite its column name.
   Previous values/counts are reconstructed from current minus saved MOM_CHANGE.
   No change threshold is reapplied and June 2009 is not excluded or explained
   automatically. No account-level/customer records are read or exported.
   See ../README.md for export and review instructions. */

/* 01: MISSING_RATE. Excel tab: 01_MISSING_RATE. */
SELECT C.RUN_NUMBER,C.PROJECT_ID,C.FIELD_NAME,C.FIELD_TYPE,
       C.POU_DT,C.MOM_PREVIOUS_POU_DT AS PREVIOUS_POU_DT,
       CAST('MISSING_RATE' AS VARCHAR(32)) AS METRIC_NAME,
       CAST(C.MISSING_RATE-C.MISSING_RATE_MOM_CHANGE AS DECIMAL(38,6)) AS PREVIOUS_VALUE,
       C.MISSING_RATE AS CURRENT_VALUE,C.MISSING_RATE_MOM_CHANGE AS ABSOLUTE_CHANGE,
       CAST(C.MISSING_RATE_MOM_CHANGE*100.000000 AS DECIMAL(38,6)) AS CHANGE_PP,
       C.MISSING_RATE_MOM_REL_CHANGE AS RELATIVE_CHANGE,C.MISSING_RATE_MOM_FLAG AS MOVEMENT_FLAG,
       CAST(C.MISSING_COUNT-C.MISSING_COUNT_MOM_CHANGE AS DECIMAL(38,0)) AS PREVIOUS_EVENT_COUNT,
       C.MISSING_COUNT AS CURRENT_EVENT_COUNT,
       CAST(C.TOTAL_COUNT-C.TOTAL_COUNT_MOM_CHANGE AS DECIMAL(38,0)) AS PREVIOUS_DENOMINATOR,
       C.TOTAL_COUNT AS CURRENT_DENOMINATOR,
       COUNT(*) OVER () AS EXPECTED_ROWS_IN_EXPORT
FROM DQ_DB.DQ_FIELD_CHANGE_REVIEW C
WHERE C.PROJECT_ID='RDS' AND C.RUN_NUMBER IN (17,18)
  AND C.MISSING_RATE_MOM_FLAG IN
      ('MODERATE_RELATIVE_MOVEMENT','HIGH_RELATIVE_MOVEMENT','ZERO_BASE_MOVEMENT')
ORDER BY CASE C.MISSING_RATE_MOM_FLAG WHEN 'HIGH_RELATIVE_MOVEMENT' THEN 1
                           WHEN 'ZERO_BASE_MOVEMENT' THEN 2 ELSE 3 END,
         ABS(C.MISSING_RATE_MOM_REL_CHANGE) DESC,ABS(C.MISSING_RATE_MOM_CHANGE) DESC,
         C.FIELD_NAME,C.POU_DT,C.RUN_NUMBER;

