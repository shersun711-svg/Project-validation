/* Executes the saved-result SELECT on synthetic data using SQLite adaptations.
   Does not compile Teradata SQL/SPL, read customer data or run profiling. */
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
const source=fs.readFileSync(new URL('../tests/compare_numeric_development.sql',import.meta.url),'utf8');
const executable=source.replace(/\/\*[\s\S]*?\*\//g,'');
assert(!/\b(CREATE|INSERT|UPDATE|DELETE|DROP|CALL|REPLACE)\b/i.test(executable));
assert(!/VW_RDS_PHASE2_FACT/i.test(executable));
const sql=source.replaceAll('DQ_DB.','')
 .replace(/EXTRACT\(YEAR FROM D\.POU_DT\)/g,"CAST(strftime('%Y',D.POU_DT) AS INTEGER)")
 .replace(/EXTRACT\(MONTH FROM D\.POU_DT\)/g,"CAST(strftime('%m',D.POU_DT) AS INTEGER)");
const db=new DatabaseSync(':memory:');
db.function('CHARACTER_LENGTH',v=>v?.length??null);
db.exec(`ATTACH DATABASE ':memory:' AS LAB_P_DECISION_SCIENCE;
CREATE TABLE DQ_RUN_LOG (RUN_ID TEXT, PROJECT_ID TEXT, STATUS TEXT, ATTEMPT_NO INTEGER,PROFILE_OVERALL TEXT,PROFILE_MONTHLY TEXT,PROFILE_YEARLY TEXT);
CREATE TABLE DQ_RUN_NUMBER (RUN_ID TEXT,RUN_NUMBER INTEGER);
CREATE TABLE DQ_RUN_FIELD_CONFIG (RUN_ID TEXT,FIELD_NAME TEXT,FIELD_TYPE TEXT);
CREATE TABLE DQ_MODULE_LOG (RUN_ID TEXT,MODULE_NAME TEXT,ATTEMPT_NO INTEGER,BATCH_ID INTEGER,STATUS TEXT);
CREATE TABLE DQ_METRIC_RESULT (RUN_ID TEXT,PROJECT_ID TEXT,FIELD_NAME TEXT,PERIOD_LEVEL TEXT,PERIOD_VALUE TEXT,MODULE_NAME TEXT,METRIC_NAME TEXT,METRIC_VALUE NUMERIC,POU_DT TEXT);
CREATE TABLE DQ_NUMERIC_STATISTICS (RUN_ID TEXT,FIELD_NAME TEXT,PERIOD_LEVEL TEXT,PERIOD_VALUE TEXT,TOTAL_COUNT INTEGER,VALID_COUNT INTEGER);
CREATE TABLE LAB_P_DECISION_SCIENCE.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT (
 RUN_ID INTEGER,FIELD_NAME TEXT,RUN_TYPE TEXT,POU_DT TEXT,ROW_COUNT INTEGER,MISSING_COUNT INTEGER,MISSING_PCT NUMERIC,
 ZERO_COUNT INTEGER,ZERO_PCT NUMERIC,MIN_VALUE NUMERIC,MAX_VALUE NUMERIC,MEAN_VALUE NUMERIC,STDDEV_VALUE NUMERIC,
 SPECIAL_COUNT INTEGER,SPECIAL_PCT NUMERIC,VALID_COUNT INTEGER,OUTLIER_COUNT INTEGER,OUTLIER_PCT NUMERIC,
 OUTLIER_VALUE_LOWER NUMERIC,OUTLIER_VALUE_UPPER NUMERIC);
INSERT INTO DQ_RUN_LOG VALUES ('our','RDS','SUCCEEDED',1,'Y','Y','N');
INSERT INTO DQ_RUN_NUMBER VALUES ('our',16);
INSERT INTO DQ_RUN_FIELD_CONFIG VALUES ('our','AMOUNT','NUMERIC');
INSERT INTO DQ_MODULE_LOG VALUES ('our','NUMERIC_BASIC',1,0,'SUCCEEDED'),('our','NUMERIC_OUTLIERS',1,0,'SUCCEEDED');`);
const metrics={TOTAL_COUNT:100,NON_MISSING_COUNT:90,MISSING_COUNT:10,MISSING_RATE_PCT:10,
 ZERO_COUNT:5,ZERO_RATE_PCT:5,MINIMUM:0,MAXIMUM:50,MEAN:10,STDDEV_POP:2,SPECIAL_COUNT:10,SPECIAL_RATE_PCT:10,
 OUTLIER_LOWER_BOUND:4,OUTLIER_UPPER_BOUND:16,OUTLIER_COUNT:2,OUTLIER_RATE_PCT:2.5,OUTLIER_VALID_COUNT:80};
const add=db.prepare('INSERT INTO DQ_METRIC_RESULT VALUES (?,?,?,?,?,?,?,?,?)');
for(const [level,key,date] of [['OVERALL','ALL',null],['MONTHLY','2018-01','2018-01-31']]){
 for(const [name,value] of Object.entries(metrics))add.run('our','RDS','AMOUNT',level,key,name.startsWith('OUTLIER_')?'NUMERIC_OUTLIERS':'NUMERIC_BASIC',name,value,date);
 db.prepare('INSERT INTO DQ_NUMERIC_STATISTICS VALUES (?,?,?,?,?,?)').run('our','AMOUNT',level,key,100,80);
 db.prepare('INSERT INTO LAB_P_DECISION_SCIENCE.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)')
 .run(1,'AMOUNT',level,date,100,10,.1,5,.05,0,50,10,2,10,.1,80,2,.025,4,16);
}
const dev='LAB_P_DECISION_SCIENCE.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT';
const rows=(query=sql)=>{const statement=db.prepare(query);statement.setReadBigInts(true);return statement.all();};
const details=query=>rows(query).filter(r=>r.ROW_KIND==='DETAIL');
let scenarios=0;
function scenario(change,status,metric,query=sql){
 db.exec('SAVEPOINT test_case');
 try{db.exec(change);const found=details(query);assert(found.some(r=>r.COMPARISON_STATUS===status&&(!metric||r.METRIC_NAME===metric)),JSON.stringify(found,(_,v)=>typeof v==='bigint'?String(v):v));scenarios++;}
 finally{db.exec('ROLLBACK TO test_case; RELEASE test_case');}
}
assert.equal(rows().length,1);assert.equal(rows()[0].COMPARISON_STATUS,'MATCH');assert.equal(rows()[0].COMPARISON_COUNT,34n);
assert.equal(details(sql.replace("CAST('N' AS CHAR(1)) AS SHOW_MATCHES","CAST('Y' AS CHAR(1)) AS SHOW_MATCHES")).length,34);
scenario(`UPDATE ${dev} SET MEAN_VALUE=10.0000005`,'MATCH','MEAN',sql.replace("CAST('N' AS CHAR(1)) AS SHOW_MATCHES","CAST('Y' AS CHAR(1)) AS SHOW_MATCHES"));
scenario(`UPDATE ${dev} SET MEAN_VALUE=10.00001`,'DIFFERENT','MEAN');
scenario(`UPDATE ${dev} SET MISSING_PCT=.100002`,'DIFFERENT','MISSING_RATE_PCT');
scenario(`UPDATE ${dev} SET MIN_VALUE=.00000001`,'DIFFERENT','MINIMUM');
scenario(`UPDATE ${dev} SET MEAN_VALUE=NULL`,'DIFFERENT','MEAN');
scenario(`INSERT INTO DQ_METRIC_RESULT SELECT * FROM DQ_METRIC_RESULT WHERE METRIC_NAME='MEAN'`,'DUPLICATE_ENGINE','MEAN');
scenario(`INSERT INTO DQ_NUMERIC_STATISTICS SELECT * FROM DQ_NUMERIC_STATISTICS`,'DUPLICATE_ENGINE');
scenario(`INSERT INTO ${dev} SELECT * FROM ${dev}`,'DUPLICATE_DEVELOPMENT');
scenario(`INSERT INTO ${dev} SELECT RUN_ID,FIELD_NAME,RUN_TYPE,'2018-01-15',ROW_COUNT,MISSING_COUNT,MISSING_PCT,ZERO_COUNT,ZERO_PCT,MIN_VALUE,MAX_VALUE,MEAN_VALUE,STDDEV_VALUE,SPECIAL_COUNT,SPECIAL_PCT,VALID_COUNT,OUTLIER_COUNT,OUTLIER_PCT,OUTLIER_VALUE_LOWER,OUTLIER_VALUE_UPPER FROM ${dev} WHERE RUN_TYPE='MONTHLY'`,'PERIOD_SCOPE_MISMATCH');
scenario(`DELETE FROM DQ_METRIC_RESULT WHERE METRIC_NAME='MEAN'`,'MISSING_ENGINE','MEAN');
scenario(`DELETE FROM ${dev} WHERE RUN_TYPE='MONTHLY'`,'MISSING_DEVELOPMENT');
scenario(`INSERT INTO DQ_RUN_FIELD_CONFIG VALUES ('our','MISSING_FIELD','NUMERIC')`,'MISSING_BOTH');
scenario(`UPDATE ${dev} SET POU_DT='2018-01-30' WHERE RUN_TYPE='MONTHLY'`,'SNAPSHOT_MISMATCH');
scenario(`UPDATE ${dev} SET ROW_COUNT=101`,'POPULATION_MISMATCH');
scenario(`DELETE FROM DQ_NUMERIC_STATISTICS`,'POPULATION_UNAVAILABLE');
scenario(`UPDATE DQ_METRIC_RESULT SET METRIC_VALUE=NULL WHERE METRIC_NAME='OUTLIER_COUNT';UPDATE DQ_NUMERIC_STATISTICS SET VALID_COUNT=0;UPDATE ${dev} SET VALID_COUNT=0,OUTLIER_COUNT=0`,'DEFINITION_DIFFERENCE','OUTLIER_COUNT');
scenario(`UPDATE DQ_RUN_LOG SET STATUS='FAILED'`,'NOT_EVALUATED');
scenario(`UPDATE DQ_RUN_LOG SET PROJECT_ID='OTHER'`,'NOT_EVALUATED');
scenario(`UPDATE DQ_MODULE_LOG SET STATUS='FAILED'`,'NOT_EVALUATED');
scenario(`DELETE FROM ${dev}`,'NOT_EVALUATED');
scenario('', 'NOT_EVALUATED',null,sql.replace('CAST(1 AS BIGINT) AS DEV_RUN_ID','CAST(NULL AS BIGINT) AS DEV_RUN_ID'));
scenario(`UPDATE DQ_RUN_LOG SET PROFILE_OVERALL='N',PROFILE_MONTHLY='N',PROFILE_YEARLY='Y'`,'NOT_EVALUATED');
// Exact integer comparison stays exact above the IEEE floating-point integer limit.
db.exec('SAVEPOINT exact_count');
db.exec(`UPDATE DQ_METRIC_RESULT SET METRIC_VALUE=9007199254740993 WHERE METRIC_NAME='ZERO_COUNT';UPDATE ${dev} SET ZERO_COUNT=9007199254740992`);
assert(details().filter(r=>r.METRIC_NAME==='ZERO_COUNT').every(r=>r.COMPARISON_STATUS==='DIFFERENT'&&r.COUNT_DELTA===1n));
db.exec('ROLLBACK TO exact_count; RELEASE exact_count');
// Unselected development fields and unrelated development runs are out of scope.
db.exec(`INSERT INTO ${dev} SELECT 2,FIELD_NAME,RUN_TYPE,POU_DT,ROW_COUNT,MISSING_COUNT,MISSING_PCT,ZERO_COUNT,ZERO_PCT,MIN_VALUE,MAX_VALUE,MEAN_VALUE,STDDEV_VALUE,SPECIAL_COUNT,SPECIAL_PCT,VALID_COUNT,OUTLIER_COUNT,OUTLIER_PCT,OUTLIER_VALUE_LOWER,OUTLIER_VALUE_UPPER FROM ${dev};UPDATE ${dev} SET FIELD_NAME='OTHER' WHERE RUN_ID=2`);
assert.equal(rows()[0].COMPARISON_COUNT,34n);
console.log(`Saved-result comparison passed: 34 mapped field/period/metrics; ${scenarios} exception/tolerance scenarios; exact large counts. SQLite adaptation only; Teradata execution remains unverified.`);
db.close();
