/* 08B: F05/F09: unrounded saved population statistics. No source scan.
   These computed bounds are diagnostic only; the saved review bounds in 08A
   are also available. A field definition is needed to establish a binary domain. */
SELECT N.RUN_NUMBER,L.PROJECT_ID,S.FIELD_NAME,S.PERIOD_VALUE,
       S.TOTAL_COUNT,S.VALID_COUNT,S.MEAN_VALUE,S.STDDEV_VALUE,
       S.MEAN_VALUE-3*S.STDDEV_VALUE AS CHECK_LOWER_BOUND,
       S.MEAN_VALUE+3*S.STDDEV_VALUE AS CHECK_UPPER_BOUND
FROM LAB_T_ORION_MVT.DQ_NUMERIC_STATISTICS S
JOIN LAB_T_ORION_MVT.DQ_RUN_NUMBER N ON S.RUN_ID=N.RUN_ID
JOIN LAB_T_ORION_MVT.DQ_RUN_LOG L ON S.RUN_ID=L.RUN_ID
WHERE N.RUN_NUMBER=17 AND L.PROJECT_ID='RDS' AND L.STATUS='SUCCEEDED'
  AND S.PERIOD_LEVEL='MONTHLY'
  AND ((S.FIELD_NAME IN ('CUST_ALL_V_MAX_DEF_L12M_IND','CUST_ALL_V_MAX_DEF_IND_CM')
        AND S.PERIOD_VALUE BETWEEN '2017-01' AND '2019-01')
    OR (S.FIELD_NAME='MV_AMORTISATION_RT'
        AND S.PERIOD_VALUE BETWEEN '2013-01' AND '2013-08'))
ORDER BY S.FIELD_NAME,S.PERIOD_VALUE;

