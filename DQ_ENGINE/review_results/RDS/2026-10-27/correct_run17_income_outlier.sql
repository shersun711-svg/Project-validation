/* USER-AUTHORISED MANUAL CORRECTION, not an engine calculation change.
   RDS / run number 17 / TOTALNETMONTHLYINCOME / NUMERIC_OUTLIERS / OVERALL ALL.
   Expected originals: count=1, stored percentage=10, numerator=1, denominator=10.
   Intended correction: count=0, stored percentage=0, numerator=0.
   DQ_BASIC_REVIEW displays that stored percentage as fraction 0.000000.
   Counts, statistics, bounds, timestamps and other fields/periods/runs stay intact.
   Refresh an existing rule row using the shared evaluator and captured thresholds.
   Do not call SP_DQ_CLASSIFY: it intentionally rejects completed runs.

   SQL Assistant, Teradata mode, ONE connection. Pause other maintenance first.
   A: Run before B; READY_RUNS must be 1. Export the before-results for your audit.
   B: Execute BT through the verification SELECTs in order. Stop on ANY error and
      ROLLBACK. Commit with ET only if both corrected metrics are zero and the
      percentage numerator/denominator is 0/10. Rule count stays as it was (0 or 1).
   C: Recheck the final view. No source scan or profiling rerun is needed.
   This script has not been executed against your Teradata database here. */

/* A: The target is empty if the expected original values have changed. */
CREATE VOLATILE TABLE DQ_FIX17_TARGET AS
(
    SELECT L.RUN_ID
    FROM LAB_T_ORION_MVT.DQ_RUN_LOG L
    JOIN LAB_T_ORION_MVT.DQ_RUN_NUMBER N ON N.RUN_ID=L.RUN_ID
    WHERE N.RUN_NUMBER=17 AND L.PROJECT_ID='RDS' AND L.STATUS='SUCCEEDED'
      AND EXISTS
      (SELECT 1 FROM LAB_T_ORION_MVT.DQ_NUMERIC_STATISTICS S
       WHERE S.RUN_ID=L.RUN_ID AND S.FIELD_NAME='TOTALNETMONTHLYINCOME'
         AND S.PERIOD_LEVEL='OVERALL' AND S.PERIOD_VALUE='ALL' AND S.VALID_COUNT=10)
      AND 2=
      (SELECT COUNT(*) FROM LAB_T_ORION_MVT.DQ_METRIC_RESULT M
       WHERE M.RUN_ID=L.RUN_ID AND M.PROJECT_ID='RDS'
         AND M.FIELD_NAME='TOTALNETMONTHLYINCOME' AND M.MODULE_NAME='NUMERIC_OUTLIERS'
         AND M.PERIOD_LEVEL='OVERALL' AND M.PERIOD_VALUE='ALL' AND M.DQ_COLOUR IS NULL
         AND ((M.METRIC_NAME='OUTLIER_COUNT' AND M.METRIC_VALUE=1)
           OR (M.METRIC_NAME='OUTLIER_RATE_PCT' AND M.METRIC_VALUE=10
               AND M.RATE_NUMERATOR=1 AND M.RATE_DENOMINATOR=10)))
) WITH DATA UNIQUE PRIMARY INDEX (RUN_ID) ON COMMIT PRESERVE ROWS;

SELECT COUNT(*) AS READY_RUNS FROM DQ_FIX17_TARGET;

/* Preserve the existing rule key and before-image for this session only. */
CREATE VOLATILE TABLE DQ_FIX17_RULE_BEFORE AS
(
    SELECT Q.* FROM LAB_T_ORION_MVT.DQ_RULE_RESULT Q
    WHERE Q.RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_TARGET)
      AND Q.PROJECT_ID='RDS' AND Q.FIELD_NAME='TOTALNETMONTHLYINCOME'
      AND Q.MODULE_NAME='NUMERIC_OUTLIERS' AND Q.PERIOD_LEVEL='OVERALL'
      AND Q.PERIOD_VALUE='ALL' AND Q.RULE_NAME='OUTLIER_RATE_PCT'
) WITH DATA PRIMARY INDEX (RUN_ID) ON COMMIT PRESERVE ROWS;

SELECT M.* FROM LAB_T_ORION_MVT.DQ_METRIC_RESULT M
WHERE M.RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_TARGET)
  AND M.PROJECT_ID='RDS' AND M.FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND M.MODULE_NAME='NUMERIC_OUTLIERS' AND M.PERIOD_LEVEL='OVERALL'
  AND M.PERIOD_VALUE='ALL' AND M.METRIC_NAME IN ('OUTLIER_COUNT','OUTLIER_RATE_PCT');
SELECT * FROM DQ_FIX17_RULE_BEFORE;

/* B: Scoped correction; only the two agreed metric rows qualify. */
BT;
LOCKING TABLE LAB_T_ORION_MVT.DQ_RUN_LOG FOR WRITE
SELECT COUNT(*) AS SUCCEEDED_TARGET_RUNS FROM LAB_T_ORION_MVT.DQ_RUN_LOG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_TARGET)
  AND PROJECT_ID='RDS' AND STATUS='SUCCEEDED';

UPDATE LAB_T_ORION_MVT.DQ_METRIC_RESULT
SET METRIC_VALUE=0,
    RATE_NUMERATOR=CASE WHEN METRIC_NAME='OUTLIER_RATE_PCT' THEN 0 ELSE RATE_NUMERATOR END
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_TARGET)
  AND PROJECT_ID='RDS' AND FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND MODULE_NAME='NUMERIC_OUTLIERS' AND PERIOD_LEVEL='OVERALL' AND PERIOD_VALUE='ALL'
  AND ((METRIC_NAME='OUTLIER_COUNT' AND METRIC_VALUE=1)
    OR (METRIC_NAME='OUTLIER_RATE_PCT' AND METRIC_VALUE=10
        AND RATE_NUMERATOR=1 AND RATE_DENOMINATOR=10));

/* Maintain an existing assessment only; do not invent an unevaluated run's history. */
DELETE FROM LAB_T_ORION_MVT.DQ_RULE_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_RULE_BEFORE)
  AND PROJECT_ID='RDS' AND FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND MODULE_NAME='NUMERIC_OUTLIERS' AND PERIOD_LEVEL='OVERALL'
  AND PERIOD_VALUE='ALL' AND RULE_NAME='OUTLIER_RATE_PCT';

INSERT INTO LAB_T_ORION_MVT.DQ_RULE_RESULT
(RUN_ID,PROJECT_ID,FIELD_NAME,MODULE_NAME,PERIOD_LEVEL,PERIOD_VALUE,
 RULE_NAME,OBSERVED_VALUE,GREEN_THRESHOLD,RED_THRESHOLD,STATUS,REASON,POU_DT)
SELECT V.RUN_ID,V.PROJECT_ID,V.FIELD_NAME,V.MODULE_NAME,V.PERIOD_LEVEL,V.PERIOD_VALUE,
       V.METRIC_NAME,V.OBSERVED_VALUE,V.GREEN_THRESHOLD,V.RED_THRESHOLD,V.DQ_COLOUR,V.REASON,V.POU_DT
FROM LAB_T_ORION_MVT.DQ_COLOUR_RULE V
JOIN DQ_FIX17_RULE_BEFORE B
  ON B.RUN_ID=V.RUN_ID AND B.PROJECT_ID=V.PROJECT_ID AND B.FIELD_NAME=V.FIELD_NAME
 AND B.MODULE_NAME=V.MODULE_NAME AND B.PERIOD_LEVEL=V.PERIOD_LEVEL
 AND B.PERIOD_VALUE=V.PERIOD_VALUE AND B.RULE_NAME=V.METRIC_NAME;

/* Inspect before ET: two rows, both zero; rate numerator/denominator 0/10. */
SELECT METRIC_NAME,METRIC_VALUE,RATE_NUMERATOR,RATE_DENOMINATOR
FROM LAB_T_ORION_MVT.DQ_METRIC_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_TARGET)
  AND PROJECT_ID='RDS' AND FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND MODULE_NAME='NUMERIC_OUTLIERS' AND PERIOD_LEVEL='OVERALL' AND PERIOD_VALUE='ALL'
  AND METRIC_NAME IN ('OUTLIER_COUNT','OUTLIER_RATE_PCT');
SELECT Q.* FROM LAB_T_ORION_MVT.DQ_RULE_RESULT Q
WHERE Q.RUN_ID IN (SELECT RUN_ID FROM DQ_FIX17_RULE_BEFORE)
  AND Q.PROJECT_ID='RDS' AND Q.FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND Q.MODULE_NAME='NUMERIC_OUTLIERS' AND Q.PERIOD_LEVEL='OVERALL'
  AND Q.PERIOD_VALUE='ALL' AND Q.RULE_NAME='OUTLIER_RATE_PCT';
ET;

/* C: Expected count=0, fractional rate=0, valid count=10. */
SELECT RUN_NUMBER,FIELD_NAME,PERIOD_LEVEL,OUTLIER_VALID_COUNT,OUTLIER_COUNT,OUTLIER_RATE
FROM LAB_T_ORION_MVT.DQ_BASIC_REVIEW
WHERE PROJECT_ID='RDS' AND RUN_NUMBER=17
  AND FIELD_NAME='TOTALNETMONTHLYINCOME' AND PERIOD_LEVEL='OVERALL';

DROP TABLE DQ_FIX17_RULE_BEFORE;
DROP TABLE DQ_FIX17_TARGET;
