/* Read-only investigation; no changes to source, configuration or saved results.
   Sections 1-3 read saved metadata/results. Section 4 scans the CURRENT RDS view.
   Run each complete SELECT separately in SQL Assistant.
   Confirm section 3's source metadata matches the hardcoded view in section 4.
   If the source has changed since run 17, section 4 is not historical proof.
   Do not publish individual income observations in the public repository.
   Actual precision can differ: our review shows six decimals, while section 3
   reads the full stored FLOAT statistics used for outlier decisions. */

/* 1. Our selected field/period. */
SELECT RUN_NUMBER,FIELD_NAME,PERIOD_LEVEL,
       TOTAL_COUNT,NON_MISSING_COUNT,MISSING_COUNT,SPECIAL_COUNT,
       OUTLIER_VALID_COUNT,MEAN_VALUE,STDDEV_VALUE,
       OUTLIER_LOWER_BOUND,OUTLIER_UPPER_BOUND,OUTLIER_COUNT,OUTLIER_RATE
FROM LAB_T_ORION_MVT.DQ_BASIC_REVIEW
WHERE PROJECT_ID='RDS' AND RUN_NUMBER=17
  AND UPPER(TRIM(FIELD_NAME))='TOTALNETMONTHLYINCOME'
  AND PERIOD_LEVEL='OVERALL';

/* 2. MDT saved values, before comparison rounding. */
SELECT RUN_ID,FIELD_NAME,RUN_TYPE,
       ROW_COUNT,MISSING_COUNT,SPECIAL_COUNT,VALID_COUNT,
       MEAN_VALUE,STDDEV_VALUE,OUTLIER_VALUE_LOWER,OUTLIER_VALUE_UPPER,
       OUTLIER_COUNT,OUTLIER_PCT
FROM LAB_T_ORION_MVT.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT
WHERE RUN_ID=15
  AND UPPER(TRIM(FIELD_NAME))='TOTALNETMONTHLYINCOME'
  AND UPPER(TRIM(RUN_TYPE))='OVERALL';

/* 3. Saved calculation inputs and source metadata, not rounded review metrics. */
SELECT N.RUN_NUMBER,L.PROJECT_ID,L.SOURCE_DATABASE,L.SOURCE_TABLE,
       L.REPORTING_DATE_FIELD,S.TOTAL_COUNT,S.VALID_COUNT,
       S.MEAN_VALUE,S.STDDEV_VALUE,
       S.MEAN_VALUE-3.0*S.STDDEV_VALUE AS FULL_LOWER_BOUND,
       S.MEAN_VALUE+3.0*S.STDDEV_VALUE AS FULL_UPPER_BOUND
FROM LAB_T_ORION_MVT.DQ_NUMERIC_STATISTICS S
JOIN LAB_T_ORION_MVT.DQ_RUN_NUMBER N ON N.RUN_ID=S.RUN_ID
JOIN LAB_T_ORION_MVT.DQ_RUN_LOG L ON L.RUN_ID=S.RUN_ID
WHERE N.RUN_NUMBER=17 AND L.PROJECT_ID='RDS' AND L.STATUS='SUCCEEDED'
  AND S.FIELD_NAME='TOTALNETMONTHLYINCOME'
  AND S.PERIOD_LEVEL='OVERALL' AND S.PERIOD_VALUE='ALL';

/* 4. Current valid observations, filtered with run 17's captured special list.
   Expect CURRENT_VALID_COUNT=10. Equal counts alone do not prove unchanged data.
   Flags compare the same current value against the two saved calculations.
   Positive margins indicate a strict violation of OUR corresponding bound.
   Decimal margins are for display only; OUR_FLAG uses the original FLOAT test.
   MDT_FLAG uses MDT's saved bounds and input cast, not a claim that its original
   source population has been independently reconstructed. */
WITH CHOSEN_RUN AS
(
    SELECT L.RUN_ID
    FROM LAB_T_ORION_MVT.DQ_RUN_LOG L
    JOIN LAB_T_ORION_MVT.DQ_RUN_NUMBER N ON N.RUN_ID=L.RUN_ID
    WHERE N.RUN_NUMBER=17 AND L.PROJECT_ID='RDS' AND L.STATUS='SUCCEEDED'
),
SAVED_STATS AS
(
    SELECT S.*
    FROM LAB_T_ORION_MVT.DQ_NUMERIC_STATISTICS S
    JOIN CHOSEN_RUN C ON C.RUN_ID=S.RUN_ID
    WHERE S.FIELD_NAME='TOTALNETMONTHLYINCOME'
      AND S.PERIOD_LEVEL='OVERALL' AND S.PERIOD_VALUE='ALL'
),
VALID_VALUES AS
(
    SELECT R.FACT_DT,R.TOTALNETMONTHLYINCOME AS OBSERVED_VALUE
    FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT R
    CROSS JOIN CHOSEN_RUN C
    WHERE R.TOTALNETMONTHLYINCOME IS NOT NULL
      AND NOT EXISTS
      (
          SELECT 1 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
          WHERE V.RUN_ID=C.RUN_ID AND V.FIELD_TYPE='NUMERIC'
            AND V.NUMERIC_VALUE=R.TOTALNETMONTHLYINCOME
      )
)
SELECT V.FACT_DT,V.OBSERVED_VALUE,
       COUNT(*) OVER () AS CURRENT_VALID_COUNT,
       S.VALID_COUNT AS SAVED_VALID_COUNT,
       S.MEAN_VALUE-3.0*S.STDDEV_VALUE AS OUR_LOWER_BOUND,
       S.MEAN_VALUE+3.0*S.STDDEV_VALUE AS OUR_UPPER_BOUND,
       D.OUTLIER_VALUE_LOWER AS MDT_LOWER_BOUND,
       D.OUTLIER_VALUE_UPPER AS MDT_UPPER_BOUND,
       CASE WHEN CAST(V.OBSERVED_VALUE AS FLOAT)<S.MEAN_VALUE-3.0*S.STDDEV_VALUE
                  OR CAST(V.OBSERVED_VALUE AS FLOAT)>S.MEAN_VALUE+3.0*S.STDDEV_VALUE
            THEN 1 ELSE 0 END AS OUR_FLAG,
       CASE WHEN CAST(V.OBSERVED_VALUE AS DECIMAL(38,10))<D.OUTLIER_VALUE_LOWER
                  OR CAST(V.OBSERVED_VALUE AS DECIMAL(38,10))>D.OUTLIER_VALUE_UPPER
            THEN 1 ELSE 0 END AS MDT_FLAG,
       CAST((S.MEAN_VALUE-3.0*S.STDDEV_VALUE)-CAST(V.OBSERVED_VALUE AS FLOAT)
            AS DECIMAL(38,16)) AS BELOW_OUR_LOWER_BY,
       CAST(CAST(V.OBSERVED_VALUE AS FLOAT)-(S.MEAN_VALUE+3.0*S.STDDEV_VALUE)
            AS DECIMAL(38,16)) AS ABOVE_OUR_UPPER_BY
FROM VALID_VALUES V
CROSS JOIN SAVED_STATS S
JOIN LAB_T_ORION_MVT.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT D
  ON D.RUN_ID=15 AND UPPER(TRIM(D.FIELD_NAME))='TOTALNETMONTHLYINCOME'
 AND UPPER(TRIM(D.RUN_TYPE))='OVERALL'
ORDER BY V.OBSERVED_VALUE,V.FACT_DT;
