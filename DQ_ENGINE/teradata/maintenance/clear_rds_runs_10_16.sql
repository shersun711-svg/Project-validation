/* Selective cleanup: RDS runs 10 through 16 ONLY.
   Permanently deletes their results, snapshots and execution logs.
   Preserves RDS runs 17/18/19, all other projects, source/configuration tables,
   run-number mappings and counter. Does not drop any database objects.
   Requires current setup/22 account tables. Replace DQ_DB with LAB_T_ORION_MVT.
   Pause engine submissions first. Use SQL Assistant in Teradata mode, one session.
   This script has not been executed against Teradata here.

   A: Review the target list; it must contain only the intended RDS runs.
   If the RUNNING query returns any row, stop before B.
   B: Execute BT through ET in the same connection. On ANY error, stop and
   ROLLBACK before continuing; do not execute ET after an error.
   C: Every REMAINING_ROWS value must be zero. Keep the same connection.
*/

/* A: Freeze the explicit deletion list for this session. */
CREATE VOLATILE TABLE DQ_CLEANUP_TARGET AS
(
    SELECT L.RUN_ID,N.RUN_NUMBER,L.PROJECT_ID,L.STATUS
    FROM DQ_DB.DQ_RUN_LOG L
    JOIN DQ_DB.DQ_RUN_NUMBER N ON N.RUN_ID=L.RUN_ID
    WHERE L.PROJECT_ID='RDS' AND N.RUN_NUMBER BETWEEN 10 AND 16
) WITH DATA UNIQUE PRIMARY INDEX (RUN_ID) ON COMMIT PRESERVE ROWS;

SELECT * FROM DQ_CLEANUP_TARGET ORDER BY RUN_NUMBER;
SELECT RUN_ID,PROJECT_ID,STATUS FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING';

/* B: Targeted deletion. Guards also refuse cleanup if any run is RUNNING. */
BT;
LOCKING TABLE DQ_DB.DQ_RUN_LOG FOR WRITE
SELECT COUNT(*) AS RUNNING_RUNS FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING';
DELETE FROM DQ_DB.DQ_RULE_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_METRIC_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_FIELD_AVAILABILITY
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_NUMERIC_STATISTICS
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_OUTLIER_CHUNK_YEAR
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_RUN_FIELD_CONFIG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_RUN_SPECIAL_VALUE
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_ACCOUNT_DETAIL
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_ACCOUNT_SUMMARY
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_MODULE_LOG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
DELETE FROM DQ_DB.DQ_RUN_LOG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
  AND NOT EXISTS (SELECT 1 FROM DQ_DB.DQ_RUN_LOG WHERE STATUS='RUNNING');
ET;

/* C: Verify all targeted history was removed. */
SELECT CAST('DQ_RULE_RESULT' AS VARCHAR(32)) AS TABLE_NAME,COUNT(*) AS REMAINING_ROWS
FROM DQ_DB.DQ_RULE_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_METRIC_RESULT',COUNT(*)
FROM DQ_DB.DQ_METRIC_RESULT
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_FIELD_AVAILABILITY',COUNT(*)
FROM DQ_DB.DQ_FIELD_AVAILABILITY
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_NUMERIC_STATISTICS',COUNT(*)
FROM DQ_DB.DQ_NUMERIC_STATISTICS
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_OUTLIER_CHUNK_YEAR',COUNT(*)
FROM DQ_DB.DQ_OUTLIER_CHUNK_YEAR
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_RUN_FIELD_CONFIG',COUNT(*)
FROM DQ_DB.DQ_RUN_FIELD_CONFIG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_RUN_SPECIAL_VALUE',COUNT(*)
FROM DQ_DB.DQ_RUN_SPECIAL_VALUE
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_ACCOUNT_DETAIL',COUNT(*)
FROM DQ_DB.DQ_ACCOUNT_DETAIL
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_ACCOUNT_SUMMARY',COUNT(*)
FROM DQ_DB.DQ_ACCOUNT_SUMMARY
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_MODULE_LOG',COUNT(*)
FROM DQ_DB.DQ_MODULE_LOG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET)
UNION ALL SELECT 'DQ_RUN_LOG',COUNT(*)
FROM DQ_DB.DQ_RUN_LOG
WHERE RUN_ID IN (SELECT RUN_ID FROM DQ_CLEANUP_TARGET);

/* Preserved successful review runs. */
SELECT N.RUN_NUMBER,L.PROJECT_ID,L.STATUS
FROM DQ_DB.DQ_RUN_LOG L
JOIN DQ_DB.DQ_RUN_NUMBER N ON N.RUN_ID=L.RUN_ID
WHERE L.PROJECT_ID='RDS' AND N.RUN_NUMBER IN (17,18,19)
ORDER BY N.RUN_NUMBER;

DROP TABLE DQ_CLEANUP_TARGET;
