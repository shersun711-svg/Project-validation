/* READ ONLY. February/May 2019: MV_PCKG_AVG_PAY_TO_BAL_L6M_RT.
Run the entire SELECT once. Original jump limits are captured from account run 20.
Expected PAY_BAL_JUMPS: Feb 9196, May 12950 on the same source version.
WITH_ALL_FOUR_MISSING: four original fields valid-to-missing on the same account.
WITH_BALANCE_ZERO_PATTERN: those four transitions + original balance jump to zero.
WITH_SIX_FIELD_PATTERN: the five-field pattern + repayment/income valid-to--999993.
Prior pattern sizes: five-field Feb 8403 / May 12023; six-field Feb 8260 / May 12010.
This tests intersection with payment/balance jumps, not equality of all cohorts.
All columns count subsets of PAY_BAL_JUMPS; they overlap and must not be added.
Numeric zero remains valid; missing/special ratios are excluded. Previous zero
uses absolute jump limit only. NULL counts mean failed controls, not a pass.
Full populations and matched consecutive months; no individual records exported.
Current missing package IDs establish association, not causation or new missingness.
No source, configuration, saved results or permanent objects are changed.
*/
WITH reference_runs AS
(
 SELECT DISTINCT RUN_ID,FIELD_TYPE FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND
 ((RUN_NUMBER=19 AND FIELD_TYPE='CATEGORICAL') OR
  (RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'))
), reference_control AS
(
 SELECT SUM(CASE WHEN FIELD_TYPE='CATEGORICAL' THEN 1 ELSE 0 END) AS CAT_RUNS,
        SUM(CASE WHEN FIELD_TYPE='NUMERIC' THEN 1 ELSE 0 END) AS NUM_RUNS
 FROM reference_runs
), cat_special AS
(
 SELECT DISTINCT UPPER(TRIM(V.SPECIAL_VALUE)) AS SPECIAL_KEY
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON V.RUN_ID=R.RUN_ID AND R.FIELD_TYPE='CATEGORICAL'
 WHERE V.FIELD_TYPE='CATEGORICAL' AND V.SPECIAL_VALUE IS NOT NULL
), num_special AS
(
 SELECT DISTINCT V.NUMERIC_VALUE AS SPECIAL_KEY
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON V.RUN_ID=R.RUN_ID AND R.FIELD_TYPE='NUMERIC'
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), balance_limits AS
(
 SELECT MAX(CAST(ABS_CHANGE_MIN AS FLOAT)) AS A,
        MAX(CAST(REL_CHANGE_MIN AS FLOAT)) AS R,
        COUNT(DISTINCT ABS_CHANGE_MIN) AS ABS_CONFIGS,
        COUNT(DISTINCT REL_CHANGE_MIN) AS REL_CONFIGS,
        SUM(CASE WHEN ABS_CHANGE_MIN IS NULL OR REL_CHANGE_MIN IS NULL THEN 1 ELSE 0 END) AS BAD_CONFIGS
 FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_NAME='PCKG_BALANCE_AMT'
), pay_limits AS
(
 SELECT MAX(CAST(ABS_CHANGE_MIN AS FLOAT)) AS A,
        MAX(CAST(REL_CHANGE_MIN AS FLOAT)) AS R,
        COUNT(DISTINCT ABS_CHANGE_MIN) AS ABS_CONFIGS,
        COUNT(DISTINCT REL_CHANGE_MIN) AS REL_CONFIGS,
        SUM(CASE WHEN ABS_CHANGE_MIN IS NULL OR REL_CHANGE_MIN IS NULL THEN 1 ELSE 0 END) AS BAD_CONFIGS
 FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_NAME='MV_PCKG_AVG_PAY_TO_BAL_L6M_RT'
), source_values AS
(
 SELECT AGMT_ID,CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MONTH_KEY,
 NULLIF(UPPER(TRIM(CAST(EVENT_DESCRIPTION AS VARCHAR(512)))),'') AS EVENT_VALUE,
 NULLIF(UPPER(TRIM(CAST(MV_PROP_POSTCODE_NM AS VARCHAR(512)))),'') AS POSTCODE_VALUE,
 CAST(PCKG_BOVO_VAL_AMT AS FLOAT) AS BOVO_VALUE,
 CAST(PCKG_REPAY_AMT AS FLOAT) AS REPAY_VALUE,
 CAST(PCKG_BALANCE_AMT AS FLOAT) AS BALANCE_VALUE,
 CAST(MV_PCKG_REPAY_TO_INC_RT AS FLOAT) AS REPAY_INCOME_VALUE,
 CAST(MV_PCKG_AVG_PAY_TO_BAL_L6M_RT AS FLOAT) AS PAY_BAL_VALUE,
 NULLIF(TRIM(CAST(PCKG_ID AS VARCHAR(128))),'') AS PACKAGE_ID,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN (DATE '2019-01-31',DATE '2019-02-28',DATE '2019-04-30',DATE '2019-05-31')
), key_control AS
(
 SELECT SUM(CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))='' OR KEY_COUNT<>1 THEN 1 ELSE 0 END) AS BAD_KEYS
 FROM source_values
), flagged AS
(
 SELECT C.POU_DT,C.PACKAGE_ID,C.BALANCE_VALUE,C.REPAY_INCOME_VALUE AS SPECIAL_CODE,
 CASE WHEN P.PAY_BAL_VALUE IS NOT NULL AND C.PAY_BAL_VALUE IS NOT NULL
            AND PB_PREV.SPECIAL_KEY IS NULL AND PB_CUR.SPECIAL_KEY IS NULL
            AND ABS(C.PAY_BAL_VALUE-P.PAY_BAL_VALUE)>=PL.A
            AND (P.PAY_BAL_VALUE=0 OR ABS((C.PAY_BAL_VALUE-P.PAY_BAL_VALUE)/NULLIFZERO(ABS(P.PAY_BAL_VALUE)))>=PL.R)
      THEN 1 ELSE 0 END AS PAY_BAL_JUMP,
 CASE WHEN P.REPAY_INCOME_VALUE IS NOT NULL AND RI_PREV.SPECIAL_KEY IS NULL
            AND RI_CUR.SPECIAL_KEY IS NOT NULL THEN 1 ELSE 0 END AS TO_SPECIAL,
 CASE WHEN P.BALANCE_VALUE IS NOT NULL AND C.BALANCE_VALUE IS NOT NULL
            AND BS1.SPECIAL_KEY IS NULL AND BS2.SPECIAL_KEY IS NULL
            AND ABS(C.BALANCE_VALUE-P.BALANCE_VALUE)>=L.A
            AND (P.BALANCE_VALUE=0 OR ABS((C.BALANCE_VALUE-P.BALANCE_VALUE)/NULLIFZERO(ABS(P.BALANCE_VALUE)))>=L.R)
      THEN 1 ELSE 0 END AS BALANCE_JUMP,
 CASE WHEN P.EVENT_VALUE IS NOT NULL AND CS1.SPECIAL_KEY IS NULL AND C.EVENT_VALUE IS NULL THEN 1 ELSE 0 END AS EVENT_MISSING,
 CASE WHEN P.POSTCODE_VALUE IS NOT NULL AND CS2.SPECIAL_KEY IS NULL AND C.POSTCODE_VALUE IS NULL THEN 1 ELSE 0 END AS POSTCODE_MISSING,
 CASE WHEN P.BOVO_VALUE IS NOT NULL AND NS1.SPECIAL_KEY IS NULL AND C.BOVO_VALUE IS NULL THEN 1 ELSE 0 END AS BOVO_MISSING,
 CASE WHEN P.REPAY_VALUE IS NOT NULL AND NS2.SPECIAL_KEY IS NULL AND C.REPAY_VALUE IS NULL THEN 1 ELSE 0 END AS REPAY_MISSING
 FROM source_values C
 JOIN source_values P ON C.AGMT_ID=P.AGMT_ID AND C.MONTH_KEY=P.MONTH_KEY+1
 LEFT JOIN cat_special CS1 ON P.EVENT_VALUE=CS1.SPECIAL_KEY
 LEFT JOIN cat_special CS2 ON P.POSTCODE_VALUE=CS2.SPECIAL_KEY
 LEFT JOIN num_special NS1 ON P.BOVO_VALUE=NS1.SPECIAL_KEY
 LEFT JOIN num_special NS2 ON P.REPAY_VALUE=NS2.SPECIAL_KEY
 LEFT JOIN num_special BS1 ON P.BALANCE_VALUE=BS1.SPECIAL_KEY
 LEFT JOIN num_special BS2 ON C.BALANCE_VALUE=BS2.SPECIAL_KEY
 LEFT JOIN num_special RI_PREV ON P.REPAY_INCOME_VALUE=RI_PREV.SPECIAL_KEY
 LEFT JOIN num_special RI_CUR ON C.REPAY_INCOME_VALUE=RI_CUR.SPECIAL_KEY
 LEFT JOIN num_special PB_PREV ON P.PAY_BAL_VALUE=PB_PREV.SPECIAL_KEY
 LEFT JOIN num_special PB_CUR ON C.PAY_BAL_VALUE=PB_CUR.SPECIAL_KEY
 CROSS JOIN balance_limits L CROSS JOIN pay_limits PL
 WHERE C.POU_DT IN (DATE '2019-02-28',DATE '2019-05-31')
), overlap_values AS
(
 SELECT F.*,EVENT_MISSING+POSTCODE_MISSING+BOVO_MISSING+REPAY_MISSING AS FIELD_COUNT
 FROM flagged F
), monthly AS
(
 SELECT POU_DT,SUM(PAY_BAL_JUMP) AS PAY_BAL_JUMPS,
 SUM(CASE WHEN PAY_BAL_JUMP=1 AND PACKAGE_ID IS NULL THEN 1 ELSE 0 END) AS WITH_MISSING_PCKG_ID,
 SUM(CASE WHEN PAY_BAL_JUMP=1 AND FIELD_COUNT=4 THEN 1 ELSE 0 END) AS WITH_ALL_FOUR_MISSING,
 SUM(CASE WHEN PAY_BAL_JUMP=1 AND FIELD_COUNT=4 AND BALANCE_JUMP=1 AND BALANCE_VALUE=0 THEN 1 ELSE 0 END) AS WITH_BALANCE_ZERO_PATTERN,
 SUM(CASE WHEN PAY_BAL_JUMP=1 AND FIELD_COUNT=4 AND BALANCE_JUMP=1 AND BALANCE_VALUE=0 AND TO_SPECIAL=1 AND SPECIAL_CODE=-999993 THEN 1 ELSE 0 END) AS WITH_SIX_FIELD_PATTERN
 FROM overlap_values GROUP BY POU_DT
), results AS
(
 SELECT M.*,CASE WHEN COALESCE(K.BAD_KEYS,0)=0 AND R.CAT_RUNS=1 AND R.NUM_RUNS=1
   AND L.ABS_CONFIGS=1 AND L.REL_CONFIGS=1 AND L.BAD_CONFIGS=0 AND L.A>0 AND L.R>=0
   AND PL.ABS_CONFIGS=1 AND PL.REL_CONFIGS=1 AND PL.BAD_CONFIGS=0 AND PL.A>0 AND PL.R>=0
   THEN 1 ELSE 0 END AS CAN_EVALUATE
 FROM monthly M CROSS JOIN key_control K CROSS JOIN reference_control R CROSS JOIN balance_limits L CROSS JOIN pay_limits PL
)
SELECT POU_DT,
 CASE WHEN CAN_EVALUATE=1 THEN PAY_BAL_JUMPS END AS PAY_BAL_JUMPS,
 CASE WHEN CAN_EVALUATE=1 THEN WITH_MISSING_PCKG_ID END AS WITH_MISSING_PCKG_ID,
 CASE WHEN CAN_EVALUATE=1 THEN WITH_ALL_FOUR_MISSING END AS WITH_ALL_FOUR_MISSING,
 CASE WHEN CAN_EVALUATE=1 THEN WITH_BALANCE_ZERO_PATTERN END AS WITH_BALANCE_ZERO_PATTERN,
 CASE WHEN CAN_EVALUATE=1 THEN WITH_SIX_FIELD_PATTERN END AS WITH_SIX_FIELD_PATTERN
FROM results ORDER BY POU_DT;
