/* READ ONLY -- run SELECT 1 and SELECT 2 separately in Teradata SQL Assistant.
Field: MV_PCKG_AVG_PAY_TO_BAL_L6M_RT. Full population, aggregate outputs only.
No permanent writes, run IDs, individual account output or new business thresholds.

1: Check same-account overlap of April and October 2006 jumps at all three settings.
APR_UP_OCT_DOWN is a subset of BOTH_MONTHS (payment numerator direction).
COMPLETE_STABLE_COUNT further requires all 13 consecutive monthly account records,
Oct 2005-Oct 2006, non-NULL payment and payment average, and one unchanged populated
PCKG_THRU_TIME_ID throughout. It is deliberately a subset, not the entire finding.
WINDOW_MATCH_COUNT checks the two rolling-average identities on that subset:
 April average - March average = (April payment - prior October payment)/6;
 October average - September average = (October payment - April payment)/6.
The 0.01 monetary allowance is for stored precision, not a jump threshold.

2: Show monthly payment and six-month average for the SAME complete/stable ORIGINAL
cohort (COMPLETE_STABLE_COUNT in output 1), including failures of the identity check.
Means are account-weighted: packages may appear on several mortgage agreements.
No zero-filling of missing months/inputs. Negative payment amounts are retained.
NULL count outputs signal duplicate account-month records or NULL account IDs;
do not interpret them as a pass. Zero cohort counts mean no eligible cohort.

Reconcile APR_JUMPS/OCT_JUMPS to previous output first:
LOWER 22445/22537; ORIGINAL 13640/13565; HIGHER 7770/6014.
A window match establishes calculation behaviour, not the reason for the payment.
Early collection around the May holiday still needs payment/billing evidence or
CDAO confirmation. No payment-method or billing-date linkage is inferred here.
*/

/* SELECT 1: account overlap and rolling-window identities */
WITH source_values AS
(SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(MV_PCKG_AVG_PAY_TO_BAL_L6M_RT AS FLOAT) AS V,
 CAST(PCKG_CNP_AMT AS FLOAT) AS PAYMENT,
 CAST(PCKG_CNP_AVG_L6M_AMT AS FLOAT) AS NUM,
 NULLIF(TRIM(CAST(PCKG_THRU_TIME_ID AS VARCHAR(128))),'') AS THRU,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KC
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) BETWEEN DATE '2005-10-01' AND DATE '2006-10-31'),
control AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KC<>1 THEN 1 ELSE 0 END) AS BAD FROM source_values),
states AS
(SELECT S.*, CASE WHEN V IS NULL THEN 'MISSING'
 WHEN V IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 'SPECIAL' ELSE 'VALID' END AS ST
 FROM source_values S),
history AS
(SELECT S.*, LAG(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PV,
 LAG(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PS,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PM,
 LAG(NUM) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_NUM
 FROM states S),
seed AS (SELECT COUNT(*) AS N FROM source_values),
scenarios AS
(SELECT CAST('LOWER' AS VARCHAR(16)) AS SCENARIO, CAST(0.5 AS FLOAT) AS A, CAST(0.25 AS FLOAT) AS R FROM seed
 UNION ALL SELECT CAST('ORIGINAL' AS VARCHAR(16)), CAST(1 AS FLOAT), CAST(0.5 AS FLOAT) FROM seed
 UNION ALL SELECT CAST('HIGHER' AS VARCHAR(16)), CAST(2 AS FLOAT), CAST(0.75 AS FLOAT) FROM seed),
flags AS
(SELECT H.*, C.SCENARIO FROM history H CROSS JOIN scenarios C
 WHERE POU_DT IN (DATE '2006-04-30',DATE '2006-10-31')
 AND MK-PM=1 AND PS='VALID' AND ST='VALID'
 AND ABS(V-PV)>=C.A AND (PV=0 OR ABS((V-PV)/NULLIFZERO(ABS(PV)))>=C.R)),
paired AS
(SELECT AGMT_ID, SCENARIO,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN 1 ELSE 0 END) AS APR,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN 1 ELSE 0 END) AS OCT,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' AND NUM>P_NUM THEN 1 ELSE 0 END) AS APR_UP,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' AND NUM<P_NUM THEN 1 ELSE 0 END) AS OCT_DOWN
 FROM flags GROUP BY AGMT_ID,SCENARIO),
windows AS
(SELECT AGMT_ID,
 CASE WHEN COUNT(*)=13 AND COUNT(DISTINCT MK)=13
 AND COUNT(THRU)=13 AND MIN(THRU)=MAX(THRU)
 AND COUNT(PAYMENT)=13 AND COUNT(NUM)=13 THEN 1 ELSE 0 END AS COMPLETE_STABLE,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN NUM END)
 -MAX(CASE WHEN POU_DT=DATE '2006-03-31' THEN NUM END) AS APR_AVG_CHANGE,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN NUM END)
 -MAX(CASE WHEN POU_DT=DATE '2006-09-30' THEN NUM END) AS OCT_AVG_CHANGE,
 (MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN PAYMENT END)
 -MAX(CASE WHEN POU_DT=DATE '2005-10-31' THEN PAYMENT END))/CAST(6 AS FLOAT) AS APR_EXPECTED,
 (MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN PAYMENT END)
 -MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN PAYMENT END))/CAST(6 AS FLOAT) AS OCT_EXPECTED
 FROM source_values GROUP BY AGMT_ID)
SELECT C.SCENARIO,
 CASE WHEN MAX(K.BAD)=0 THEN COALESCE(SUM(P.APR),0) END AS APR_JUMPS,
 CASE WHEN MAX(K.BAD)=0 THEN COALESCE(SUM(P.OCT),0) END AS OCT_JUMPS,
 CASE WHEN MAX(K.BAD)=0 THEN SUM(CASE WHEN P.APR=1 AND P.OCT=1 THEN 1 ELSE 0 END) END AS BOTH_MONTHS,
 CASE WHEN MAX(K.BAD)=0 THEN SUM(CASE WHEN P.APR_UP=1 AND P.OCT_DOWN=1 THEN 1 ELSE 0 END) END AS APR_UP_OCT_DOWN,
 CASE WHEN MAX(K.BAD)=0 THEN SUM(CASE WHEN P.APR_UP=1 AND P.OCT_DOWN=1 AND W.COMPLETE_STABLE=1 THEN 1 ELSE 0 END) END AS COMPLETE_STABLE_COUNT,
 CASE WHEN MAX(K.BAD)=0 THEN SUM(CASE WHEN P.APR_UP=1 AND P.OCT_DOWN=1 AND W.COMPLETE_STABLE=1
 AND ABS(W.APR_AVG_CHANGE-W.APR_EXPECTED)<=0.01
 AND ABS(W.OCT_AVG_CHANGE-W.OCT_EXPECTED)<=0.01 THEN 1 ELSE 0 END) END AS WINDOW_MATCH_COUNT
FROM scenarios C CROSS JOIN control K
LEFT JOIN paired P ON C.SCENARIO=P.SCENARIO
LEFT JOIN windows W ON P.AGMT_ID=W.AGMT_ID
GROUP BY C.SCENARIO ORDER BY C.SCENARIO;

/* SELECT 2: monthly payment profile for the fixed ORIGINAL cohort */
WITH source_values AS
(SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(MV_PCKG_AVG_PAY_TO_BAL_L6M_RT AS FLOAT) AS V,
 CAST(PCKG_CNP_AMT AS FLOAT) AS PAYMENT,
 CAST(PCKG_CNP_AVG_L6M_AMT AS FLOAT) AS NUM,
 NULLIF(TRIM(CAST(PCKG_THRU_TIME_ID AS VARCHAR(128))),'') AS THRU,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KC
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) BETWEEN DATE '2005-10-01' AND DATE '2006-10-31'),
control AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KC<>1 THEN 1 ELSE 0 END) AS BAD FROM source_values),
states AS
(SELECT S.*, CASE WHEN V IS NULL THEN 'MISSING'
 WHEN V IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 'SPECIAL' ELSE 'VALID' END AS ST
 FROM source_values S),
history AS
(SELECT S.*, LAG(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PV,
 LAG(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PS,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PM,
 LAG(NUM) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_NUM
 FROM states S),
seed AS (SELECT COUNT(*) AS N FROM source_values),
scenarios AS
(SELECT CAST('LOWER' AS VARCHAR(16)) AS SCENARIO, CAST(0.5 AS FLOAT) AS A, CAST(0.25 AS FLOAT) AS R FROM seed
 UNION ALL SELECT CAST('ORIGINAL' AS VARCHAR(16)), CAST(1 AS FLOAT), CAST(0.5 AS FLOAT) FROM seed
 UNION ALL SELECT CAST('HIGHER' AS VARCHAR(16)), CAST(2 AS FLOAT), CAST(0.75 AS FLOAT) FROM seed),
flags AS
(SELECT H.*, C.SCENARIO FROM history H CROSS JOIN scenarios C
 WHERE POU_DT IN (DATE '2006-04-30',DATE '2006-10-31')
 AND MK-PM=1 AND PS='VALID' AND ST='VALID'
 AND ABS(V-PV)>=C.A AND (PV=0 OR ABS((V-PV)/NULLIFZERO(ABS(PV)))>=C.R)),
paired AS
(SELECT AGMT_ID, SCENARIO,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN 1 ELSE 0 END) AS APR,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN 1 ELSE 0 END) AS OCT,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' AND NUM>P_NUM THEN 1 ELSE 0 END) AS APR_UP,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' AND NUM<P_NUM THEN 1 ELSE 0 END) AS OCT_DOWN
 FROM flags GROUP BY AGMT_ID,SCENARIO),
windows AS
(SELECT AGMT_ID,
 CASE WHEN COUNT(*)=13 AND COUNT(DISTINCT MK)=13
 AND COUNT(THRU)=13 AND MIN(THRU)=MAX(THRU)
 AND COUNT(PAYMENT)=13 AND COUNT(NUM)=13 THEN 1 ELSE 0 END AS COMPLETE_STABLE,
 MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN NUM END)
 -MAX(CASE WHEN POU_DT=DATE '2006-03-31' THEN NUM END) AS APR_AVG_CHANGE,
 MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN NUM END)
 -MAX(CASE WHEN POU_DT=DATE '2006-09-30' THEN NUM END) AS OCT_AVG_CHANGE,
 (MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN PAYMENT END)
 -MAX(CASE WHEN POU_DT=DATE '2005-10-31' THEN PAYMENT END))/CAST(6 AS FLOAT) AS APR_EXPECTED,
 (MAX(CASE WHEN POU_DT=DATE '2006-10-31' THEN PAYMENT END)
 -MAX(CASE WHEN POU_DT=DATE '2006-04-30' THEN PAYMENT END))/CAST(6 AS FLOAT) AS OCT_EXPECTED
 FROM source_values GROUP BY AGMT_ID)
, cohort AS
(SELECT P.AGMT_ID FROM paired P JOIN windows W ON P.AGMT_ID=W.AGMT_ID
 WHERE P.SCENARIO='ORIGINAL' AND P.APR_UP=1 AND P.OCT_DOWN=1 AND W.COMPLETE_STABLE=1),
months AS (SELECT DISTINCT POU_DT FROM source_values)
SELECT M.POU_DT,
 CASE WHEN MAX(K.BAD)=0 THEN COUNT(C.AGMT_ID) END AS ACCOUNT_COUNT,
 CASE WHEN MAX(K.BAD)=0 THEN AVG(CASE WHEN C.AGMT_ID IS NOT NULL THEN S.PAYMENT END) END AS AVG_MONTH_PAYMENT,
 CASE WHEN MAX(K.BAD)=0 THEN AVG(CASE WHEN C.AGMT_ID IS NOT NULL THEN S.NUM END) END AS AVG_SIX_MONTH_PAYMENT
FROM months M CROSS JOIN control K
LEFT JOIN source_values S ON M.POU_DT=S.POU_DT
LEFT JOIN cohort C ON S.AGMT_ID=C.AGMT_ID
GROUP BY M.POU_DT ORDER BY M.POU_DT;
