/* READ ONLY -- Teradata SQL Assistant; run as one query.
Field: CUST_ALL_MT_MAX_DELINQ_BASE_RT, February 2019.
HIGHER jump thresholds: absolute change >=2 AND relative change >=0.75;
if January is zero, only the absolute gate applies. Both values must be valid.
These are ratio units, not percentage points. No reversion filter is applied.

Purpose: distinguish drops to zero from decreases and increases BEFORE deciding
whether the February concentration needs a CDAO question.

Expected TOTAL on the same source: 4,489 jumps, of which 4,297 have no March record.
For every movement row:
 JUMP_COUNT = NO_MARCH_RECORD + MARCH_VALID + MARCH_MISSING_OR_SPECIAL.
NO_MARCH_RECORD means no adjacent March source row, not a March row with NULL ratio.
OTHER_VALID_MOVEMENT retains any flagged movement involving negative valid values.
A zero ratio or absent March row does not by itself prove closure or an error.

Full population; no samples, account IDs in output, permanent writes or run changes.
FLOAT casts precede arithmetic. NULL numeric outputs indicate duplicate account-month
rows or NULL account IDs in the source window; do not interpret those as a pass.
The TOTAL row is zero if there are no eligible jumps on a nonempty clean source.
*/
WITH source_values AS
(SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(CUST_ALL_MT_MAX_DELINQ_BASE_RT AS FLOAT) AS RATIO_VALUE,
 COUNT(*) OVER
 (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN
 (DATE '2019-01-31',DATE '2019-02-28',DATE '2019-03-31')),
states AS
(SELECT S.*, CASE WHEN RATIO_VALUE IS NULL THEN 'MISSING'
 WHEN RATIO_VALUE IN
 (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,
 -999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998)
 THEN 'SPECIAL' ELSE 'VALID' END AS VALUE_STATE
 FROM source_values S),
grain_check AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KEY_COUNT<>1 THEN 1 ELSE 0 END) AS BAD_COUNT
 FROM source_values),
history AS
(SELECT S.*,
 LAG(RATIO_VALUE) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PREV_RATIO,
 LAG(VALUE_STATE) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PREV_STATE,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PREV_MK,
 LEAD(VALUE_STATE) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NEXT_STATE,
 LEAD(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NEXT_MK
 FROM states S),
flagged AS
(SELECT H.*,
 CAST(CASE
 WHEN PREV_RATIO>0 AND RATIO_VALUE=0 THEN 'POSITIVE_TO_ZERO'
 WHEN PREV_RATIO>0 AND RATIO_VALUE>0 AND RATIO_VALUE<PREV_RATIO
 THEN 'POSITIVE_DECREASE'
 WHEN PREV_RATIO=0 AND RATIO_VALUE>0 THEN 'ZERO_TO_POSITIVE'
 WHEN PREV_RATIO>0 AND RATIO_VALUE>PREV_RATIO THEN 'POSITIVE_INCREASE'
 ELSE 'OTHER_VALID_MOVEMENT' END AS VARCHAR(32)) AS MOVEMENT_TYPE,
 CASE WHEN NEXT_MK IS NULL OR NEXT_MK-MK<>1 THEN 1 ELSE 0 END AS NO_NEXT,
 CASE WHEN NEXT_MK-MK=1 AND NEXT_STATE='VALID' THEN 1 ELSE 0 END AS NEXT_VALID,
 CASE WHEN NEXT_MK-MK=1 AND NEXT_STATE IN ('MISSING','SPECIAL')
 THEN 1 ELSE 0 END AS NEXT_INVALID
 FROM history H
 WHERE POU_DT=DATE '2019-02-28' AND MK-PREV_MK=1
 AND PREV_STATE='VALID' AND VALUE_STATE='VALID'
 AND ABS(RATIO_VALUE-PREV_RATIO)>=CAST(2 AS FLOAT)
 AND (PREV_RATIO=0 OR
 ABS((RATIO_VALUE-PREV_RATIO)/NULLIFZERO(ABS(PREV_RATIO)))>=CAST(0.75 AS FLOAT))),
summary_rows AS
(SELECT 1 AS SORT_NO, F.MOVEMENT_TYPE,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN COUNT(*) END AS JUMP_COUNT,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN SUM(F.NO_NEXT) END AS NO_MARCH_RECORD,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN SUM(F.NEXT_VALID) END AS MARCH_VALID,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN SUM(F.NEXT_INVALID) END AS MARCH_MISSING_OR_SPECIAL
 FROM flagged F CROSS JOIN grain_check G GROUP BY F.MOVEMENT_TYPE
 UNION ALL
 SELECT 2 AS SORT_NO, CAST('TOTAL' AS VARCHAR(32)) AS MOVEMENT_TYPE,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN COUNT(F.AGMT_ID) END AS JUMP_COUNT,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN COALESCE(SUM(F.NO_NEXT),0) END AS NO_MARCH_RECORD,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN COALESCE(SUM(F.NEXT_VALID),0) END AS MARCH_VALID,
 CASE WHEN MAX(G.BAD_COUNT)=0 THEN COALESCE(SUM(F.NEXT_INVALID),0) END AS MARCH_MISSING_OR_SPECIAL
 FROM grain_check G LEFT JOIN flagged F ON 1=1)
SELECT DATE '2019-02-28' AS POU_DT, MOVEMENT_TYPE, JUMP_COUNT,
 NO_MARCH_RECORD, MARCH_VALID, MARCH_MISSING_OR_SPECIAL
FROM summary_rows ORDER BY SORT_NO,MOVEMENT_TYPE;
