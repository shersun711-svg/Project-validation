/* This classifies the customer maximum. It cannot identify the winning related loan or prove its denominator. Related-account mapping is still required. */
WITH source_values AS
(SELECT AGMT_ID,CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(CUST_ALL_MT_MAX_DELINQ_BASE_RT AS FLOAT) AS V,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KC
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT WHERE CAST(FACT_DT AS DATE) IN (DATE '2008-10-31',DATE '2008-11-30',DATE '2008-12-31',DATE '2013-11-30',DATE '2013-12-31',DATE '2014-01-31',DATE '2019-01-31',DATE '2019-02-28',DATE '2019-03-31')),
 states AS
(SELECT S.*,CASE WHEN V IS NULL THEN 'MISSING' WHEN V IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 'SPECIAL' ELSE 'VALID' END AS ST FROM source_values S),
 control AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KC<>1 THEN 1 ELSE 0 END) AS BAD FROM states),
 history AS
(SELECT S.*,LAG(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PV,
 LEAD(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NV,
 LAG(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PS,
 LEAD(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NS,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PM,
 LEAD(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NM
 FROM states S),
 seed AS (SELECT COUNT(*) AS N FROM states)
, scenarios AS
(SELECT CAST('ORIGINAL' AS VARCHAR(16)) AS SCENARIO,CAST(1 AS FLOAT) AS A,CAST(0.5 AS FLOAT) AS R,CAST(0.1 AS FLOAT) AS RA,CAST(0.05 AS FLOAT) AS RR FROM seed
 UNION ALL SELECT CAST('HIGHER_TIGHTER' AS VARCHAR(16)),CAST(2 AS FLOAT),CAST(0.75 AS FLOAT),CAST(0.05 AS FLOAT),CAST(0.025 AS FLOAT) FROM seed),
f AS (SELECT H.*,C.SCENARIO,
 CASE WHEN MK-PM=1 AND PS='VALID' AND ST='VALID' AND ABS(V-PV)>=C.A AND (PV=0 OR ABS((V-PV)/NULLIFZERO(ABS(PV)))>=C.R) THEN 1 ELSE 0 END AS J,
 CASE WHEN NM-MK=1 AND NS='VALID' AND ((V>PV AND NV<V) OR (V<PV AND NV>V)) AND ABS(NV-PV)<=GREATEST(C.RA,ABS(PV)*C.RR) THEN 1 ELSE 0 END AS RETURN_FLAG
 FROM history H CROSS JOIN scenarios C WHERE POU_DT IN (DATE '2008-11-30',DATE '2013-12-31',DATE '2019-02-28')),
classified AS (SELECT F.*,CASE WHEN PV=0 AND V>0 AND NM-MK=1 AND NS='VALID' AND NV=0 THEN 'ZERO_POSITIVE_ZERO'
 WHEN PV>0 AND V=0 AND RETURN_FLAG=1 THEN 'POSITIVE_ZERO_RETURN'
 WHEN PV>0 AND V>PV AND RETURN_FLAG=1 THEN 'POSITIVE_UP_RETURN'
 WHEN PV>0 AND V<PV AND RETURN_FLAG=1 THEN 'POSITIVE_DOWN_RETURN'
 WHEN NM IS NULL OR NM-MK<>1 THEN 'NO_ADJACENT_NEXT'
 WHEN NS<>'VALID' THEN 'NEXT_MISSING_OR_SPECIAL'
 ELSE 'OTHER_JUMP' END AS PATTERN FROM f F WHERE J=1)
SELECT POU_DT,SCENARIO,PATTERN,
 CASE WHEN MAX(BAD)=0 THEN COUNT(*) END AS JUMP_COUNT,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN RETURN_FLAG=1 THEN 1 ELSE 0 END) END AS REVERSION_COUNT,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN RETURN_FLAG=1 AND NV=PV THEN 1 ELSE 0 END) END AS EXACT_RETURN_COUNT
FROM classified CROSS JOIN control GROUP BY POU_DT,SCENARIO,PATTERN ORDER BY POU_DT,SCENARIO,PATTERN;
