/* Customer-related six-month credit measure. This classifies movements but cannot prove collection timing or recompute the related-account aggregation without the upstream relationship/transaction mapping. Exact return is diagnostic, not the tolerance-based reversion count. */
WITH source_values AS
(SELECT AGMT_ID,CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(CUST_ALL_C_PYMTS_CR_AVG_L6M_AMT AS FLOAT) AS V,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KC
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT WHERE CAST(FACT_DT AS DATE) IN (DATE '2005-12-31',DATE '2006-01-31',DATE '2006-02-28',DATE '2006-03-31',DATE '2006-04-30',DATE '2007-04-30',DATE '2007-05-31',DATE '2007-06-30',DATE '2009-04-30',DATE '2009-05-31',DATE '2009-06-30')),
 states AS
(SELECT S.*,CASE WHEN V IS NULL THEN 'MISSING' WHEN V IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 'SPECIAL' ELSE 'VALID' END AS ST FROM source_values S),
 control AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KC<>1 THEN 1 ELSE 0 END) AS BAD FROM states),
 history AS
(SELECT S.*,LAG(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PV,
 LEAD(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NV,
 LAG(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PS,
 LEAD(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NS,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PM,
 LEAD(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NM
 FROM states S),
 seed AS (SELECT COUNT(*) AS N FROM states)
, scenarios AS (SELECT CAST('LOWER' AS VARCHAR(16)) AS SCENARIO,CAST(500 AS FLOAT) AS A,CAST(0.25 AS FLOAT) AS R FROM seed
 UNION ALL SELECT CAST('ORIGINAL' AS VARCHAR(16)),CAST(1000 AS FLOAT),CAST(0.5 AS FLOAT) FROM seed
 UNION ALL SELECT CAST('HIGHER' AS VARCHAR(16)),CAST(2000 AS FLOAT),CAST(0.75 AS FLOAT) FROM seed),
f AS (SELECT H.*,C.SCENARIO,CASE WHEN PV=0 THEN 'ZERO_START' WHEN V>PV THEN 'INCREASE_NONZERO' ELSE 'DECREASE_NONZERO' END AS PATTERN
 FROM history H CROSS JOIN scenarios C WHERE POU_DT IN (DATE '2006-01-31',DATE '2006-02-28',DATE '2006-03-31',DATE '2007-05-31',DATE '2009-05-31') AND MK-PM=1 AND PS='VALID' AND ST='VALID'
 AND ABS(V-PV)>=C.A AND (PV=0 OR ABS((V-PV)/NULLIFZERO(ABS(PV)))>=C.R))
SELECT POU_DT,SCENARIO,PATTERN,
 CASE WHEN MAX(BAD)=0 THEN COUNT(*) END AS JUMP_COUNT,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN NM-MK=1 AND NS='VALID' AND NV=PV THEN 1 ELSE 0 END) END AS EXACT_NEXT_RETURN,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN NM IS NULL OR NM-MK<>1 THEN 1 ELSE 0 END) END AS NO_ADJACENT_NEXT,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN NM-MK=1 AND NS<>'VALID' THEN 1 ELSE 0 END) END AS NEXT_INVALID
FROM f CROSS JOIN control GROUP BY POU_DT,SCENARIO,PATTERN ORDER BY POU_DT,SCENARIO,PATTERN;
