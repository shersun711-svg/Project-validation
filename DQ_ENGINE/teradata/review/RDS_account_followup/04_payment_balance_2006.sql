/* Input movement counts overlap. The quotient uses x100; matched arithmetic does not validate source input semantics. */
WITH source_values AS
(SELECT AGMT_ID,CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MK,
 CAST(MV_PCKG_AVG_PAY_TO_BAL_L6M_RT AS FLOAT) AS V,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KC,
 CAST(PCKG_CNP_AVG_L6M_AMT AS FLOAT) AS NUM,
 CAST(PCKG_AVG_BAL_L6M_LAG1_AMT AS FLOAT) AS DEN,
 NULLIF(TRIM(CAST(PCKG_ID AS VARCHAR(128))),'') AS PKG,
 NULLIF(TRIM(CAST(PCKG_THRU_TIME_ID AS VARCHAR(128))),'') AS THRU
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT WHERE CAST(FACT_DT AS DATE) IN (DATE '2006-03-31',DATE '2006-04-30',DATE '2006-05-31',DATE '2006-09-30',DATE '2006-10-31',DATE '2006-11-30')),
 states AS
(SELECT S.*,CASE WHEN V IS NULL THEN 'MISSING' WHEN V IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 'SPECIAL' ELSE 'VALID' END AS ST FROM source_values S),
 control AS
(SELECT SUM(CASE WHEN AGMT_ID IS NULL OR KC<>1 THEN 1 ELSE 0 END) AS BAD FROM states),
 history AS
(SELECT S.*,LAG(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PV,
 LEAD(V) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NV,
 LAG(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PS,
 LEAD(ST) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NS,
 LAG(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS PM,
 LEAD(MK) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS NM,
 LAG(NUM) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_NUM,
 LAG(DEN) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_DEN,
 LAG(PKG) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_PKG,
 LAG(THRU) OVER (PARTITION BY AGMT_ID ORDER BY MK) AS P_THRU
 FROM states S),
 seed AS (SELECT COUNT(*) AS N FROM states)
, scenarios AS
(SELECT CAST('LOWER' AS VARCHAR(16)) AS SCENARIO,CAST(0.5 AS FLOAT) AS A,CAST(0.25 AS FLOAT) AS R FROM seed
 UNION ALL SELECT CAST('ORIGINAL' AS VARCHAR(16)),CAST(1 AS FLOAT),CAST(0.5 AS FLOAT) FROM seed
 UNION ALL SELECT CAST('HIGHER' AS VARCHAR(16)),CAST(2 AS FLOAT),CAST(0.75 AS FLOAT) FROM seed),
f AS (SELECT H.*,C.SCENARIO FROM history H CROSS JOIN scenarios C
 WHERE POU_DT IN (DATE '2006-04-30',DATE '2006-10-31') AND MK-PM=1 AND PS='VALID' AND ST='VALID'
 AND ABS(V-PV)>=C.A AND (PV=0 OR ABS((V-PV)/NULLIFZERO(ABS(PV)))>=C.R))
SELECT POU_DT,SCENARIO,
 CASE WHEN MAX(BAD)=0 THEN COUNT(*) END AS JUMP_COUNT,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN NUM>P_NUM THEN 1 ELSE 0 END) END AS NUM_INCREASE,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN NUM<P_NUM THEN 1 ELSE 0 END) END AS NUM_DECREASE,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN DEN>P_DEN THEN 1 ELSE 0 END) END AS DEN_INCREASE,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN DEN<P_DEN THEN 1 ELSE 0 END) END AS DEN_DECREASE,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN DEN>0 AND DEN<=10 THEN 1 ELSE 0 END) END AS DEN_LE_10,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN PV=0 THEN 1 ELSE 0 END) END AS ZERO_START,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN PKG IS NULL THEN 1 ELSE 0 END) END AS CURRENT_PKG_MISSING,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN PKG<>P_PKG THEN 1 ELSE 0 END) END AS POPULATED_PKG_CHANGED,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN THRU<>P_THRU THEN 1 ELSE 0 END) END AS POPULATED_THRU_CHANGED,
 CASE WHEN MAX(BAD)=0 THEN SUM(CASE WHEN DEN IS NULL OR DEN<=0 THEN 1 WHEN NUM<0 OR NUM/NULLIFZERO(DEN)>10 THEN 1 WHEN ABS(V-100*COALESCE(NUM,CAST(0 AS FLOAT))/NULLIFZERO(DEN))>GREATEST(CAST(0.000101 AS FLOAT),ABS(V)*CAST(0.000000001 AS FLOAT)) THEN 1 ELSE 0 END) END AS INPUT_NOT_RECONCILED
FROM f CROSS JOIN control GROUP BY POU_DT,SCENARIO ORDER BY POU_DT,SCENARIO;
