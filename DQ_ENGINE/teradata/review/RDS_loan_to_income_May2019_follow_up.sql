 SELECT E.*,
        CASE WHEN VALID_PAIR=1 AND ABS(CHANGE_RATIO)>=CAST(1 AS FLOAT)
                   AND (PREVIOUS_RATIO=0 OR ABS(RELATIVE_CHANGE)>=CAST(0.5 AS FLOAT))
             THEN 1 ELSE 0 END AS ORIGINAL_JUMP,
        CASE WHEN VALID_PAIR=1 AND ABS(CHANGE_RATIO)>=CAST(2 AS FLOAT)
                   AND (PREVIOUS_RATIO=0 OR ABS(RELATIVE_CHANGE)>=CAST(0.75 AS FLOAT))
             THEN 1 ELSE 0 END AS HIGHER_JUMP,
        CASE WHEN CHANGE_RATIO>0 THEN 'INCREASE' ELSE 'DECREASE' END AS DIRECTION
 FROM comparisons E
)
 , ranked AS
(
 SELECT F.*,
        ROW_NUMBER() OVER (PARTITION BY MONTH_KEY,DIRECTION ORDER BY ABS(CHANGE_RATIO),AGMT_ID) AS RANK_IN_DIRECTION,
        COUNT(*) OVER (PARTITION BY MONTH_KEY,DIRECTION) AS DIRECTION_COUNT
 FROM flags F WHERE ORIGINAL_JUMP=1
), bucketed AS
(
 SELECT R.*,CAST(FLOOR((CAST(RANK_IN_DIRECTION-1 AS FLOAT)*5)/DIRECTION_COUNT)+1 AS INTEGER) AS VALUE_GROUP
 FROM ranked R
), positioned AS
(
 SELECT B.*,MIN(RANK_IN_DIRECTION) OVER (PARTITION BY MONTH_KEY,DIRECTION,VALUE_GROUP) AS GROUP_FIRST,
        COUNT(*) OVER (PARTITION BY MONTH_KEY,DIRECTION,VALUE_GROUP) AS GROUP_COUNT
 FROM bucketed B
)
SELECT POU_DT,AGMT_ID,DIRECTION,HIGHER_JUMP,
       PREVIOUS_DATE,PREVIOUS_RATIO,RATIO_VALUE AS CURRENT_RATIO,
       CHANGE_RATIO,RELATIVE_CHANGE,
       CASE WHEN NEXT_MONTH=MONTH_KEY+1 AND NEXT_KEY_COUNT=1 THEN NEXT_DATE END AS NEXT_DATE,
       CASE WHEN NEXT_MONTH=MONTH_KEY+1 AND NEXT_KEY_COUNT=1 THEN NEXT_RATIO END AS NEXT_RATIO,
       CASE WHEN NEXT_MONTH=MONTH_KEY+1 AND NEXT_KEY_COUNT=1 THEN NEXT_STATE
            ELSE 'NO_ADJACENT_MONTH' END AS NEXT_STATE,
       PREVIOUS_ORIGINAL_LOAN,ORIGINAL_LOAN AS CURRENT_ORIGINAL_LOAN,
       PREVIOUS_INCOME,INCOME AS CURRENT_INCOME,
       PACKAGE_BALANCE AS CURRENT_PACKAGE_BALANCE,
       PREVIOUS_PACKAGE_ID,PACKAGE_ID AS CURRENT_PACKAGE_ID,PACKAGE_ID_PATTERN,
       PREVIOUS_PACKAGE_TIME_ID,PACKAGE_TIME_ID AS CURRENT_PACKAGE_TIME_ID,PACKAGE_TIME_PATTERN
FROM positioned
WHERE RANK_IN_DIRECTION=GROUP_FIRST+CAST(FLOOR((GROUP_COUNT-1)/2.0) AS INTEGER)
ORDER BY POU_DT,DIRECTION,VALUE_GROUP;
