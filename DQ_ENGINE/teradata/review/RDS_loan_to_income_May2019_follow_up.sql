/* Read-only Teradata SQL: MV_PCKG_LOAN_TO_INC_RT, May 2019 only.
   Run Query 1 and Query 2 separately in SQL Assistant; export both results.
   Uses existing source view and run 20 NUMERIC special snapshot; no SAS,
   permanent tables, configuration edits or new engine runs are required.

   Query 1 should reproduce valid pairs 117841, original jumps 3831,
   higher jumps 465 on the sensitivity source. REQUIRE EVALUATED status.
   Direction, input-change and package diagnostics overlap. They describe
   associations, not established causes; do not sum them as unique events.
   Input-change counts compare non-NULL stored values, without validating
   upstream amounts or treating changes to/from NULL as numeric changes.

   Query 2 returns up to 5 increases and 5 decreases, stratified by absolute
   ratio change (up to 10 examples total). It shows April/May loan numerator,
   top-two-borrower income denominator and package IDs, plus June ratio where
   available. Not a random sample. Keep agreement examples internal.

   Units: ratio is original package loan / selected borrower income, without
   x100. CHANGE_RATIO=1 means one income multiple, not one percentage point.
   Original jump: absolute >=1 AND relative >=50%; higher: >=2 AND >=75%.
   Previous zero uses absolute-only test. Missing/special ratios are excluded;
   next states are labelled and month gaps are not treated as adjacent.
   Source must stay fixed across queries. No reversion verdict is assigned.
*/

/* QUERY 1: monthly controls and input/package summaries. */
WITH reference_runs AS
(
 SELECT DISTINCT RUN_ID FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'
), reference_context AS
(
 SELECT COUNT(*) AS REFERENCE_RUN_COUNT FROM reference_runs
), special_values AS
(
 SELECT DISTINCT V.NUMERIC_VALUE
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON V.RUN_ID=R.RUN_ID
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), source_values AS
(
 SELECT S.AGMT_ID,CAST(S.FACT_DT AS DATE) AS POU_DT,
        EXTRACT(YEAR FROM S.FACT_DT)*12+EXTRACT(MONTH FROM S.FACT_DT) AS MONTH_KEY,
        CAST(S.MV_PCKG_LOAN_TO_INC_RT AS FLOAT) AS RATIO_VALUE,
        CAST(S.PCKG_ORIG_LOAN_EXCL_WHSE_AMT AS FLOAT) AS ORIGINAL_LOAN,
        CAST(S.PCKG_BORR_TOP2_TOTAL_INC_AMT AS FLOAT) AS INCOME,
        CAST(S.PCKG_BALANCE_AMT AS FLOAT) AS PACKAGE_BALANCE,
        NULLIF(TRIM(CAST(S.PCKG_ID AS VARCHAR(128))),'') AS PACKAGE_ID,
        NULLIF(TRIM(CAST(S.PCKG_THRU_TIME_ID AS VARCHAR(128))),'') AS PACKAGE_TIME_ID
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT S
 WHERE S.FACT_DT>=DATE '2019-04-01' AND S.FACT_DT<DATE '2019-07-01'
), classified AS
(
 SELECT S.*,C.REFERENCE_RUN_COUNT,
        COUNT(*) OVER (PARTITION BY AGMT_ID,MONTH_KEY) AS KEY_COUNT,
        CASE WHEN RATIO_VALUE IS NULL THEN 'MISSING'
             WHEN REFERENCE_RUN_COUNT<>1 THEN 'UNVERIFIED'
             WHEN V.NUMERIC_VALUE IS NOT NULL THEN 'SPECIAL'
             ELSE 'VALID' END AS RATIO_STATE
 FROM source_values S CROSS JOIN reference_context C
 LEFT JOIN special_values V ON S.RATIO_VALUE=V.NUMERIC_VALUE
), neighbours AS
(
 SELECT C.*,
        SUM(CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))=''
                      OR KEY_COUNT<>1 THEN 1 ELSE 0 END) OVER () AS WINDOW_BAD_KEYS,
        LAG(POU_DT) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_DATE,
        LAG(MONTH_KEY) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_MONTH,
        LAG(KEY_COUNT) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_KEY_COUNT,
        LAG(RATIO_VALUE) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_RATIO,
        LAG(RATIO_STATE) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_STATE,
        LAG(ORIGINAL_LOAN) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_ORIGINAL_LOAN,
        LAG(INCOME) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_INCOME,
        LAG(PACKAGE_ID) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_PACKAGE_ID,
        LAG(PACKAGE_TIME_ID) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS PREVIOUS_PACKAGE_TIME_ID,
        LEAD(POU_DT) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS NEXT_DATE,
        LEAD(MONTH_KEY) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS NEXT_MONTH,
        LEAD(KEY_COUNT) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS NEXT_KEY_COUNT,
        LEAD(RATIO_VALUE) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS NEXT_RATIO,
        LEAD(RATIO_STATE) OVER (PARTITION BY AGMT_ID ORDER BY POU_DT) AS NEXT_STATE
 FROM classified C
), comparisons AS
(
 SELECT N.*,
        CASE WHEN REFERENCE_RUN_COUNT=1 AND WINDOW_BAD_KEYS=0
                   AND MONTH_KEY-PREVIOUS_MONTH=1
                   AND KEY_COUNT=1 AND PREVIOUS_KEY_COUNT=1
                   AND PREVIOUS_STATE='VALID' AND RATIO_STATE='VALID'
             THEN 1 ELSE 0 END AS VALID_PAIR,
        RATIO_VALUE-PREVIOUS_RATIO AS CHANGE_RATIO,
        (RATIO_VALUE-PREVIOUS_RATIO)/NULLIFZERO(ABS(PREVIOUS_RATIO)) AS RELATIVE_CHANGE,
        CASE WHEN PACKAGE_ID IS NULL AND PREVIOUS_PACKAGE_ID IS NULL THEN 'MISSING_BOTH'
             WHEN PACKAGE_ID IS NULL THEN 'BECAME_MISSING'
             WHEN PREVIOUS_PACKAGE_ID IS NULL THEN 'BECAME_POPULATED'
             WHEN PACKAGE_ID=PREVIOUS_PACKAGE_ID THEN 'UNCHANGED'
             ELSE 'CHANGED' END AS PACKAGE_ID_PATTERN,
        CASE WHEN PACKAGE_TIME_ID IS NULL AND PREVIOUS_PACKAGE_TIME_ID IS NULL THEN 'MISSING_BOTH'
             WHEN PACKAGE_TIME_ID IS NULL THEN 'BECAME_MISSING'
             WHEN PREVIOUS_PACKAGE_TIME_ID IS NULL THEN 'BECAME_POPULATED'
             WHEN PACKAGE_TIME_ID=PREVIOUS_PACKAGE_TIME_ID THEN 'UNCHANGED'
             ELSE 'CHANGED' END AS PACKAGE_TIME_PATTERN
 FROM neighbours N
 WHERE POU_DT>=DATE '2019-05-01' AND POU_DT<DATE '2019-06-01'
), flags AS
(
 SELECT E.*,
        CASE WHEN VALID_PAIR=1 AND ABS(CHANGE_RATIO)>=CAST(1 AS FLOAT)
                   AND (PREVIOUS_RATIO=0 OR ABS(RELATIVE_CHANGE)>=CAST(0.5 AS FLOAT))
             THEN 1 ELSE 0 END AS ORIGINAL_JUMP,
        CASE WHEN VALID_PAIR=1 AND ABS(CHANGE_RATIO)>=CAST(2 AS FLOAT)
                   AND (PREVIOUS_RATIO=0 OR ABS(RELATIVE_CHANGE)>=CAST(0.75 AS FLOAT))
             THEN 1 ELSE 0 END AS HIGHER_JUMP,
        CASE WHEN CHANGE_RATIO>0 THEN 'INCREASE' ELSE 'DECREASE' END AS DIRECTION
 FROM comparisons E
)
 , monthly_summary AS
(
SELECT MAX(POU_DT) AS POU_DT,
       CASE WHEN MAX(REFERENCE_RUN_COUNT)<>1 THEN 'CHECK_SPECIAL_REFERENCE'
            WHEN MAX(WINDOW_BAD_KEYS)>0 THEN 'CHECK_SOURCE_GRAIN'
            ELSE 'EVALUATED' END AS REVIEW_STATUS,
       COUNT(*) AS TOTAL_COUNT,SUM(VALID_PAIR) AS VALID_PAIR_COUNT,
       CASE WHEN MAX(REFERENCE_RUN_COUNT)=1 AND MAX(WINDOW_BAD_KEYS)=0
            THEN SUM(ORIGINAL_JUMP) END AS ORIGINAL_JUMP_COUNT,
       CASE WHEN MAX(REFERENCE_RUN_COUNT)=1 AND MAX(WINDOW_BAD_KEYS)=0
            THEN SUM(HIGHER_JUMP) END AS HIGHER_JUMP_COUNT,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND CHANGE_RATIO>0 THEN 1 ELSE 0 END) AS INCREASE_COUNT,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND CHANGE_RATIO<0 THEN 1 ELSE 0 END) AS DECREASE_COUNT,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND PREVIOUS_RATIO=0 THEN 1 ELSE 0 END) AS ZERO_START_COUNT,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND ORIGINAL_LOAN<>PREVIOUS_ORIGINAL_LOAN
                THEN 1 ELSE 0 END) AS LOAN_AMOUNT_CHANGED,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND INCOME<>PREVIOUS_INCOME
                THEN 1 ELSE 0 END) AS INCOME_CHANGED,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND PACKAGE_ID IS NULL THEN 1 ELSE 0 END) AS CURRENT_PACKAGE_ID_MISSING,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND PACKAGE_ID_PATTERN='BECAME_MISSING'
                THEN 1 ELSE 0 END) AS PACKAGE_ID_BECAME_MISSING,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND PACKAGE_ID_PATTERN='CHANGED'
                THEN 1 ELSE 0 END) AS PACKAGE_ID_CHANGED,
       SUM(CASE WHEN ORIGINAL_JUMP=1 AND PACKAGE_TIME_PATTERN='CHANGED'
                THEN 1 ELSE 0 END) AS PACKAGE_TIME_ID_CHANGED
FROM flags GROUP BY MONTH_KEY
)
SELECT * FROM monthly_summary ORDER BY 1;

