/* Query 2, READ ONLY: population tail concentration of customer maximum delinquency.
This DOES NOT test the originating denominator: this field is a maximum over
related mortgage/term accounts, not necessarily this AGMT_ID's delinquency.
Upstream relationship mapping and winning related-account inputs are required
before linking these results to Issue 5. Top 1% is a diagnostic cohort only.
Full source populations for spike/adjacent months; no customer details output.
Absolute-value ranking avoids cancellation from negative values. Ties are split
by AGMT_ID; the top cohort is CEILING(valid_count * 0.01) records.
*/
WITH source_values AS
(
 SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
 CAST(CUST_ALL_MT_MAX_DELINQ_BASE_RT AS FLOAT) AS RATIO_VALUE,
 COUNT(*) OVER (PARTITION BY AGMT_ID, EXTRACT(YEAR FROM FACT_DT), EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN (DATE '2018-06-30',DATE '2018-07-31',DATE '2018-08-31',DATE '2020-07-31',DATE '2020-08-31',DATE '2020-09-30')
), controls AS
(
 SELECT POU_DT, SUM(CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))='' OR KEY_COUNT<>1 THEN 1 ELSE 0 END) AS BAD_KEYS
 FROM source_values GROUP BY POU_DT
), ranked AS
(
 SELECT S.*,
 ROW_NUMBER() OVER (PARTITION BY POU_DT ORDER BY ABS(RATIO_VALUE) DESC, AGMT_ID) AS TAIL_RANK,
 COUNT(*) OVER (PARTITION BY POU_DT) AS VALID_COUNT
 FROM source_values S
 WHERE RATIO_VALUE IS NOT NULL AND RATIO_VALUE NOT IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998)
), summary_values AS
(
 SELECT POU_DT, MAX(VALID_COUNT) AS VALID_COUNT, AVG(RATIO_VALUE) AS MEAN_ALL,
 SUM(CASE WHEN TAIL_RANK<=CEILING(VALID_COUNT*CAST(0.01 AS FLOAT)) THEN 1 ELSE 0 END) AS TOP_1PCT_COUNT,
 SUM(CASE WHEN TAIL_RANK<=CEILING(VALID_COUNT*CAST(0.01 AS FLOAT)) THEN ABS(RATIO_VALUE) ELSE CAST(0 AS FLOAT) END)/NULLIFZERO(SUM(ABS(RATIO_VALUE))) AS TOP_1PCT_ABS_CONTRIB,
 AVG(CASE WHEN TAIL_RANK>CEILING(VALID_COUNT*CAST(0.01 AS FLOAT)) THEN RATIO_VALUE END) AS MEAN_WITHOUT_TOP_1PCT
 FROM ranked GROUP BY POU_DT
)
SELECT C.POU_DT,
 CASE WHEN C.BAD_KEYS>0 THEN 'CHECK_SOURCE_GRAIN' WHEN S.VALID_COUNT IS NULL THEN 'NO_VALID_RATIOS' ELSE 'TAIL_CHECK_ONLY' END AS REVIEW_STATUS,
 CASE WHEN C.BAD_KEYS=0 THEN S.VALID_COUNT END AS VALID_COUNT,
 CASE WHEN C.BAD_KEYS=0 THEN S.MEAN_ALL END AS MEAN_ALL,
 CASE WHEN C.BAD_KEYS=0 THEN S.TOP_1PCT_COUNT END AS TOP_1PCT_COUNT,
 CASE WHEN C.BAD_KEYS=0 THEN S.TOP_1PCT_ABS_CONTRIB END AS TOP_1PCT_ABS_CONTRIB,
 CASE WHEN C.BAD_KEYS=0 THEN S.MEAN_WITHOUT_TOP_1PCT END AS MEAN_WITHOUT_TOP_1PCT
FROM controls C LEFT JOIN summary_values S ON C.POU_DT=S.POU_DT
ORDER BY C.POU_DT;
