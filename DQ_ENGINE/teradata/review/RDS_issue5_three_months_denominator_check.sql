/* READ ONLY Teradata SQL Assistant. Run the entire SELECT once.
Five ratios x three separate elevated/spike months x cutoffs 10, 100, 500 = 45 rows.
No adjacent-month controls or account samples in this focused result.
High-level LTI months are examples of elevated levels, not necessarily spike onsets.
Both savings/balance ratios use 100*savings/balance. Other ratios do not use x100.
Income is ANNUAL for loan/income, MONTHLY (annual/12) for repayment/income.
Cutoffs refer to actual denominator amounts in source currency and are cumulative
(0 < denominator <= cutoff); do not sum across cutoffs or compare unlike units.
These scenarios are not business limits or recommended data exclusions.
Only stored ratios are screened against the confirmed common special list.
Numeric inputs equal to those codes may be genuine amounts, so they are not
rejected automatically. Input validity must be assessed separately.
Formula tolerance: account savings/balance max(0.0051, abs(ratio)*1E-9) for
rounding; others max(1E-6, abs(ratio)*1E-9). FLOAT casts precede arithmetic.
Output has seven columns: FIELD_NAME, POU_DT, DENOM_CUTOFF, VALID_COUNT,
SMALL_DENOM_COUNT, MEAN_ALL, MEAN_WITHOUT_SMALL.
MEAN_WITHOUT_SMALL is diagnostic only; this does not recommend removing records.
Contribution and reconciliation calculations remain internal; the displayed
counts and means describe concentration, not proof that inputs are correct.
Counts are agreement-level observations (packages/customers can be repeated).
Duplicate/null keys suppress numeric outputs as NULL; these are not passed results.
Missing requested months return no rows.
Cutoff UNION branches reference a one-row seed to avoid Teradata error 3888.
Compare MEAN_ALL and VALID_COUNT to saved profiling first; keep source fixed.
Arithmetic reconciliation does not validate underlying amounts or model treatment.
Delinquency is excluded: originating related-account inputs are still required.
No source changes, permanent tables, saved engine results or run IDs are created.
*/
WITH source_values AS
(
SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
       CAST(BALANCE_AMT AS FLOAT) AS BALANCE_AMT,
       CAST(MV_PCKG_LOAN_TO_INC_RT AS FLOAT) AS MV_PCKG_LOAN_TO_INC_RT,
       CAST(MV_PCKG_REPAY_TO_INC_RT AS FLOAT) AS MV_PCKG_REPAY_TO_INC_RT,
       CAST(MV_PCKG_SAV_DEP_TO_BALANCE_RT AS FLOAT) AS MV_PCKG_SAV_DEP_TO_BALANCE_RT,
       CAST(MV_PCKG_SAV_DEP_TO_REPAY_RT AS FLOAT) AS MV_PCKG_SAV_DEP_TO_REPAY_RT,
       CAST(MV_TOT_DEP_SAV_TO_ACC_BAL_RT AS FLOAT) AS MV_TOT_DEP_SAV_TO_ACC_BAL_RT,
       CAST(PCKG_BALANCE_AMT AS FLOAT) AS PCKG_BALANCE_AMT,
       CAST(PCKG_BORR_TOP2_TOTAL_INC_AMT AS FLOAT) AS PCKG_BORR_TOP2_TOTAL_INC_AMT,
       CAST(PCKG_ORIG_LOAN_EXCL_WHSE_AMT AS FLOAT) AS PCKG_ORIG_LOAN_EXCL_WHSE_AMT,
       CAST(PCKG_REPAY_AMT AS FLOAT) AS PCKG_REPAY_AMT,
       CAST(TOTAL_DEPOSIT_SAVINGS_BALANCE AS FLOAT) AS TOTAL_DEPOSIT_SAVINGS_BALANCE,
       COUNT(*) OVER (PARTITION BY AGMT_ID, EXTRACT(YEAR FROM FACT_DT), EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN (DATE '2007-01-31',DATE '2008-05-31',DATE '2008-08-31',DATE '2008-10-31',DATE '2009-12-31',DATE '2010-03-31',DATE '2011-02-28',DATE '2011-09-30',DATE '2011-10-31',DATE '2013-11-30',DATE '2023-06-30',DATE '2024-03-31')
), field_values AS
(
SELECT CAST('MV_TOT_DEP_SAV_TO_ACC_BAL_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_TOT_DEP_SAV_TO_ACC_BAL_RT AS RATIO_VALUE, TOTAL_DEPOSIT_SAVINGS_BALANCE AS NUMERATOR,
       BALANCE_AMT AS RAW_DENOMINATOR, BALANCE_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2011-10-31',DATE '2013-11-30',DATE '2023-06-30')
UNION ALL
SELECT CAST('MV_PCKG_SAV_DEP_TO_BALANCE_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_SAV_DEP_TO_BALANCE_RT AS RATIO_VALUE, TOTAL_DEPOSIT_SAVINGS_BALANCE AS NUMERATOR,
       PCKG_BALANCE_AMT AS RAW_DENOMINATOR, PCKG_BALANCE_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2011-10-31',DATE '2013-11-30',DATE '2023-06-30')
UNION ALL
SELECT CAST('MV_PCKG_LOAN_TO_INC_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_LOAN_TO_INC_RT AS RATIO_VALUE, PCKG_ORIG_LOAN_EXCL_WHSE_AMT AS NUMERATOR,
       PCKG_BORR_TOP2_TOTAL_INC_AMT AS RAW_DENOMINATOR, PCKG_BORR_TOP2_TOTAL_INC_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2007-01-31',DATE '2008-08-31',DATE '2009-12-31')
UNION ALL
SELECT CAST('MV_PCKG_REPAY_TO_INC_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_REPAY_TO_INC_RT AS RATIO_VALUE, PCKG_REPAY_AMT AS NUMERATOR,
       PCKG_BORR_TOP2_TOTAL_INC_AMT AS RAW_DENOMINATOR, PCKG_BORR_TOP2_TOTAL_INC_AMT/CAST(12 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2008-05-31',DATE '2011-02-28',DATE '2024-03-31')
UNION ALL
SELECT CAST('MV_PCKG_SAV_DEP_TO_REPAY_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_SAV_DEP_TO_REPAY_RT AS RATIO_VALUE, TOTAL_DEPOSIT_SAVINGS_BALANCE AS NUMERATOR,
       PCKG_REPAY_AMT AS RAW_DENOMINATOR, PCKG_REPAY_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2008-10-31',DATE '2010-03-31',DATE '2011-09-30')
), marked AS
(
 SELECT F.*,
 CASE WHEN RATIO_VALUE IS NOT NULL AND RATIO_VALUE NOT IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 1 ELSE 0 END AS VALID_RATIO,
 CASE WHEN NUMERATOR IS NOT NULL
            AND RAW_DENOMINATOR IS NOT NULL
            AND DENOMINATOR>0 THEN 1 ELSE 0 END AS VALID_INPUTS,
 CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))='' OR KEY_COUNT<>1 THEN 1 ELSE 0 END AS BAD_KEY
 FROM field_values F
), reconciled AS
(
 SELECT M.*, CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1
  AND ABS(RATIO_VALUE-(CASE WHEN FIELD_NAME IN ('MV_TOT_DEP_SAV_TO_ACC_BAL_RT','MV_PCKG_SAV_DEP_TO_BALANCE_RT') THEN CAST(100 AS FLOAT) ELSE CAST(1 AS FLOAT) END)*NUMERATOR/NULLIFZERO(DENOMINATOR))
       <= CASE WHEN FIELD_NAME='MV_TOT_DEP_SAV_TO_ACC_BAL_RT' AND ABS(RATIO_VALUE)*1E-9<0.0051 THEN 0.0051 WHEN ABS(RATIO_VALUE)*1E-9>1E-6 THEN ABS(RATIO_VALUE)*1E-9 ELSE 1E-6 END
  THEN 1 ELSE 0 END AS FORMULA_MATCH
 FROM marked M
), cutoff_seed AS
(
 SELECT COUNT(*) AS SEED_COUNT FROM source_values
), cutoffs AS
(
 SELECT CAST(10 AS FLOAT) AS DENOM_CUTOFF FROM cutoff_seed
 UNION ALL SELECT CAST(100 AS FLOAT) FROM cutoff_seed
 UNION ALL SELECT CAST(500 AS FLOAT) FROM cutoff_seed
), aggregated AS
(
 SELECT FIELD_NAME, POU_DT, DENOM_CUTOFF,
 SUM(BAD_KEY) AS BAD_KEYS,
 SUM(VALID_RATIO) AS VALID_COUNT,
 SUM(FORMULA_MATCH) AS RECONCILED_COUNT,
 AVG(CASE WHEN VALID_RATIO=1 THEN RATIO_VALUE END) AS MEAN_ALL,
 SUM(CASE WHEN VALID_RATIO=1 THEN ABS(RATIO_VALUE) END) AS ALL_ABS_RATIO_SUM,
 SUM(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF THEN 1 ELSE 0 END) AS SMALL_DENOM_COUNT,
 SUM(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF THEN ABS(RATIO_VALUE) ELSE CAST(0 AS FLOAT) END) AS SMALL_ABS_RATIO_SUM,
 AVG(CASE WHEN VALID_RATIO=1 AND NOT (VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF) THEN RATIO_VALUE END) AS MEAN_WITHOUT_SMALL,
 MIN(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 THEN DENOMINATOR END) AS MIN_POS_DENOM
 FROM reconciled CROSS JOIN cutoffs
 GROUP BY FIELD_NAME, POU_DT, DENOM_CUTOFF
)
SELECT FIELD_NAME, POU_DT, DENOM_CUTOFF,
 CASE WHEN BAD_KEYS=0 THEN VALID_COUNT END AS VALID_COUNT,
 CASE WHEN BAD_KEYS=0 THEN SMALL_DENOM_COUNT END AS SMALL_DENOM_COUNT,
 CASE WHEN BAD_KEYS=0 THEN MEAN_ALL END AS MEAN_ALL,
 CASE WHEN BAD_KEYS=0 THEN MEAN_WITHOUT_SMALL END AS MEAN_WITHOUT_SMALL
FROM aggregated
ORDER BY FIELD_NAME, POU_DT, DENOM_CUTOFF;
