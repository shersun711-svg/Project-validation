/* READ ONLY Teradata SQL Assistant. Run this entire SELECT as Query 1.
Full account populations for selected spike and neighbouring months; no samples.
Units: ratio is stored without x100. Income denominator for repayment/income is
monthly income (annual / 12); loan/income uses annual income. Other denominators
are amounts in source currency. Cutoffs 1, 10 and 100 are diagnostic scenarios,
NOT approved business limits, recommended replacements or proposed exclusions.
Special-value list is the analyst-confirmed common list used in the review.
Reconciles stored ratios to their inputs before assigning an explanatory status.
Float casts precede arithmetic/aggregation to avoid fixed-decimal overflow.
Duplicate/missing account keys suppress diagnostic outputs. No ratio values,
input amounts, configuration or saved engine outputs are changed.
A matching quotient establishes arithmetic consistency, not correctness of inputs.
Source should be unchanged from the profiling run; compare VALID_COUNT / MEAN_ALL
with the saved MoM run. Missing requested source months produce no result row.
Source FACT_DT is assumed month-end, consistent with the supplied results.
*/
WITH source_values AS
(
SELECT AGMT_ID, CAST(FACT_DT AS DATE) AS POU_DT,
       CAST(MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT AS FLOAT) AS MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT,
       CAST(MV_PCKG_LOAN_TO_INC_RT AS FLOAT) AS MV_PCKG_LOAN_TO_INC_RT,
       CAST(MV_PCKG_REPAY_TO_INC_RT AS FLOAT) AS MV_PCKG_REPAY_TO_INC_RT,
       CAST(MV_PCKG_SAV_DEP_TO_REPAY_RT AS FLOAT) AS MV_PCKG_SAV_DEP_TO_REPAY_RT,
       CAST(PCKG_AVG_BAL_L6M_AMT AS FLOAT) AS PCKG_AVG_BAL_L6M_AMT,
       CAST(PCKG_AVG_BAL_L7_12M_AMT AS FLOAT) AS PCKG_AVG_BAL_L7_12M_AMT,
       CAST(PCKG_BORR_TOP2_TOTAL_INC_AMT AS FLOAT) AS PCKG_BORR_TOP2_TOTAL_INC_AMT,
       CAST(PCKG_ORIG_LOAN_EXCL_WHSE_AMT AS FLOAT) AS PCKG_ORIG_LOAN_EXCL_WHSE_AMT,
       CAST(PCKG_REPAY_AMT AS FLOAT) AS PCKG_REPAY_AMT,
       CAST(TOTAL_DEPOSIT_SAVINGS_BALANCE AS FLOAT) AS TOTAL_DEPOSIT_SAVINGS_BALANCE,
       COUNT(*) OVER (PARTITION BY AGMT_ID, EXTRACT(YEAR FROM FACT_DT), EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN (DATE '2006-08-31',DATE '2006-09-30',DATE '2006-10-31',DATE '2006-12-31',DATE '2007-01-31',DATE '2007-02-28',DATE '2008-09-30',DATE '2008-10-31',DATE '2008-11-30',DATE '2009-02-28',DATE '2009-03-31',DATE '2009-04-30',DATE '2009-07-31',DATE '2009-08-31',DATE '2009-09-30',DATE '2010-03-31',DATE '2010-04-30',DATE '2010-05-31',DATE '2011-01-31',DATE '2011-02-28',DATE '2011-03-31',DATE '2011-08-31',DATE '2011-09-30',DATE '2011-10-31',DATE '2011-11-30',DATE '2011-12-31',DATE '2012-01-31',DATE '2024-02-29',DATE '2024-03-31',DATE '2024-04-30',DATE '2024-10-31',DATE '2024-11-30',DATE '2024-12-31')
), field_values AS
(
SELECT CAST('MV_PCKG_LOAN_TO_INC_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_LOAN_TO_INC_RT AS RATIO_VALUE, PCKG_ORIG_LOAN_EXCL_WHSE_AMT AS NUMERATOR,
       PCKG_BORR_TOP2_TOTAL_INC_AMT AS RAW_DENOMINATOR, PCKG_BORR_TOP2_TOTAL_INC_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2006-08-31',DATE '2006-09-30',DATE '2006-10-31',DATE '2006-12-31',DATE '2007-01-31',DATE '2007-02-28')
UNION ALL
SELECT CAST('MV_PCKG_REPAY_TO_INC_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_REPAY_TO_INC_RT AS RATIO_VALUE, PCKG_REPAY_AMT AS NUMERATOR,
       PCKG_BORR_TOP2_TOTAL_INC_AMT AS RAW_DENOMINATOR, PCKG_BORR_TOP2_TOTAL_INC_AMT/CAST(12 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2011-01-31',DATE '2011-02-28',DATE '2011-03-31',DATE '2024-02-29',DATE '2024-03-31',DATE '2024-04-30',DATE '2024-10-31',DATE '2024-11-30',DATE '2024-12-31')
UNION ALL
SELECT CAST('MV_PCKG_SAV_DEP_TO_REPAY_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_SAV_DEP_TO_REPAY_RT AS RATIO_VALUE, TOTAL_DEPOSIT_SAVINGS_BALANCE AS NUMERATOR,
       PCKG_REPAY_AMT AS RAW_DENOMINATOR, PCKG_REPAY_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2008-09-30',DATE '2008-10-31',DATE '2008-11-30',DATE '2010-03-31',DATE '2010-04-30',DATE '2010-05-31',DATE '2011-08-31',DATE '2011-09-30',DATE '2011-10-31',DATE '2011-11-30',DATE '2011-12-31',DATE '2012-01-31')
UNION ALL
SELECT CAST('MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT' AS VARCHAR(64)) AS FIELD_NAME, AGMT_ID, POU_DT, KEY_COUNT,
       MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT AS RATIO_VALUE, PCKG_AVG_BAL_L6M_AMT AS NUMERATOR,
       PCKG_AVG_BAL_L7_12M_AMT AS RAW_DENOMINATOR, PCKG_AVG_BAL_L7_12M_AMT/CAST(1 AS FLOAT) AS DENOMINATOR
 FROM source_values WHERE POU_DT IN (DATE '2009-02-28',DATE '2009-03-31',DATE '2009-04-30',DATE '2009-07-31',DATE '2009-08-31',DATE '2009-09-30')
), marked AS
(
 SELECT F.*,
 CASE WHEN RATIO_VALUE IS NOT NULL AND RATIO_VALUE NOT IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998) THEN 1 ELSE 0 END AS VALID_RATIO,
 CASE WHEN NUMERATOR IS NOT NULL AND NUMERATOR NOT IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998)
            AND RAW_DENOMINATOR IS NOT NULL AND RAW_DENOMINATOR NOT IN (-99999,-999999,-999998,-99998,-99997,-9999,-9998,-999997,-999993,-999,-999995,999999,999998,999990,99999,99998,999.99,999.88,999,9999,9998)
            AND DENOMINATOR>0 THEN 1 ELSE 0 END AS VALID_INPUTS,
 CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))='' OR KEY_COUNT<>1 THEN 1 ELSE 0 END AS BAD_KEY
 FROM field_values F
), reconciled AS
(
 SELECT M.*, CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1
  AND ABS(RATIO_VALUE-NUMERATOR/NULLIFZERO(DENOMINATOR))
       <= CASE WHEN ABS(RATIO_VALUE)*1E-6>1E-6 THEN ABS(RATIO_VALUE)*1E-6 ELSE 1E-6 END
  THEN 1 ELSE 0 END AS FORMULA_MATCH
 FROM marked M
), cutoffs AS
(
 SELECT CAST(1 AS FLOAT) AS DENOM_CUTOFF
 UNION ALL SELECT CAST(10 AS FLOAT)
 UNION ALL SELECT CAST(100 AS FLOAT)
), aggregated AS
(
 SELECT FIELD_NAME, POU_DT, DENOM_CUTOFF,
 SUM(BAD_KEY) AS BAD_KEYS,
 SUM(VALID_RATIO) AS VALID_COUNT,
 SUM(FORMULA_MATCH) AS RECONCILED_COUNT,
 AVG(CASE WHEN VALID_RATIO=1 THEN RATIO_VALUE END) AS MEAN_ALL,
 SUM(CASE WHEN VALID_RATIO=1 THEN ABS(RATIO_VALUE) END) AS ALL_ABS_RATIO_SUM,
 SUM(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF THEN 1 ELSE 0 END) AS SMALL_DENOM_COUNT,
 SUM(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF THEN ABS(RATIO_VALUE) ELSE CAST(0 AS FLOAT) END) AS SMALL_ABS_RATIO_SUM,
 AVG(CASE WHEN VALID_RATIO=1 AND NOT (VALID_INPUTS=1 AND DENOMINATOR<=DENOM_CUTOFF) THEN RATIO_VALUE END) AS MEAN_WITHOUT_SMALL,
 MIN(CASE WHEN VALID_RATIO=1 AND VALID_INPUTS=1 THEN DENOMINATOR END) AS MIN_POS_DENOM
 FROM reconciled CROSS JOIN cutoffs
 GROUP BY FIELD_NAME, POU_DT, DENOM_CUTOFF
)
SELECT FIELD_NAME, POU_DT, DENOM_CUTOFF,
 CASE WHEN BAD_KEYS>0 THEN 'CHECK_SOURCE_GRAIN'
      WHEN VALID_COUNT=0 THEN 'NO_VALID_RATIOS'
      WHEN RECONCILED_COUNT<>VALID_COUNT THEN 'CHECK_INPUT_RECONCILIATION'
      ELSE 'RECONCILED' END AS REVIEW_STATUS,
 CASE WHEN BAD_KEYS=0 THEN VALID_COUNT END AS VALID_COUNT,
 CASE WHEN BAD_KEYS=0 THEN RECONCILED_COUNT END AS RECONCILED_COUNT,
 CASE WHEN BAD_KEYS=0 THEN MEAN_ALL END AS MEAN_ALL,
 CASE WHEN BAD_KEYS=0 THEN SMALL_DENOM_COUNT END AS SMALL_DENOM_COUNT,
 CASE WHEN BAD_KEYS=0 THEN CAST(SMALL_DENOM_COUNT AS FLOAT)/NULLIFZERO(CAST(VALID_COUNT AS FLOAT)) END AS SMALL_DENOM_SHARE,
 CASE WHEN BAD_KEYS=0 THEN SMALL_ABS_RATIO_SUM/NULLIFZERO(ALL_ABS_RATIO_SUM) END AS ABS_RATIO_CONTRIB_SHARE,
 CASE WHEN BAD_KEYS=0 THEN MEAN_WITHOUT_SMALL END AS MEAN_WITHOUT_SMALL,
 CASE WHEN BAD_KEYS=0 THEN MIN_POS_DENOM END AS MIN_POS_DENOM
FROM aggregated
ORDER BY FIELD_NAME, POU_DT, DENOM_CUTOFF;
