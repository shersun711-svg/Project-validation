/* Three remaining calendar scenarios: compact full-population checks.
   Teradata SQL Assistant: run Query 1 and Query 2 separately; export both.
   June 2024 was already checked and is NOT repeated here.

   Target        Non-working start      Compared due days    Previous / next
   Nov 2008      Sat 1 / Sun 2           1-2 versus 3-31     Oct / Dec 2008
   Sep 2024      Sun 1                   1 versus 2-31       Aug / Oct 2024
   Jun 2025      Sun 1 / bank hol Mon 2  1-2 versus 3-31     May / Jul 2025

   QUERY 1 (5 columns): target month, due-day group, valid target accounts,
   target zero-payment count and zero rate. Rate excludes missing/special
   payments. Missing/invalid bill-day groups stay visible if present.
   Original profiling zero counts: Nov 2008=27262, Sep 2024=7546,
   Jun 2025=10115; current-source results can differ if data has changed.

   QUERY 2 (6 columns): target month, due-day group, target-zero accounts,
   matched accounts, PREV_GT_NEXT_COUNT and PREV_GT_NEXT_SHARE.
   PREV/NEXT are the previous/next calendar month shown above. For example,
   September compares August payments with October payments, on the same
   September-zero accounts. Matched requires valid payments in all 3 months.
   The share uses matched accounts, not all target-zero accounts. All rates
   and shares are fractions (0.97 means 97%). No arbitrary pass cutoff.

   Full target-month cohorts, no sampling and no account-ID export. Absent
   adjacent records and missing/special values are never treated as zero.
   Groups use the TARGET month bill day; no assumption of unchanged bill days.
   The two queries must use a fixed source and the same target date list.
   Calendar grouping is configured specifically for these three cases.

   Shared specials come from successful RDS account run 20, previously
   confirmed equal to the profiling list. Reference and account/month grain
   checks remain internal. NULL output counts mean a failed control, not zero.
   If Query 1 has NULL counts, do not interpret an empty Query 2 as no cases.
   Read-only: no permanent data/objects or engine runs are changed/created.

   This assesses whether monthly patterns support a similar timing mechanism.
   Exact receipt dates and the applicable collection rule are not verified.
*/

/* QUERY 1: zero-payment concentration. */
WITH targets AS
(
 /* Edit this same date list in BOTH queries. Use first-of-month dates. */
 SELECT CALENDAR_DATE AS TARGET_MONTH
 FROM SYS_CALENDAR.CALENDAR
 WHERE CALENDAR_DATE IN (DATE '2008-11-01', DATE '2024-09-01', DATE '2025-06-01')
), reference_runs AS
(
 SELECT DISTINCT RUN_ID FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'
), reference_context AS
(
 SELECT COUNT(*) AS REFERENCE_RUN_COUNT FROM reference_runs
), special_values AS
(
 SELECT DISTINCT V.NUMERIC_VALUE
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON R.RUN_ID=V.RUN_ID
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), source_values AS
(
 SELECT T.TARGET_MONTH,CAST(S.AGMT_ID AS VARCHAR(128)) AS ACCOUNT_KEY,
        (EXTRACT(YEAR FROM S.FACT_DT)*12+EXTRACT(MONTH FROM S.FACT_DT))
         -(EXTRACT(YEAR FROM T.TARGET_MONTH)*12+EXTRACT(MONTH FROM T.TARGET_MONTH)) AS MONTH_POSITION,
        CAST(S.BILL_DAY AS FLOAT) AS BILL_DAY_VALUE,
        CAST(S.PROBE_CNP_AMT AS FLOAT) AS PAYMENT_VALUE
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT S
 JOIN targets T ON S.FACT_DT>=ADD_MONTHS(T.TARGET_MONTH,-1)
               AND S.FACT_DT<ADD_MONTHS(T.TARGET_MONTH,2)
), classified AS
(
 SELECT S.*,C.REFERENCE_RUN_COUNT,
        COUNT(*) OVER (PARTITION BY TARGET_MONTH,ACCOUNT_KEY,MONTH_POSITION) AS KEY_COUNT,
        CASE WHEN PAYMENT_VALUE IS NULL THEN 'MISSING'
             WHEN C.REFERENCE_RUN_COUNT<>1 THEN 'UNVERIFIED'
             WHEN V.NUMERIC_VALUE IS NOT NULL THEN 'SPECIAL'
             ELSE 'VALID' END AS PAYMENT_STATE
 FROM source_values S CROSS JOIN reference_context C
 LEFT JOIN special_values V ON S.PAYMENT_VALUE=V.NUMERIC_VALUE
), checked AS
(
 SELECT C.*,
        SUM(CASE WHEN ACCOUNT_KEY IS NULL OR TRIM(ACCOUNT_KEY)=''
                      OR KEY_COUNT<>1 THEN 1 ELSE 0 END)
          OVER (PARTITION BY TARGET_MONTH) AS WINDOW_BAD_KEYS
 FROM classified C
), account_months AS
(
 SELECT TARGET_MONTH,ACCOUNT_KEY,
        MAX(REFERENCE_RUN_COUNT) AS REFERENCE_RUN_COUNT,MAX(WINDOW_BAD_KEYS) AS WINDOW_BAD_KEYS,
        MAX(CASE WHEN MONTH_POSITION=-1 THEN 1 ELSE 0 END) AS PREV_OBSERVED,
        MAX(CASE WHEN MONTH_POSITION=0 THEN 1 ELSE 0 END) AS TARGET_OBSERVED,
        MAX(CASE WHEN MONTH_POSITION=1 THEN 1 ELSE 0 END) AS NEXT_OBSERVED,
        MAX(CASE WHEN MONTH_POSITION=-1 THEN PAYMENT_VALUE END) AS PREV_PAYMENT,
        MAX(CASE WHEN MONTH_POSITION=0 THEN PAYMENT_VALUE END) AS TARGET_PAYMENT,
        MAX(CASE WHEN MONTH_POSITION=1 THEN PAYMENT_VALUE END) AS NEXT_PAYMENT,
        MAX(CASE WHEN MONTH_POSITION=-1 THEN PAYMENT_STATE END) AS PREV_STATE,
        MAX(CASE WHEN MONTH_POSITION=0 THEN PAYMENT_STATE END) AS TARGET_STATE,
        MAX(CASE WHEN MONTH_POSITION=1 THEN PAYMENT_STATE END) AS NEXT_STATE,
        MAX(CASE WHEN MONTH_POSITION=0 THEN BILL_DAY_VALUE END) AS TARGET_BILL_DAY
 FROM checked GROUP BY TARGET_MONTH,ACCOUNT_KEY
), target_cohort AS
(
 SELECT A.*,
        CASE WHEN REFERENCE_RUN_COUNT=1 AND WINDOW_BAD_KEYS=0 THEN 1 ELSE 0 END AS PUBLISH_RESULTS,
        CASE WHEN TARGET_BILL_DAY IS NULL OR TARGET_BILL_DAY<1 OR TARGET_BILL_DAY>31
                       OR TARGET_BILL_DAY<>FLOOR(TARGET_BILL_DAY) THEN 'MISSING_OR_INVALID'
             WHEN TARGET_MONTH=DATE '2024-09-01' AND TARGET_BILL_DAY=1 THEN 'DAY_01'
             WHEN TARGET_MONTH=DATE '2024-09-01' THEN 'DAYS_02_31'
             WHEN TARGET_BILL_DAY IN (1,2) THEN 'DAYS_01_02'
             ELSE 'DAYS_03_31' END AS BILL_DAY_GROUP,
        CASE WHEN PREV_OBSERVED=1 AND NEXT_OBSERVED=1
                   AND PREV_STATE='VALID' AND TARGET_STATE='VALID' AND NEXT_STATE='VALID'
             THEN 1 ELSE 0 END AS COMPLETE_VALID
 FROM account_months A WHERE TARGET_OBSERVED=1
)
 , due_day_summary AS
(
 SELECT TARGET_MONTH,BILL_DAY_GROUP,MAX(PUBLISH_RESULTS) AS PUBLISH_RESULTS,
        SUM(CASE WHEN TARGET_STATE='VALID' THEN 1 ELSE 0 END) AS VALID_TARGET_COUNT,
        SUM(CASE WHEN TARGET_STATE='VALID' AND TARGET_PAYMENT=0 THEN 1 ELSE 0 END) AS TARGET_ZERO_COUNT
 FROM target_cohort GROUP BY TARGET_MONTH,BILL_DAY_GROUP
)
SELECT TARGET_MONTH,BILL_DAY_GROUP,
       CASE WHEN PUBLISH_RESULTS=1 THEN VALID_TARGET_COUNT END AS VALID_TARGET_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN TARGET_ZERO_COUNT END AS TARGET_ZERO_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN CAST(TARGET_ZERO_COUNT AS FLOAT)/NULLIFZERO(VALID_TARGET_COUNT) END AS TARGET_ZERO_RATE
FROM due_day_summary ORDER BY 1,2;

