/* RDS: 10 value examples per numeric field, with neighbouring months.
   Teradata SQL Assistant: run this entire SELECT as one statement.
   Read-only: no objects, settings or saved results are changed.

   EDIT TARGET_MONTH below to the FIRST DAY of the month to inspect.
   Default February 2026 allows January/February/March examples within the
   available account-review window. Set EXAMPLES_PER_FIELD to 5 or 10.

   For each field, split current-month valid values into 5 or 10 equal-count
   groups and display one central observation per group. This shows the value
   range without selecting only flagged records. It is not a random sample,
   proof of normal behaviour, or a replacement for a full distribution review.
   Repeated values may appear when many accounts have the same value.

   Current-month NULLs/configured specials are excluded from examples when
   valid values exist, but their counts remain visible. If no valid values
   exist, examples instead show the available missing/special states.

   Classification uses the captured NUMERIC special list for RDS account run
   20. The data comes from today's source view, not a reconstruction of run 20.
   If that successful reference is unavailable/ambiguous, non-null values are
   labelled UNVERIFIED and included without claiming specials were excluded.
   Inspect REFERENCE_STATUS. Assumes the reviewed one-account/calendar-month
   grain; the source must remain unchanged during execution.

   FLOAT calculations match the account check's exploratory numeric approach;
   retain source precision before making decisions on exact boundary cases.
   Keep agreement IDs/results within the approved internal environment.
*/
WITH params AS
(
  SELECT DATE '2026-02-01' AS TARGET_MONTH,
         10 AS EXAMPLES_PER_FIELD
  FROM SYS_CALENDAR.CALENDAR
  WHERE CALENDAR_DATE=DATE '2000-01-01'
), reference_runs AS
(
  SELECT DISTINCT RUN_ID
  FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
  WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'
), reference_context AS
(
  SELECT COUNT(*) AS REFERENCE_RUN_COUNT FROM reference_runs
), special_values AS
(
  SELECT DISTINCT V.NUMERIC_VALUE
  FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
  JOIN reference_runs R ON R.RUN_ID=V.RUN_ID
  WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), fields AS
(
  SELECT CAST(CASE EXTRACT(DAY FROM CALENDAR_DATE)
           WHEN 1 THEN 'CHQ_LMT_UTIL_AVG_BAL_6M'
           WHEN 2 THEN 'CUST_ALL_C_PYMTS_CR_AVG_L6M_AMT'
           WHEN 3 THEN 'CUST_ALL_MT_MAX_DELINQ_BASE_RT'
           WHEN 4 THEN 'MTHS_SINCE_DETERIORATION_CNT'
           WHEN 5 THEN 'MV_CUST_ALL_MTHS_SNC_DIST_CNT'
           WHEN 6 THEN 'MV_PCKG_AVG_PAY_TO_BAL_L6M_RT'
           WHEN 7 THEN 'MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT'
           WHEN 8 THEN 'MV_PCKG_LOAN_TO_INC_RT'
           WHEN 9 THEN 'MV_PCKG_REPAY_TO_INC_RT'
           WHEN 10 THEN 'MV_PCKG_SAV_DEP_TO_BALANCE_RT'
           WHEN 11 THEN 'MV_PCKG_SAV_DEP_TO_REPAY_RT'
           WHEN 12 THEN 'PCKG_BALANCE_AMT'
           WHEN 13 THEN 'PCKG_BOVO_VAL_AMT'
           WHEN 14 THEN 'PCKG_REPAY_AMT'
         END AS VARCHAR(128)) AS FIELD_NAME
  FROM SYS_CALENDAR.CALENDAR
  WHERE CALENDAR_DATE BETWEEN DATE '2000-01-01' AND DATE '2000-01-14'
), source_window AS
(
  SELECT S.AGMT_ID, CAST(S.FACT_DT AS DATE) AS POU_DT,
         S.CHQ_LMT_UTIL_AVG_BAL_6M,
         S.CUST_ALL_C_PYMTS_CR_AVG_L6M_AMT,
         S.CUST_ALL_MT_MAX_DELINQ_BASE_RT,
         S.MTHS_SINCE_DETERIORATION_CNT,
         S.MV_CUST_ALL_MTHS_SNC_DIST_CNT,
         S.MV_PCKG_AVG_PAY_TO_BAL_L6M_RT,
         S.MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT,
         S.MV_PCKG_LOAN_TO_INC_RT,
         S.MV_PCKG_REPAY_TO_INC_RT,
         S.MV_PCKG_SAV_DEP_TO_BALANCE_RT,
         S.MV_PCKG_SAV_DEP_TO_REPAY_RT,
         S.PCKG_BALANCE_AMT,
         S.PCKG_BOVO_VAL_AMT,
         S.PCKG_REPAY_AMT
  FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT S
  CROSS JOIN params P
  WHERE S.FACT_DT >= ADD_MONTHS(P.TARGET_MONTH,-1)
    AND S.FACT_DT < ADD_MONTHS(P.TARGET_MONTH,2)
), long_values AS
(
  SELECT S.AGMT_ID, S.POU_DT, F.FIELD_NAME,
         EXTRACT(YEAR FROM S.POU_DT)*12+EXTRACT(MONTH FROM S.POU_DT) AS MONTH_KEY,
         CASE F.FIELD_NAME
           WHEN 'CHQ_LMT_UTIL_AVG_BAL_6M' THEN CAST(S.CHQ_LMT_UTIL_AVG_BAL_6M AS FLOAT)
           WHEN 'CUST_ALL_C_PYMTS_CR_AVG_L6M_AMT' THEN CAST(S.CUST_ALL_C_PYMTS_CR_AVG_L6M_AMT AS FLOAT)
           WHEN 'CUST_ALL_MT_MAX_DELINQ_BASE_RT' THEN CAST(S.CUST_ALL_MT_MAX_DELINQ_BASE_RT AS FLOAT)
           WHEN 'MTHS_SINCE_DETERIORATION_CNT' THEN CAST(S.MTHS_SINCE_DETERIORATION_CNT AS FLOAT)
           WHEN 'MV_CUST_ALL_MTHS_SNC_DIST_CNT' THEN CAST(S.MV_CUST_ALL_MTHS_SNC_DIST_CNT AS FLOAT)
           WHEN 'MV_PCKG_AVG_PAY_TO_BAL_L6M_RT' THEN CAST(S.MV_PCKG_AVG_PAY_TO_BAL_L6M_RT AS FLOAT)
           WHEN 'MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT' THEN CAST(S.MV_PCKG_BAL_AMT_L6M_TO_L7T12M_RT AS FLOAT)
           WHEN 'MV_PCKG_LOAN_TO_INC_RT' THEN CAST(S.MV_PCKG_LOAN_TO_INC_RT AS FLOAT)
           WHEN 'MV_PCKG_REPAY_TO_INC_RT' THEN CAST(S.MV_PCKG_REPAY_TO_INC_RT AS FLOAT)
           WHEN 'MV_PCKG_SAV_DEP_TO_BALANCE_RT' THEN CAST(S.MV_PCKG_SAV_DEP_TO_BALANCE_RT AS FLOAT)
           WHEN 'MV_PCKG_SAV_DEP_TO_REPAY_RT' THEN CAST(S.MV_PCKG_SAV_DEP_TO_REPAY_RT AS FLOAT)
           WHEN 'PCKG_BALANCE_AMT' THEN CAST(S.PCKG_BALANCE_AMT AS FLOAT)
           WHEN 'PCKG_BOVO_VAL_AMT' THEN CAST(S.PCKG_BOVO_VAL_AMT AS FLOAT)
           WHEN 'PCKG_REPAY_AMT' THEN CAST(S.PCKG_REPAY_AMT AS FLOAT)
         END AS NUMBER_VALUE
  FROM source_window S CROSS JOIN fields F
), classified AS
(
  SELECT L.*,
         CASE WHEN L.NUMBER_VALUE IS NULL THEN 'MISSING'
              WHEN C.REFERENCE_RUN_COUNT<>1 THEN 'UNVERIFIED'
              WHEN V.NUMERIC_VALUE IS NOT NULL THEN 'SPECIAL'
              ELSE 'VALID' END AS VALUE_STATE,
         CASE WHEN C.REFERENCE_RUN_COUNT=1 THEN 'RUN20_SPECIAL_LIST'
              ELSE 'CHECK_REFERENCE_RUN20' END AS REFERENCE_STATUS
  FROM long_values L
  CROSS JOIN reference_context C
  LEFT JOIN special_values V ON L.NUMBER_VALUE=V.NUMERIC_VALUE
), neighbours AS
(
  SELECT C.*,
         LAG(POU_DT) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS PREVIOUS_DATE,
         LAG(MONTH_KEY) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS PREVIOUS_MONTH_KEY,
         LAG(NUMBER_VALUE) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS PREVIOUS_VALUE,
         LAG(VALUE_STATE) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS PREVIOUS_STATE,
         LEAD(POU_DT) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS NEXT_DATE,
         LEAD(MONTH_KEY) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS NEXT_MONTH_KEY,
         LEAD(NUMBER_VALUE) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS NEXT_VALUE,
         LEAD(VALUE_STATE) OVER (PARTITION BY FIELD_NAME,AGMT_ID ORDER BY POU_DT) AS NEXT_STATE
  FROM classified C
), current_population AS
(
  SELECT N.*,
         COUNT(*) OVER (PARTITION BY FIELD_NAME) AS CURRENT_TOTAL_COUNT,
         SUM(CASE WHEN VALUE_STATE='VALID' THEN 1 ELSE 0 END)
           OVER (PARTITION BY FIELD_NAME) AS CURRENT_VALID_COUNT,
         SUM(CASE WHEN VALUE_STATE='MISSING' THEN 1 ELSE 0 END)
           OVER (PARTITION BY FIELD_NAME) AS CURRENT_MISSING_COUNT,
         SUM(CASE WHEN VALUE_STATE='SPECIAL' THEN 1 ELSE 0 END)
           OVER (PARTITION BY FIELD_NAME) AS CURRENT_SPECIAL_COUNT,
         SUM(CASE WHEN VALUE_STATE='UNVERIFIED' THEN 1 ELSE 0 END)
           OVER (PARTITION BY FIELD_NAME) AS CURRENT_UNVERIFIED_COUNT,
         SUM(CASE WHEN VALUE_STATE='VALID' AND NUMBER_VALUE=0 THEN 1 ELSE 0 END)
           OVER (PARTITION BY FIELD_NAME) AS CURRENT_VALID_ZERO_COUNT
  FROM neighbours N CROSS JOIN params P
  WHERE N.POU_DT>=P.TARGET_MONTH
    AND N.POU_DT<ADD_MONTHS(P.TARGET_MONTH,1)
), example_population AS
(
  SELECT C.*
  FROM current_population C
  WHERE VALUE_STATE='VALID' OR CURRENT_VALID_COUNT=0
), numbered AS
(
  SELECT E.*,
         ROW_NUMBER() OVER
           (PARTITION BY FIELD_NAME ORDER BY NUMBER_VALUE,AGMT_ID,POU_DT) AS VALUE_RANK,
         COUNT(*) OVER (PARTITION BY FIELD_NAME) AS EXAMPLE_POPULATION_COUNT
  FROM example_population E
), bucketed AS
(
  SELECT N.*,
         /* Equal-count value groups; at most EXAMPLES_PER_FIELD groups. */
         CAST(FLOOR((CAST(VALUE_RANK-1 AS FLOAT)*P.EXAMPLES_PER_FIELD)
              /EXAMPLE_POPULATION_COUNT)+1 AS INTEGER) AS VALUE_GROUP
  FROM numbered N CROSS JOIN params P
), group_positions AS
(
  SELECT B.*,
         MIN(NUMBER_VALUE) OVER (PARTITION BY FIELD_NAME,VALUE_GROUP) AS GROUP_MIN_VALUE,
         MAX(NUMBER_VALUE) OVER (PARTITION BY FIELD_NAME,VALUE_GROUP) AS GROUP_MAX_VALUE,
         MIN(VALUE_RANK) OVER (PARTITION BY FIELD_NAME,VALUE_GROUP) AS GROUP_FIRST_RANK,
         COUNT(*) OVER (PARTITION BY FIELD_NAME,VALUE_GROUP) AS GROUP_COUNT
  FROM bucketed B
)
SELECT FIELD_NAME, VALUE_GROUP, AGMT_ID,
       CASE WHEN PREVIOUS_MONTH_KEY=MONTH_KEY-1 THEN PREVIOUS_DATE END AS PREVIOUS_DATE,
       CASE WHEN PREVIOUS_MONTH_KEY=MONTH_KEY-1 THEN PREVIOUS_VALUE END AS PREVIOUS_VALUE,
       CASE WHEN PREVIOUS_MONTH_KEY=MONTH_KEY-1 THEN PREVIOUS_STATE
            ELSE 'NO_ADJACENT_MONTH' END AS PREVIOUS_STATE,
       POU_DT AS CURRENT_DATE_VALUE, NUMBER_VALUE AS CURRENT_VALUE,
       VALUE_STATE AS CURRENT_STATE,
       CASE WHEN NEXT_MONTH_KEY=MONTH_KEY+1 THEN NEXT_DATE END AS NEXT_DATE,
       CASE WHEN NEXT_MONTH_KEY=MONTH_KEY+1 THEN NEXT_VALUE END AS NEXT_VALUE,
       CASE WHEN NEXT_MONTH_KEY=MONTH_KEY+1 THEN NEXT_STATE
            ELSE 'NO_ADJACENT_MONTH' END AS NEXT_STATE,
       CASE WHEN PREVIOUS_MONTH_KEY=MONTH_KEY-1
                  AND PREVIOUS_STATE='VALID' AND VALUE_STATE='VALID'
            THEN NUMBER_VALUE-PREVIOUS_VALUE END AS CHANGE_VALUE,
       CASE WHEN PREVIOUS_MONTH_KEY=MONTH_KEY-1
                  AND PREVIOUS_STATE='VALID' AND VALUE_STATE='VALID'
                  AND PREVIOUS_VALUE<>0
            THEN (NUMBER_VALUE-PREVIOUS_VALUE)/ABS(PREVIOUS_VALUE) END AS RELATIVE_CHANGE,
       GROUP_MIN_VALUE, GROUP_MAX_VALUE, GROUP_COUNT,
       CURRENT_TOTAL_COUNT, CURRENT_VALID_COUNT, CURRENT_MISSING_COUNT,
       CURRENT_SPECIAL_COUNT, CURRENT_UNVERIFIED_COUNT, CURRENT_VALID_ZERO_COUNT,
       REFERENCE_STATUS,
       CASE WHEN CURRENT_VALID_COUNT>0 THEN 'VALID_VALUES'
            WHEN CURRENT_UNVERIFIED_COUNT>0 THEN 'UNVERIFIED_VALUES'
            ELSE 'NO_VALID_VALUES' END AS EXAMPLE_SCOPE
FROM group_positions
WHERE VALUE_RANK=GROUP_FIRST_RANK+CAST(FLOOR((GROUP_COUNT-1)/2.0) AS INTEGER)
ORDER BY FIELD_NAME,VALUE_GROUP;
