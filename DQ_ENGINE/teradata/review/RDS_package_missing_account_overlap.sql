/* READ ONLY Teradata SQL Assistant: cross-field valid-to-missing overlap.
Run the complete SELECT once. Full source populations, no samples.
Compares the same AGMT_ID across consecutive months for the report's five dates.
References account-check snapshots: categorical run 19, numeric run 20.
If those snapshots are unavailable/different, amend the two run numbers below.
No new run, permanent object or saved result is created.
Output counts are account-month observations, not unique people or packages.
MATCHED_ACCOUNT_COUNT = records observed in both months, not all-fields-valid pairs.
Four field counts use each field's own valid-previous -> missing-current test.
TWO_OR_MORE and ALL_FOUR directly measure overlap on the SAME account/month.
TWO_OR_MORE_PCKG_MISSING is a subset of TWO_OR_MORE, with current PCKG_ID missing.
It does not mean package ID became missing and does not establish a common cause.
Missing strings include blanks; previous special values are excluded by type.
All counts are suppressed as NULL if duplicate/null source keys exist in the date
window or either special-value snapshot resolves to other than one run.
NULL outputs are not a pass. Compare field counts with saved report results.
Source must match the original run version. Snapshot must exist even if empty.
*/
WITH reference_runs AS
(
 SELECT DISTINCT RUN_ID,FIELD_TYPE FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND
 ((RUN_NUMBER=19 AND FIELD_TYPE='CATEGORICAL') OR
  (RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'))
), reference_control AS
(
 SELECT SUM(CASE WHEN FIELD_TYPE='CATEGORICAL' THEN 1 ELSE 0 END) AS CAT_RUNS,
        SUM(CASE WHEN FIELD_TYPE='NUMERIC' THEN 1 ELSE 0 END) AS NUM_RUNS
 FROM reference_runs
), cat_special AS
(
 SELECT DISTINCT UPPER(TRIM(V.SPECIAL_VALUE)) AS SPECIAL_KEY
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON V.RUN_ID=R.RUN_ID AND R.FIELD_TYPE='CATEGORICAL'
 WHERE V.FIELD_TYPE='CATEGORICAL' AND V.SPECIAL_VALUE IS NOT NULL
), num_special AS
(
 SELECT DISTINCT V.NUMERIC_VALUE AS SPECIAL_KEY
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON V.RUN_ID=R.RUN_ID AND R.FIELD_TYPE='NUMERIC'
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), source_values AS
(
 SELECT AGMT_ID,CAST(FACT_DT AS DATE) AS POU_DT,
 EXTRACT(YEAR FROM FACT_DT)*12+EXTRACT(MONTH FROM FACT_DT) AS MONTH_KEY,
 NULLIF(UPPER(TRIM(CAST(EVENT_DESCRIPTION AS VARCHAR(512)))),'') AS EVENT_VALUE,
 NULLIF(UPPER(TRIM(CAST(MV_PROP_POSTCODE_NM AS VARCHAR(512)))),'') AS POSTCODE_VALUE,
 CAST(PCKG_BOVO_VAL_AMT AS FLOAT) AS BOVO_VALUE,
 CAST(PCKG_REPAY_AMT AS FLOAT) AS REPAY_VALUE,
 NULLIF(TRIM(CAST(PCKG_ID AS VARCHAR(128))),'') AS PACKAGE_ID,
 COUNT(*) OVER (PARTITION BY AGMT_ID,EXTRACT(YEAR FROM FACT_DT),EXTRACT(MONTH FROM FACT_DT)) AS KEY_COUNT
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT
 WHERE CAST(FACT_DT AS DATE) IN (DATE '2019-01-31',DATE '2019-02-28',DATE '2019-04-30',DATE '2019-05-31',DATE '2020-01-31',DATE '2020-02-29',DATE '2022-02-28',DATE '2022-03-31',DATE '2024-10-31',DATE '2024-11-30')
), key_control AS
(
 SELECT SUM(CASE WHEN AGMT_ID IS NULL OR TRIM(CAST(AGMT_ID AS VARCHAR(128)))='' OR KEY_COUNT<>1 THEN 1 ELSE 0 END) AS BAD_KEYS
 FROM source_values
), flagged AS
(
 SELECT C.POU_DT,C.PACKAGE_ID,
 CASE WHEN P.EVENT_VALUE IS NOT NULL AND CS1.SPECIAL_KEY IS NULL AND C.EVENT_VALUE IS NULL THEN 1 ELSE 0 END AS EVENT_MISSING,
 CASE WHEN P.POSTCODE_VALUE IS NOT NULL AND CS2.SPECIAL_KEY IS NULL AND C.POSTCODE_VALUE IS NULL THEN 1 ELSE 0 END AS POSTCODE_MISSING,
 CASE WHEN P.BOVO_VALUE IS NOT NULL AND NS1.SPECIAL_KEY IS NULL AND C.BOVO_VALUE IS NULL THEN 1 ELSE 0 END AS BOVO_MISSING,
 CASE WHEN P.REPAY_VALUE IS NOT NULL AND NS2.SPECIAL_KEY IS NULL AND C.REPAY_VALUE IS NULL THEN 1 ELSE 0 END AS REPAY_MISSING
 FROM source_values C
 JOIN source_values P ON C.AGMT_ID=P.AGMT_ID AND C.MONTH_KEY=P.MONTH_KEY+1
 LEFT JOIN cat_special CS1 ON P.EVENT_VALUE=CS1.SPECIAL_KEY
 LEFT JOIN cat_special CS2 ON P.POSTCODE_VALUE=CS2.SPECIAL_KEY
 LEFT JOIN num_special NS1 ON P.BOVO_VALUE=NS1.SPECIAL_KEY
 LEFT JOIN num_special NS2 ON P.REPAY_VALUE=NS2.SPECIAL_KEY
 WHERE C.POU_DT IN (DATE '2019-02-28',DATE '2019-05-31',DATE '2020-02-29',DATE '2022-03-31',DATE '2024-11-30')
), overlap_values AS
(
 SELECT F.*,EVENT_MISSING+POSTCODE_MISSING+BOVO_MISSING+REPAY_MISSING AS FIELD_COUNT
 FROM flagged F
), monthly AS
(
 SELECT POU_DT,COUNT(*) AS MATCHED_ACCOUNT_COUNT,
 SUM(EVENT_MISSING) AS EVENT_MISSING,SUM(POSTCODE_MISSING) AS POSTCODE_MISSING,
 SUM(BOVO_MISSING) AS BOVO_MISSING,SUM(REPAY_MISSING) AS REPAY_MISSING,
 SUM(CASE WHEN FIELD_COUNT>=2 THEN 1 ELSE 0 END) AS TWO_OR_MORE,
 SUM(CASE WHEN FIELD_COUNT=4 THEN 1 ELSE 0 END) AS ALL_FOUR,
 SUM(CASE WHEN FIELD_COUNT>=2 AND PACKAGE_ID IS NULL THEN 1 ELSE 0 END) AS TWO_OR_MORE_PCKG_MISSING
 FROM overlap_values GROUP BY POU_DT
), results AS
(
 SELECT M.*,CASE WHEN COALESCE(K.BAD_KEYS,0)=0 AND R.CAT_RUNS=1 AND R.NUM_RUNS=1 THEN 1 ELSE 0 END AS CAN_EVALUATE
 FROM monthly M CROSS JOIN key_control K CROSS JOIN reference_control R
)
SELECT POU_DT,
 CASE WHEN CAN_EVALUATE=1 THEN MATCHED_ACCOUNT_COUNT END AS MATCHED_ACCOUNT_COUNT,
 CASE WHEN CAN_EVALUATE=1 THEN EVENT_MISSING END AS EVENT_MISSING,
 CASE WHEN CAN_EVALUATE=1 THEN POSTCODE_MISSING END AS POSTCODE_MISSING,
 CASE WHEN CAN_EVALUATE=1 THEN BOVO_MISSING END AS BOVO_MISSING,
 CASE WHEN CAN_EVALUATE=1 THEN REPAY_MISSING END AS REPAY_MISSING,
 CASE WHEN CAN_EVALUATE=1 THEN TWO_OR_MORE END AS TWO_OR_MORE,
 CASE WHEN CAN_EVALUATE=1 THEN ALL_FOUR END AS ALL_FOUR,
 CASE WHEN CAN_EVALUATE=1 THEN TWO_OR_MORE_PCKG_MISSING END AS TWO_OR_MORE_PCKG_MISSING
FROM results
ORDER BY POU_DT;
