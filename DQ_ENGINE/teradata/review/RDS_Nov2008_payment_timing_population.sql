/* November 2008 PROBE_CNP_AMT: compact full-population timing checks.
   Read-only Teradata SQL Assistant. Run Query 1 and Query 2 SEPARATELY.
   No sampling, account-ID output, permanent tables or engine runs.

   November 1 was Saturday and November 2 Sunday. Check due days 1-2
   against days 3-31, using all accounts observed in November as a fixed
   population. October and December are the comparison months.

   Q1 (4 columns): valid November accounts, zero-payment accounts and zero
   rate by November bill-day group. Missing/special November payments are
   excluded from the rate denominator. Missing/invalid bill days stay visible.
   Original profiling population: 164147 accounts; November zeros: 27262.
   The valid-payment denominator may be smaller than the full population.

   Q2 (5 columns): November-zero accounts only. MATCHED_ACCOUNT_COUNT means
   valid October-November-December payment observations. OCT_GT_DEC_COUNT
   counts matched accounts paying more in October than December, and its
   share uses the MATCHED count. Missing records are never converted to zero.

   Rates are fractions (0.97 means 97%). Shared numeric special snapshot is
   from RDS account run 20, confirmed equal to the profiling list. Reference
   and account/month grain checks run internally. NULL output counts mean
   a control failed: do not interpret them as zero or use them for closure.
   Keep the source fixed across both queries. BILL_DAY is the due day in the
   attestation (available from Jan 2007); PROBE_CNP_AMT is monthly net payment.

   A concentration of November zeros in days 1-2 and higher October receipts
   for those same accounts would support a similar timing mechanism to June
   2024. It would not prove exact receipt dates or the collection convention.
   No November explanation or pass is assumed before reviewing the results.
*/

/* QUERY 1: November zeros by due-day group. */
WITH reference_runs AS
(
 SELECT DISTINCT RUN_ID FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'
), reference_context AS
(
 SELECT COUNT(*) AS REFERENCE_RUN_COUNT FROM reference_runs
), special_values AS
(
 SELECT DISTINCT V.NUMERIC_VALUE
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON R.RUN_ID=V.RUN_ID
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), source_values AS
(
 SELECT CAST(S.AGMT_ID AS VARCHAR(128)) AS ACCOUNT_KEY,
        CAST(S.FACT_DT AS DATE) AS POU_DT,
        EXTRACT(MONTH FROM S.FACT_DT) AS MONTH_NO,
        CAST(S.BILL_DAY AS FLOAT) AS BILL_DAY_VALUE,
        CAST(S.PROBE_CNP_AMT AS FLOAT) AS PAYMENT_VALUE
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT S
 WHERE S.FACT_DT>=DATE '2008-10-01' AND S.FACT_DT<DATE '2009-01-01'
), classified AS
(
 SELECT S.*,C.REFERENCE_RUN_COUNT,
        COUNT(*) OVER (PARTITION BY ACCOUNT_KEY,MONTH_NO) AS KEY_COUNT,
        CASE WHEN PAYMENT_VALUE IS NULL THEN 'MISSING'
             WHEN C.REFERENCE_RUN_COUNT<>1 THEN 'UNVERIFIED'
             WHEN V.NUMERIC_VALUE IS NOT NULL THEN 'SPECIAL'
             ELSE 'VALID' END AS PAYMENT_STATE
 FROM source_values S CROSS JOIN reference_context C
 LEFT JOIN special_values V ON S.PAYMENT_VALUE=V.NUMERIC_VALUE
), checked AS
(
 SELECT C.*,
        SUM(CASE WHEN ACCOUNT_KEY IS NULL OR TRIM(ACCOUNT_KEY)=''
                      OR KEY_COUNT<>1 THEN 1 ELSE 0 END) OVER () AS WINDOW_BAD_KEYS
 FROM classified C
), account_months AS
(
 SELECT ACCOUNT_KEY,MAX(REFERENCE_RUN_COUNT) AS REFERENCE_RUN_COUNT,
        MAX(WINDOW_BAD_KEYS) AS WINDOW_BAD_KEYS,
        MAX(CASE WHEN MONTH_NO=10 THEN 1 ELSE 0 END) AS OCT_OBSERVED,
        MAX(CASE WHEN MONTH_NO=11 THEN 1 ELSE 0 END) AS NOV_OBSERVED,
        MAX(CASE WHEN MONTH_NO=12 THEN 1 ELSE 0 END) AS DEC_OBSERVED,
        MAX(CASE WHEN MONTH_NO=10 THEN PAYMENT_VALUE END) AS OCT_PAYMENT,
        MAX(CASE WHEN MONTH_NO=11 THEN PAYMENT_VALUE END) AS NOV_PAYMENT,
        MAX(CASE WHEN MONTH_NO=12 THEN PAYMENT_VALUE END) AS DEC_PAYMENT,
        MAX(CASE WHEN MONTH_NO=10 THEN PAYMENT_STATE END) AS OCT_STATE,
        MAX(CASE WHEN MONTH_NO=11 THEN PAYMENT_STATE END) AS NOV_STATE,
        MAX(CASE WHEN MONTH_NO=12 THEN PAYMENT_STATE END) AS DEC_STATE,
        MAX(CASE WHEN MONTH_NO=10 THEN BILL_DAY_VALUE END) AS OCT_BILL_DAY,
        MAX(CASE WHEN MONTH_NO=11 THEN BILL_DAY_VALUE END) AS NOV_BILL_DAY,
        MAX(CASE WHEN MONTH_NO=12 THEN BILL_DAY_VALUE END) AS DEC_BILL_DAY
 FROM checked GROUP BY ACCOUNT_KEY
), nov_cohort AS
(
 SELECT A.*,
        CASE WHEN REFERENCE_RUN_COUNT<>1 THEN 'CHECK_SPECIAL_REFERENCE'
             WHEN WINDOW_BAD_KEYS>0 THEN 'CHECK_SOURCE_GRAIN'
             ELSE 'EVALUATED' END AS REVIEW_STATUS,
        CASE WHEN REFERENCE_RUN_COUNT=1 AND WINDOW_BAD_KEYS=0 THEN 1 ELSE 0 END AS PUBLISH_RESULTS,
        CASE WHEN NOV_BILL_DAY=1 THEN 'DAY_01'
             WHEN NOV_BILL_DAY=2 THEN 'DAY_02'
             WHEN NOV_BILL_DAY=3 THEN 'DAY_03'
             WHEN NOV_BILL_DAY BETWEEN 3 AND 31 AND NOV_BILL_DAY=FLOOR(NOV_BILL_DAY)
                  THEN 'DAYS_03_31'
             WHEN NOV_BILL_DAY IS NULL THEN 'MISSING_BILL_DAY'
             ELSE 'INVALID_BILL_DAY' END AS BILL_DAY_DETAIL,
        CASE WHEN NOV_BILL_DAY IN (1,2) THEN 'DAYS_01_02'
             WHEN NOV_BILL_DAY BETWEEN 3 AND 31 AND NOV_BILL_DAY=FLOOR(NOV_BILL_DAY)
                  THEN 'DAYS_03_31'
             ELSE 'MISSING_OR_INVALID' END AS BILL_DAY_GROUP,
        CASE WHEN NOV_STATE='VALID' AND NOV_PAYMENT=0 THEN 'NOV_ZERO'
             WHEN NOV_STATE='VALID' AND NOV_PAYMENT>0 THEN 'NOV_POSITIVE'
             WHEN NOV_STATE='VALID' AND NOV_PAYMENT<0 THEN 'NOV_NEGATIVE'
             WHEN NOV_STATE='MISSING' THEN 'NOV_MISSING'
             WHEN NOV_STATE='SPECIAL' THEN 'NOV_SPECIAL'
             ELSE 'NOV_UNVERIFIED' END AS PAYMENT_GROUP,
        CASE WHEN OCT_OBSERVED=1 AND DEC_OBSERVED=1
                   AND OCT_STATE='VALID' AND NOV_STATE='VALID' AND DEC_STATE='VALID'
             THEN 1 ELSE 0 END AS COMPLETE_VALID,
        CASE WHEN OCT_BILL_DAY=NOV_BILL_DAY AND DEC_BILL_DAY=NOV_BILL_DAY
                   AND NOV_BILL_DAY BETWEEN 1 AND 31 AND NOV_BILL_DAY=FLOOR(NOV_BILL_DAY)
             THEN 1 ELSE 0 END AS STABLE_BILL_DAY
 FROM account_months A WHERE NOV_OBSERVED=1
)
 , due_day_summary AS
(
 SELECT BILL_DAY_GROUP,MAX(PUBLISH_RESULTS) AS PUBLISH_RESULTS,
        SUM(CASE WHEN NOV_STATE='VALID' THEN 1 ELSE 0 END) AS VALID_NOV_COUNT,
        SUM(CASE WHEN NOV_STATE='VALID' AND NOV_PAYMENT=0 THEN 1 ELSE 0 END) AS NOV_ZERO_COUNT
 FROM nov_cohort GROUP BY BILL_DAY_GROUP
)
SELECT BILL_DAY_GROUP,
       CASE WHEN PUBLISH_RESULTS=1 THEN VALID_NOV_COUNT END AS VALID_NOV_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN NOV_ZERO_COUNT END AS NOV_ZERO_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN CAST(NOV_ZERO_COUNT AS FLOAT)/NULLIFZERO(VALID_NOV_COUNT) END AS NOV_ZERO_RATE
FROM due_day_summary ORDER BY 1;

