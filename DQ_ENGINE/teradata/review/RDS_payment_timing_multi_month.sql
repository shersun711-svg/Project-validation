        MAX(CASE WHEN MONTH_POSITION=1 THEN PAYMENT_STATE END) AS NEXT_STATE,
        MAX(CASE WHEN MONTH_POSITION=0 THEN BILL_DAY_VALUE END) AS TARGET_BILL_DAY
 FROM checked GROUP BY TARGET_MONTH,ACCOUNT_KEY
), target_cohort AS
(
 SELECT A.*,
        CASE WHEN REFERENCE_RUN_COUNT=1 AND WINDOW_BAD_KEYS=0 THEN 1 ELSE 0 END AS PUBLISH_RESULTS,
