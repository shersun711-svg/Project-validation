)
SELECT TARGET_MONTH,BILL_DAY_GROUP,
       CASE WHEN PUBLISH_RESULTS=1 THEN TARGET_ZERO_COUNT END AS TARGET_ZERO_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN MATCHED_ACCOUNT_COUNT END AS MATCHED_ACCOUNT_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN PREV_GT_NEXT_COUNT END AS PREV_GT_NEXT_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN CAST(PREV_GT_NEXT_COUNT AS FLOAT)/NULLIFZERO(MATCHED_ACCOUNT_COUNT) END AS PREV_GT_NEXT_SHARE
FROM payment_pattern_summary ORDER BY 1,2;
