/* MoM Issue 4: compact full-population evidence, no sampling.
   Run Query 1 and Query 2 SEPARATELY in Teradata SQL Assistant.
   Q1: Are June zero payments concentrated in due days 1-3?
   Q2: Among those June-zero accounts, how many paid more in May than July?

   Same logic/reference/source as the original detailed checks. Both use the
   fixed June 2024 population; missing May/July records are not treated as zero.
   Q1 zero rate uses valid June payments; missing/special payments are excluded
   from that denominator. Q2 MATCHED_ACCOUNT_COUNT requires valid observed
   payments in all three months. Its share uses that matched count, not all
   June-zero accounts. Rates/shares are fractions: 0.97 means 97%.
   Missing/invalid bill-day groups are retained if present.

   Shared special list: successful RDS account run 20 snapshot. Source must be
   fixed across queries. Reference and account/month integrity checks remain
   internal; NULL output counts mean a control failed and MUST NOT be treated
   as zero or used to close the finding. No permanent objects/data are changed.
   BILL_DAY is the attested repayment due day. These results corroborate a
   timing explanation; they do not verify exact receipt dates or special-value
   propagation. No new materiality threshold or automatic pass is imposed.
*/

/* QUERY 1: June zero payments by due-day group (four columns). */
WITH reference_runs AS
(
 SELECT DISTINCT RUN_ID FROM LAB_T_ORION_MVT.DQ_ACCOUNT_REVIEW
 WHERE PROJECT_ID='RDS' AND RUN_NUMBER=20 AND FIELD_TYPE='NUMERIC'
), reference_context AS
(
 SELECT COUNT(*) AS REFERENCE_RUN_COUNT FROM reference_runs
), special_values AS
(
 SELECT DISTINCT V.NUMERIC_VALUE
 FROM LAB_T_ORION_MVT.DQ_RUN_SPECIAL_VALUE V
 JOIN reference_runs R ON R.RUN_ID=V.RUN_ID
 WHERE V.FIELD_TYPE='NUMERIC' AND V.NUMERIC_VALUE IS NOT NULL
), source_values AS
(
 SELECT CAST(S.AGMT_ID AS VARCHAR(128)) AS ACCOUNT_KEY,
        CAST(S.FACT_DT AS DATE) AS POU_DT,
        EXTRACT(MONTH FROM S.FACT_DT) AS MONTH_NO,
        CAST(S.BILL_DAY AS FLOAT) AS BILL_DAY_VALUE,
        CAST(S.PROBE_CNP_AMT AS FLOAT) AS PAYMENT_VALUE
 FROM LAB_T_ORION_MVT.VW_RDS_PHASE2_FACT S
 WHERE S.FACT_DT>=DATE '2024-05-01' AND S.FACT_DT<DATE '2024-08-01'
), classified AS
(
 SELECT S.*,C.REFERENCE_RUN_COUNT,
        COUNT(*) OVER (PARTITION BY ACCOUNT_KEY,MONTH_NO) AS KEY_COUNT,
        CASE WHEN PAYMENT_VALUE IS NULL THEN 'MISSING'
             WHEN C.REFERENCE_RUN_COUNT<>1 THEN 'UNVERIFIED'
             WHEN V.NUMERIC_VALUE IS NOT NULL THEN 'SPECIAL'
             ELSE 'VALID' END AS PAYMENT_STATE
 FROM source_values S CROSS JOIN reference_context C
 LEFT JOIN special_values V ON S.PAYMENT_VALUE=V.NUMERIC_VALUE
), checked AS
(
 SELECT C.*,
        SUM(CASE WHEN ACCOUNT_KEY IS NULL OR TRIM(ACCOUNT_KEY)=''
                      OR KEY_COUNT<>1 THEN 1 ELSE 0 END) OVER () AS WINDOW_BAD_KEYS
 FROM classified C
), account_months AS
(
 SELECT ACCOUNT_KEY,MAX(REFERENCE_RUN_COUNT) AS REFERENCE_RUN_COUNT,
        MAX(WINDOW_BAD_KEYS) AS WINDOW_BAD_KEYS,
        MAX(CASE WHEN MONTH_NO=5 THEN 1 ELSE 0 END) AS MAY_OBSERVED,
        MAX(CASE WHEN MONTH_NO=6 THEN 1 ELSE 0 END) AS JUNE_OBSERVED,
        MAX(CASE WHEN MONTH_NO=7 THEN 1 ELSE 0 END) AS JULY_OBSERVED,
        MAX(CASE WHEN MONTH_NO=5 THEN PAYMENT_VALUE END) AS MAY_PAYMENT,
        MAX(CASE WHEN MONTH_NO=6 THEN PAYMENT_VALUE END) AS JUNE_PAYMENT,
        MAX(CASE WHEN MONTH_NO=7 THEN PAYMENT_VALUE END) AS JULY_PAYMENT,
        MAX(CASE WHEN MONTH_NO=5 THEN PAYMENT_STATE END) AS MAY_STATE,
        MAX(CASE WHEN MONTH_NO=6 THEN PAYMENT_STATE END) AS JUNE_STATE,
        MAX(CASE WHEN MONTH_NO=7 THEN PAYMENT_STATE END) AS JULY_STATE,
        MAX(CASE WHEN MONTH_NO=5 THEN BILL_DAY_VALUE END) AS MAY_BILL_DAY,
        MAX(CASE WHEN MONTH_NO=6 THEN BILL_DAY_VALUE END) AS JUNE_BILL_DAY,
        MAX(CASE WHEN MONTH_NO=7 THEN BILL_DAY_VALUE END) AS JULY_BILL_DAY
 FROM checked GROUP BY ACCOUNT_KEY
), june_cohort AS
(
 SELECT A.*,
        CASE WHEN REFERENCE_RUN_COUNT<>1 THEN 'CHECK_SPECIAL_REFERENCE'
             WHEN WINDOW_BAD_KEYS>0 THEN 'CHECK_SOURCE_GRAIN'
             ELSE 'EVALUATED' END AS REVIEW_STATUS,
        CASE WHEN REFERENCE_RUN_COUNT=1 AND WINDOW_BAD_KEYS=0 THEN 1 ELSE 0 END AS PUBLISH_RESULTS,
        CASE WHEN JUNE_BILL_DAY=1 THEN 'DAY_01'
             WHEN JUNE_BILL_DAY=2 THEN 'DAY_02'
             WHEN JUNE_BILL_DAY=3 THEN 'DAY_03'
             WHEN JUNE_BILL_DAY BETWEEN 4 AND 31 AND JUNE_BILL_DAY=FLOOR(JUNE_BILL_DAY)
                  THEN 'DAYS_04_31'
             WHEN JUNE_BILL_DAY IS NULL THEN 'MISSING_BILL_DAY'
             ELSE 'INVALID_BILL_DAY' END AS BILL_DAY_DETAIL,
        CASE WHEN JUNE_BILL_DAY IN (1,2,3) THEN 'DAYS_01_03'
             WHEN JUNE_BILL_DAY BETWEEN 4 AND 31 AND JUNE_BILL_DAY=FLOOR(JUNE_BILL_DAY)
                  THEN 'DAYS_04_31'
             ELSE 'MISSING_OR_INVALID' END AS BILL_DAY_GROUP,
        CASE WHEN JUNE_STATE='VALID' AND JUNE_PAYMENT=0 THEN 'JUNE_ZERO'
             WHEN JUNE_STATE='VALID' AND JUNE_PAYMENT>0 THEN 'JUNE_POSITIVE'
             WHEN JUNE_STATE='VALID' AND JUNE_PAYMENT<0 THEN 'JUNE_NEGATIVE'
             WHEN JUNE_STATE='MISSING' THEN 'JUNE_MISSING'
             WHEN JUNE_STATE='SPECIAL' THEN 'JUNE_SPECIAL'
             ELSE 'JUNE_UNVERIFIED' END AS PAYMENT_GROUP,
        CASE WHEN MAY_OBSERVED=1 AND JULY_OBSERVED=1
                   AND MAY_STATE='VALID' AND JUNE_STATE='VALID' AND JULY_STATE='VALID'
             THEN 1 ELSE 0 END AS COMPLETE_VALID,
        CASE WHEN MAY_BILL_DAY=JUNE_BILL_DAY AND JULY_BILL_DAY=JUNE_BILL_DAY
                   AND JUNE_BILL_DAY BETWEEN 1 AND 31 AND JUNE_BILL_DAY=FLOOR(JUNE_BILL_DAY)
             THEN 1 ELSE 0 END AS STABLE_BILL_DAY
 FROM account_months A WHERE JUNE_OBSERVED=1
)
 , due_day_summary AS
(
 SELECT BILL_DAY_GROUP,MAX(PUBLISH_RESULTS) AS PUBLISH_RESULTS,
        SUM(CASE WHEN JUNE_STATE='VALID' THEN 1 ELSE 0 END) AS VALID_JUNE_COUNT,
        SUM(CASE WHEN JUNE_STATE='VALID' AND JUNE_PAYMENT=0 THEN 1 ELSE 0 END) AS JUNE_ZERO_COUNT
 FROM june_cohort GROUP BY BILL_DAY_GROUP
)
SELECT BILL_DAY_GROUP,
       CASE WHEN PUBLISH_RESULTS=1 THEN VALID_JUNE_COUNT END AS VALID_JUNE_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN JUNE_ZERO_COUNT END AS JUNE_ZERO_COUNT,
       CASE WHEN PUBLISH_RESULTS=1 THEN CAST(JUNE_ZERO_COUNT AS FLOAT)/NULLIFZERO(VALID_JUNE_COUNT) END AS JUNE_ZERO_RATE
FROM due_day_summary ORDER BY 1;

