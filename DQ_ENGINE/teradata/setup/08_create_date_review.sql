/* Additive upgrade, deploy once. Date extrema are FINAL REVIEW rows,
   not long-format profiling metrics. No date rows enter DQ_METRIC_RESULT.
   TIMESTAMP(6) preserves DATE and ordinary TIMESTAMP source extrema. */
CREATE MULTISET TABLE DQ_DB.DQ_DATE_REVIEW
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL,
    FIELD_NAME VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    PERIOD_LEVEL VARCHAR(8) CHARACTER SET LATIN NOT NULL
        CHECK (PERIOD_LEVEL IN ('OVERALL','YEARLY','MONTHLY')),
    PERIOD_VALUE VARCHAR(10) CHARACTER SET LATIN NOT NULL,
    EARLIEST_DATE TIMESTAMP(6),
    LATEST_DATE TIMESTAMP(6),
    EXECUTION_TIMESTAMP TIMESTAMP(6) NOT NULL
) PRIMARY INDEX (RUN_ID,FIELD_NAME)
UNIQUE INDEX (RUN_ID,FIELD_NAME,PERIOD_LEVEL,PERIOD_VALUE);
