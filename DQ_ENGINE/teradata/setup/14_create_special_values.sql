/* Additive deployment: run table CREATEs ONCE on existing/current installs.
   No existing configuration, results or history is replaced. Lists come from
   Excel, not seed SQL. Snapshot values make historical definitions auditable. */
CREATE MULTISET TABLE DQ_DB.DQ_SPECIAL_VALUE_CONFIG
(
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL,
    FIELD_TYPE VARCHAR(16) CHARACTER SET LATIN NOT NULL
        CHECK (FIELD_TYPE IN ('NUMERIC','CATEGORICAL')),
    SPECIAL_VALUE VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    NUMERIC_VALUE DECIMAL(38,10),
    ACTIVE_IND CHAR(1) NOT NULL CHECK (ACTIVE_IND IN ('Y','N')),
    CHECK ((FIELD_TYPE='NUMERIC' AND NUMERIC_VALUE IS NOT NULL)
        OR (FIELD_TYPE='CATEGORICAL' AND NUMERIC_VALUE IS NULL))
) UNIQUE PRIMARY INDEX (PROJECT_ID,FIELD_TYPE,SPECIAL_VALUE);

CREATE MULTISET TABLE DQ_DB.DQ_SPECIAL_VALUE_XLS_STAGE
(
    LOAD_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL,
    FIELD_TYPE VARCHAR(16) CHARACTER SET LATIN NOT NULL
        CHECK (FIELD_TYPE IN ('NUMERIC','CATEGORICAL')),
    SPECIAL_VALUE VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    ACTIVE_IND CHAR(1) NOT NULL CHECK (ACTIVE_IND IN ('Y','N'))
) UNIQUE PRIMARY INDEX (LOAD_ID,PROJECT_ID,FIELD_TYPE,SPECIAL_VALUE);

/* Marker distinguishes an explicitly empty sheet (clear the project list)
   from an older workbook without the sheet (preserve the existing list). */
CREATE MULTISET TABLE DQ_DB.DQ_SPECIAL_LOAD_STAGE
(
    LOAD_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL
) UNIQUE PRIMARY INDEX (LOAD_ID,PROJECT_ID);

CREATE MULTISET TABLE DQ_DB.DQ_RUN_SPECIAL_VALUE
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    FIELD_TYPE VARCHAR(16) CHARACTER SET LATIN NOT NULL,
    SPECIAL_VALUE VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    NUMERIC_VALUE DECIMAL(38,10)
) UNIQUE PRIMARY INDEX (RUN_ID,FIELD_TYPE,SPECIAL_VALUE);
