/* One-time additive upgrade. Stop profiling during this migration.
   Backfill short run numbers without rewriting historical IDs/results.
   A single locked counter assigns subsequent numbers across all projects. */
CREATE MULTISET TABLE DQ_DB.DQ_RUN_NUMBER
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    RUN_NUMBER BIGINT NOT NULL CHECK (RUN_NUMBER>0)
) UNIQUE PRIMARY INDEX (RUN_ID)
UNIQUE INDEX (RUN_NUMBER);

CREATE MULTISET TABLE DQ_DB.DQ_RUN_COUNTER
(
    COUNTER_KEY BYTEINT NOT NULL CHECK (COUNTER_KEY=1),
    LAST_NUMBER BIGINT NOT NULL CHECK (LAST_NUMBER>=0)
) UNIQUE PRIMARY INDEX (COUNTER_KEY);
INSERT INTO DQ_DB.DQ_RUN_COUNTER VALUES (1,0);
INSERT INTO DQ_DB.DQ_RUN_NUMBER
SELECT RUN_ID,CAST(ROW_NUMBER() OVER (ORDER BY START_TIME,RUN_ID) AS BIGINT)
FROM DQ_DB.DQ_RUN_LOG;
UPDATE DQ_DB.DQ_RUN_COUNTER
SET LAST_NUMBER=(SELECT COALESCE(MAX(RUN_NUMBER),0) FROM DQ_DB.DQ_RUN_NUMBER)
WHERE COUNTER_KEY=1;
