/* Deploy ONCE before replacing the shared classifier and completed view.
   Aggregate decisions only. RULE_NAME is the existing percentage metric name.
   Keep the legacy metric colour column for historical compatibility. */
CREATE MULTISET TABLE DQ_DB.DQ_RULE_RESULT
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL,
    FIELD_NAME VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    MODULE_NAME VARCHAR(32) CHARACTER SET LATIN NOT NULL,
    PERIOD_LEVEL VARCHAR(8) CHARACTER SET LATIN NOT NULL
        CHECK (PERIOD_LEVEL IN ('OVERALL','YEARLY','MONTHLY')),
    PERIOD_VALUE VARCHAR(10) CHARACTER SET LATIN NOT NULL,
    RULE_NAME VARCHAR(32) CHARACTER SET LATIN NOT NULL,
    OBSERVED_VALUE DECIMAL(38,10),
    GREEN_THRESHOLD DECIMAL(9,4),
    RED_THRESHOLD DECIMAL(9,4),
    STATUS VARCHAR(16) CHARACTER SET LATIN NOT NULL
        CHECK (STATUS IN ('GREEN','AMBER','RED','NOT_EVALUATED')),
    REASON VARCHAR(128) CHARACTER SET LATIN,
    CHECK ((STATUS='NOT_EVALUATED' AND REASON IS NOT NULL)
        OR (STATUS<>'NOT_EVALUATED' AND REASON IS NULL))
) PRIMARY INDEX (RUN_ID,FIELD_NAME)
UNIQUE INDEX (RUN_ID,FIELD_NAME,MODULE_NAME,PERIOD_LEVEL,PERIOD_VALUE,RULE_NAME);

