CREATE MULTISET TABLE DQ_DB.DQ_METRIC_RESULT
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    PROJECT_ID VARCHAR(30) CHARACTER SET LATIN NOT NULL,
    FIELD_NAME VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    FIELD_TYPE VARCHAR(16) CHARACTER SET LATIN NOT NULL,
    MODULE_NAME VARCHAR(32) CHARACTER SET LATIN NOT NULL,
    PERIOD_LEVEL VARCHAR(8) CHARACTER SET LATIN NOT NULL
        CHECK (PERIOD_LEVEL IN ('OVERALL','YEARLY','MONTHLY')),
    PERIOD_VALUE VARCHAR(10) CHARACTER SET LATIN NOT NULL,
    METRIC_NAME VARCHAR(32) CHARACTER SET LATIN NOT NULL,
    METRIC_VALUE DECIMAL(38,10),
    DATE_METRIC_VALUE TIMESTAMP(6), /* Reserved for later date module. */
    IS_PERCENTAGE CHAR(1) NOT NULL CHECK (IS_PERCENTAGE IN ('Y','N')),
    RATE_NUMERATOR BIGINT,
    RATE_DENOMINATOR BIGINT,
    DQ_COLOUR VARCHAR(16) CHARACTER SET LATIN,
    EXECUTION_TIMESTAMP TIMESTAMP(6) NOT NULL
) PRIMARY INDEX (RUN_ID, FIELD_NAME)
UNIQUE INDEX (RUN_ID, FIELD_NAME, MODULE_NAME, PERIOD_LEVEL, PERIOD_VALUE, METRIC_NAME);

/* Immutable selection per run; retry checks the configuration again. */
CREATE MULTISET TABLE DQ_DB.DQ_RUN_FIELD_CONFIG
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    FIELD_NAME VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    FIELD_TYPE VARCHAR(16) CHARACTER SET LATIN NOT NULL,
    FIELD_ORDINAL INTEGER NOT NULL
) PRIMARY INDEX (RUN_ID)
UNIQUE INDEX (RUN_ID, FIELD_NAME);
