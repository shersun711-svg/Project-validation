/* Deploy ONCE after the current engine schema. No raw source rows are stored.
   Shared unrounded FLOAT statistics prevent rounded Basic result values from
   changing strict outlier decisions. Fixed rule: mean +/- 3*population deviation. */
CREATE MULTISET TABLE DQ_DB.DQ_NUMERIC_STATISTICS
(
    RUN_ID CHAR(36) CHARACTER SET LATIN NOT NULL,
    FIELD_NAME VARCHAR(128) CHARACTER SET LATIN NOT NULL,
    PERIOD_LEVEL VARCHAR(8) CHARACTER SET LATIN NOT NULL
        CHECK (PERIOD_LEVEL IN ('OVERALL','YEARLY','MONTHLY')),
    PERIOD_VALUE VARCHAR(10) CHARACTER SET LATIN NOT NULL,
    TOTAL_COUNT BIGINT NOT NULL,
    VALID_COUNT BIGINT NOT NULL,
    MEAN_VALUE FLOAT,
    STDDEV_VALUE FLOAT,
    CHECK (VALID_COUNT>=0 AND TOTAL_COUNT>=VALID_COUNT)
) PRIMARY INDEX (RUN_ID,FIELD_NAME)
UNIQUE INDEX (RUN_ID,FIELD_NAME,PERIOD_LEVEL,PERIOD_VALUE);

