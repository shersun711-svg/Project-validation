/* Never expose partial RUNNING/FAILED results as a completed report. */
REPLACE VIEW DQ_DB.DQ_COMPLETED_RESULT AS
SELECT R.RUN_ID,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,R.MODULE_NAME,
       R.PERIOD_LEVEL,R.PERIOD_VALUE,R.METRIC_NAME,R.METRIC_VALUE,
       R.DATE_METRIC_VALUE,R.IS_PERCENTAGE,R.RATE_NUMERATOR,R.RATE_DENOMINATOR,
       COALESCE(Q.STATUS,R.DQ_COLOUR) AS DQ_COLOUR,
       R.EXECUTION_TIMESTAMP,N.RUN_NUMBER
FROM DQ_DB.DQ_METRIC_RESULT R
JOIN DQ_DB.DQ_RUN_LOG L ON R.RUN_ID=L.RUN_ID AND R.PROJECT_ID=L.PROJECT_ID
LEFT JOIN DQ_DB.DQ_RULE_RESULT Q
 ON R.RUN_ID=Q.RUN_ID AND R.PROJECT_ID=Q.PROJECT_ID AND R.FIELD_NAME=Q.FIELD_NAME
 AND R.MODULE_NAME=Q.MODULE_NAME AND R.PERIOD_LEVEL=Q.PERIOD_LEVEL
 AND R.PERIOD_VALUE=Q.PERIOD_VALUE AND R.METRIC_NAME=Q.RULE_NAME
LEFT JOIN DQ_DB.DQ_RUN_NUMBER N ON R.RUN_ID=N.RUN_ID
WHERE L.STATUS = 'SUCCEEDED';

REPLACE VIEW DQ_DB.DQ_RUN_SUMMARY AS
SELECT R.RUN_ID, R.PROJECT_ID, R.MODULE_NAME, R.FIELD_TYPE,
       COUNT(DISTINCT R.FIELD_NAME) AS FIELDS_TESTED,
       SUM(CAST(1 AS BIGINT)) AS METRIC_RESULT_COUNT,
       SUM(CAST(CASE WHEN R.DQ_COLOUR = 'GREEN' THEN 1 ELSE 0 END AS BIGINT)) AS GREEN_COUNT,
       SUM(CAST(CASE WHEN R.DQ_COLOUR = 'AMBER' THEN 1 ELSE 0 END AS BIGINT)) AS AMBER_COUNT,
       SUM(CAST(CASE WHEN R.DQ_COLOUR = 'RED' THEN 1 ELSE 0 END AS BIGINT)) AS RED_COUNT,
       R.RUN_NUMBER
FROM DQ_DB.DQ_COMPLETED_RESULT R
GROUP BY 1,2,3,4,10;
