/* Date-specific final review: four requested metrics and their classification.
   Only successful runs. Availability stays separate in DQ_BASIC_REVIEW as
   FIRST_AVAILABLE_FACT_DT/LAST_AVAILABLE_FACT_DT (OVERALL only). */
REPLACE VIEW DQ_DB.DQ_DATE_BASIC_REVIEW AS
SELECT RUN_ID,RUN_NUMBER,PROJECT_ID,FIELD_NAME,PERIOD_LEVEL,PERIOD_VALUE,
       TOTAL_COUNT,NON_MISSING_COUNT,MISSING_COUNT,MISSING_RATE_PCT,MISSING_RATE_COLOUR
FROM DQ_DB.DQ_BASIC_REVIEW
WHERE FIELD_TYPE='DATE' AND MODULE_NAME='DATE_BASIC';
