/* Shared results-layer classification. The counts preserve exact boundary
   decisions even if a stored/displayed rate rounds to 1% or 5%.
   Per-run thresholds are captured before profiling for audit reproducibility. */
REPLACE VIEW DQ_DB.DQ_COLOUR_RULE AS
SELECT R.RUN_ID, R.FIELD_NAME, R.MODULE_NAME, R.PERIOD_LEVEL, R.PERIOD_VALUE,
       R.METRIC_NAME,
       CAST(CASE
           WHEN R.IS_PERCENTAGE <> 'Y' THEN NULL
           WHEN R.RATE_DENOMINATOR IS NULL OR R.RATE_DENOMINATOR = 0
               THEN 'NOT_EVALUATED'
           WHEN CAST(R.RATE_NUMERATOR AS DECIMAL(28,0)) * 100
                < CAST(R.RATE_DENOMINATOR AS DECIMAL(28,0)) * L.GREEN_THRESHOLD
               THEN 'GREEN'
           WHEN CAST(R.RATE_NUMERATOR AS DECIMAL(28,0)) * 100
                < CAST(R.RATE_DENOMINATOR AS DECIMAL(28,0)) * L.RED_THRESHOLD
               THEN 'AMBER'
           ELSE 'RED'
       END AS VARCHAR(16)) AS DQ_COLOUR
FROM DQ_DB.DQ_METRIC_RESULT R
JOIN DQ_DB.DQ_RUN_LOG L ON R.RUN_ID = L.RUN_ID;

REPLACE PROCEDURE DQ_DB.SP_DQ_CLASSIFY (IN P_RUN_ID CHAR(36))
SQL SECURITY INVOKER
BEGIN
    UPDATE R
    FROM DQ_DB.DQ_METRIC_RESULT AS R, DQ_DB.DQ_COLOUR_RULE AS C
    SET DQ_COLOUR = C.DQ_COLOUR
    WHERE R.RUN_ID = P_RUN_ID AND R.RUN_ID = C.RUN_ID
      AND R.FIELD_NAME = C.FIELD_NAME AND R.MODULE_NAME = C.MODULE_NAME
      AND R.PERIOD_LEVEL = C.PERIOD_LEVEL AND R.PERIOD_VALUE = C.PERIOD_VALUE
      AND R.METRIC_NAME = C.METRIC_NAME;
END;
