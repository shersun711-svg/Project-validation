/* Independent field-level comparisons of successful MONTHLY profiling results.
   No source reads, new tables, result writes or rule evaluations.
   Filter PROJECT_ID, RUN_NUMBER and COMPARISON_TYPE when reviewing this view.
   The month key uses actual POU_DT calendar months, not a row offset or day gap.
   POU_DT retains the latest actual source snapshot date when it was captured.
   UNKNOWN periods and old results without captured POU_DT are excluded.
   Values use the review's six-decimal precision; rate values are fractions.
   ABSOLUTE_CHANGE is signed current-minus-previous, in the metric's units.
   RELATIVE_CHANGE is a fraction, not a percentage. RATE_CHANGE_PP is in
   percentage points. No green/amber/red change thresholds have been agreed. */
REPLACE VIEW DQ_DB.DQ_FIELD_CHANGE_REVIEW AS
WITH comparison_seed AS
(
    /* Teradata requires each UNION branch to reference a table. Aggregate an
       existing metadata table to exactly one row, even when it is empty. */
    SELECT COUNT(*) AS SEED_COUNT FROM DQ_DB.DQ_RUN_NUMBER
),
comparison_types AS
(
    SELECT CAST('MOM' AS VARCHAR(3)) AS COMPARISON_TYPE,1 AS MONTH_GAP
    FROM comparison_seed
    UNION ALL
    SELECT CAST('YOY' AS VARCHAR(3)),12 FROM comparison_seed
),
saved AS
(
    SELECT R.RUN_ID,N.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,
           R.MODULE_NAME,R.PERIOD_VALUE,R.POU_DT,R.METRIC_NAME,R.METRIC_VALUE,
           R.IS_PERCENTAGE,R.RATE_NUMERATOR,R.RATE_DENOMINATOR,
           EXTRACT(YEAR FROM R.POU_DT)*12 + EXTRACT(MONTH FROM R.POU_DT) AS MONTH_KEY
    FROM DQ_DB.DQ_METRIC_RESULT R
    JOIN DQ_DB.DQ_RUN_LOG L ON R.RUN_ID=L.RUN_ID AND R.PROJECT_ID=L.PROJECT_ID
    LEFT JOIN DQ_DB.DQ_RUN_NUMBER N ON R.RUN_ID=N.RUN_ID
    WHERE L.STATUS='SUCCEEDED' AND R.PERIOD_LEVEL='MONTHLY'
      AND R.POU_DT IS NOT NULL
      AND R.MODULE_NAME IN ('NUMERIC_BASIC','NUMERIC_OUTLIERS',
                           'CATEGORICAL_BASIC','IDENTIFIER_BASIC','DATE_BASIC')
),
metrics AS
(
    SELECT RUN_ID,RUN_NUMBER,PROJECT_ID,FIELD_NAME,FIELD_TYPE,MODULE_NAME,
           PERIOD_VALUE,POU_DT,MONTH_KEY,
           CAST(CASE S.METRIC_NAME
             WHEN 'MINIMUM' THEN 'MIN_VALUE' WHEN 'MAXIMUM' THEN 'MAX_VALUE'
             WHEN 'MEAN' THEN 'MEAN_VALUE' WHEN 'STDDEV_POP' THEN 'STDDEV_VALUE'
             WHEN 'MISSING_RATE_PCT' THEN 'MISSING_RATE'
             WHEN 'SPECIAL_RATE_PCT' THEN 'SPECIAL_RATE'
             WHEN 'ZERO_RATE_PCT' THEN 'ZERO_RATE'
             WHEN 'OUTLIER_RATE_PCT' THEN 'OUTLIER_RATE'
             ELSE S.METRIC_NAME END AS VARCHAR(32)) AS METRIC_NAME,
           CAST(CASE WHEN IS_PERCENTAGE='Y' THEN METRIC_VALUE/100.000000
                     ELSE METRIC_VALUE END AS DECIMAL(38,6)) AS OBSERVED_VALUE,
           IS_PERCENTAGE AS IS_RATE
    FROM saved S
    WHERE S.METRIC_NAME IN ('TOTAL_COUNT','NON_MISSING_COUNT','MISSING_COUNT',
          'SPECIAL_COUNT','ZERO_COUNT','DISTINCT_COUNT','OUTLIER_COUNT',
          'OUTLIER_VALID_COUNT','MISSING_RATE_PCT','SPECIAL_RATE_PCT',
          'ZERO_RATE_PCT','OUTLIER_RATE_PCT','MINIMUM','MAXIMUM','MEAN','STDDEV_POP')
    UNION ALL
    /* These two populations are saved in the existing rate counts, rather
       than separate categorical/identifier metric rows. No recomputation. */
    SELECT RUN_ID,RUN_NUMBER,PROJECT_ID,FIELD_NAME,FIELD_TYPE,MODULE_NAME,
           PERIOD_VALUE,POU_DT,MONTH_KEY,CAST('TOTAL_COUNT' AS VARCHAR(32)),
           CAST(RATE_DENOMINATOR AS DECIMAL(38,6)),CAST('N' AS CHAR(1))
    FROM saved WHERE FIELD_TYPE IN ('CATEGORICAL','IDENTIFIER')
      AND METRIC_NAME='MISSING_RATE_PCT'
    UNION ALL
    SELECT RUN_ID,RUN_NUMBER,PROJECT_ID,FIELD_NAME,FIELD_TYPE,MODULE_NAME,
           PERIOD_VALUE,POU_DT,MONTH_KEY,CAST('NON_MISSING_COUNT' AS VARCHAR(32)),
           CAST(RATE_DENOMINATOR-RATE_NUMERATOR AS DECIMAL(38,6)),CAST('N' AS CHAR(1))
    FROM saved WHERE FIELD_TYPE IN ('CATEGORICAL','IDENTIFIER')
      AND METRIC_NAME='MISSING_RATE_PCT'
),
paired AS
(
    SELECT C.RUN_ID,C.RUN_NUMBER,C.PROJECT_ID,C.FIELD_NAME,C.FIELD_TYPE,
           C.MODULE_NAME,T.COMPARISON_TYPE,C.POU_DT,P.POU_DT AS PREVIOUS_POU_DT,
           C.PERIOD_VALUE AS PERIOD_MONTH,P.PERIOD_VALUE AS PREVIOUS_PERIOD_MONTH,
           C.METRIC_NAME,C.IS_RATE,C.OBSERVED_VALUE AS CURRENT_VALUE,
           P.OBSERVED_VALUE AS PREVIOUS_VALUE,
           C.OBSERVED_VALUE-P.OBSERVED_VALUE AS ABSOLUTE_CHANGE,
           CASE WHEN P.OBSERVED_VALUE<>0
                THEN CAST(C.OBSERVED_VALUE-P.OBSERVED_VALUE AS FLOAT)
                     /NULLIF(CAST(P.OBSERVED_VALUE AS FLOAT),0) END AS RELATIVE_VALUE,
           CAST(CASE WHEN P.RUN_ID IS NULL THEN 'NOT_EVALUATED'
                     WHEN C.OBSERVED_VALUE IS NULL OR P.OBSERVED_VALUE IS NULL
                       THEN 'NOT_EVALUATED' ELSE 'EVALUATED' END AS VARCHAR(16)) AS COMPARISON_STATUS,
           CAST(CASE WHEN P.RUN_ID IS NULL THEN 'Comparison month or metric is unavailable'
                     WHEN C.OBSERVED_VALUE IS NULL THEN 'Current metric value is unavailable'
                     WHEN P.OBSERVED_VALUE IS NULL THEN 'Previous metric value is unavailable'
                     WHEN P.OBSERVED_VALUE=0 THEN 'Relative change is undefined because previous value is zero'
                     ELSE NULL END AS VARCHAR(128)) AS BASE_REASON
    FROM metrics C
    CROSS JOIN comparison_types T
    LEFT JOIN metrics P
      ON C.RUN_ID=P.RUN_ID AND C.PROJECT_ID=P.PROJECT_ID
     AND C.FIELD_NAME=P.FIELD_NAME AND C.FIELD_TYPE=P.FIELD_TYPE
     AND C.MODULE_NAME=P.MODULE_NAME AND C.METRIC_NAME=P.METRIC_NAME
     AND C.MONTH_KEY-P.MONTH_KEY=T.MONTH_GAP
)
SELECT RUN_ID,RUN_NUMBER,PROJECT_ID,FIELD_NAME,FIELD_TYPE,MODULE_NAME,
       COMPARISON_TYPE,POU_DT,PREVIOUS_POU_DT,
       METRIC_NAME,IS_RATE,CURRENT_VALUE,PREVIOUS_VALUE,
       CAST(ABSOLUTE_CHANGE AS DECIMAL(38,6)) AS ABSOLUTE_CHANGE,
       CAST(CASE WHEN ABS(RELATIVE_VALUE)<1E32 THEN RELATIVE_VALUE END AS DECIMAL(38,6)) AS RELATIVE_CHANGE,
       CAST(CASE WHEN IS_RATE='Y' THEN ABSOLUTE_CHANGE*100.000000 END AS DECIMAL(38,6)) AS RATE_CHANGE_PP,
       COMPARISON_STATUS,
       CAST(CASE WHEN BASE_REASON IS NOT NULL THEN BASE_REASON
                 WHEN ABS(RELATIVE_VALUE)>=1E32 THEN 'Relative change exceeds supported display range'
                 ELSE NULL END AS VARCHAR(128)) AS REASON
FROM paired;

GRANT SELECT ON DQ_DB.DQ_FIELD_CHANGE_REVIEW TO DQ_DB;
