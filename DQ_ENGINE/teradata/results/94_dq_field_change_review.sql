    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.ABSOLUTE_CHANGE END) AS MIN_VALUE_MOM_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.RELATIVE_CHANGE END) AS MIN_VALUE_MOM_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.CHANGE_FLAG END) AS MIN_VALUE_MOM_FLAG,
    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.ABSOLUTE_CHANGE END) AS MIN_VALUE_YOY_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.RELATIVE_CHANGE END) AS MIN_VALUE_YOY_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MIN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.CHANGE_FLAG END) AS MIN_VALUE_YOY_FLAG,
    /* MAX_VALUE */
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE'
             THEN C.CURRENT_VALUE END) AS MAX_VALUE,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.ABSOLUTE_CHANGE END) AS MAX_VALUE_MOM_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.RELATIVE_CHANGE END) AS MAX_VALUE_MOM_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.CHANGE_FLAG END) AS MAX_VALUE_MOM_FLAG,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.ABSOLUTE_CHANGE END) AS MAX_VALUE_YOY_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.RELATIVE_CHANGE END) AS MAX_VALUE_YOY_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MAX_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.CHANGE_FLAG END) AS MAX_VALUE_YOY_FLAG,
    /* MEAN_VALUE */
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE'
             THEN C.CURRENT_VALUE END) AS MEAN_VALUE,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.ABSOLUTE_CHANGE END) AS MEAN_VALUE_MOM_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.RELATIVE_CHANGE END) AS MEAN_VALUE_MOM_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.CHANGE_FLAG END) AS MEAN_VALUE_MOM_FLAG,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.ABSOLUTE_CHANGE END) AS MEAN_VALUE_YOY_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.RELATIVE_CHANGE END) AS MEAN_VALUE_YOY_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'MEAN_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.CHANGE_FLAG END) AS MEAN_VALUE_YOY_FLAG,
    /* STDDEV_VALUE */
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE'
             THEN C.CURRENT_VALUE END) AS STDDEV_VALUE,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.ABSOLUTE_CHANGE END) AS STDDEV_VALUE_MOM_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.RELATIVE_CHANGE END) AS STDDEV_VALUE_MOM_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'MOM'
             THEN C.CHANGE_FLAG END) AS STDDEV_VALUE_MOM_FLAG,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.ABSOLUTE_CHANGE END) AS STDDEV_VALUE_YOY_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.RELATIVE_CHANGE END) AS STDDEV_VALUE_YOY_REL_CHANGE,
    MAX(CASE WHEN C.METRIC_NAME = 'STDDEV_VALUE' AND C.COMPARISON_TYPE = 'YOY'
             THEN C.CHANGE_FLAG END) AS STDDEV_VALUE_YOY_FLAG,
    /* Existing evaluation statuses: absolute differences */
    CAST(
        CASE
            WHEN MAX(CASE
                WHEN C.COMPARISON_TYPE = 'MOM'
                 AND C.COMPARISON_STATUS = 'EVALUATED'
                THEN 1 ELSE 0 END) = 0
                THEN 'NOT_EVALUATED'
            WHEN MAX(CASE
                WHEN C.COMPARISON_TYPE = 'MOM'
                 AND C.COMPARISON_STATUS = 'NOT_EVALUATED'
                THEN 1 ELSE 0 END) = 1
                THEN 'PARTIALLY_EVALUATED'
            ELSE 'EVALUATED'
        END AS VARCHAR(20)
    ) AS MOM_STATUS,
    CAST(
        CASE
            WHEN MAX(CASE
                WHEN C.COMPARISON_TYPE = 'YOY'
                 AND C.COMPARISON_STATUS = 'EVALUATED'
                THEN 1 ELSE 0 END) = 0
                THEN 'NOT_EVALUATED'
            WHEN MAX(CASE
                WHEN C.COMPARISON_TYPE = 'YOY'
                 AND C.COMPARISON_STATUS = 'NOT_EVALUATED'
                THEN 1 ELSE 0 END) = 1
                THEN 'PARTIALLY_EVALUATED'
            ELSE 'EVALUATED'
        END AS VARCHAR(20)
    ) AS YOY_STATUS
FROM changes C
GROUP BY
    C.RUN_ID,
    C.RUN_NUMBER,
    C.PROJECT_ID,
    C.FIELD_NAME,
    C.FIELD_TYPE,
    C.POU_DT;

