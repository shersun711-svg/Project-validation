/* Synchronized with the user-supplied deployed view definition, 2026-10-20.
   Replace DQ_DB with the approved schema in a deployment copy.
   Reads saved monthly profiling results only; no profiling rerun required.
   Current, absolute/relative MoM/YoY changes and movement flags share one row.
   Movement thresholds in this supplied definition are 10% and 20% in magnitude.
   MOM_STATUS/YOY_STATUS still describe absolute-difference availability.
   Filter PROJECT_ID and RUN_NUMBER when querying. */
REPLACE VIEW DQ_DB.DQ_FIELD_CHANGE_REVIEW AS
WITH comparison_seed AS
(
    SELECT COUNT(*) AS SEED_COUNT
    FROM DQ_DB.DQ_RUN_NUMBER
),
comparison_types AS
(
    SELECT
        CAST('MOM' AS VARCHAR(3)) AS COMPARISON_TYPE,
        1 AS MONTH_GAP
    FROM comparison_seed
    UNION ALL
    SELECT
        CAST('YOY' AS VARCHAR(3)),
        12
    FROM comparison_seed
),
saved AS
(
    SELECT
        R.RUN_ID,
        N.RUN_NUMBER,
        R.PROJECT_ID,
        R.FIELD_NAME,
        R.FIELD_TYPE,
        R.MODULE_NAME,
        R.PERIOD_VALUE,
        R.POU_DT,
        R.METRIC_NAME,
        R.METRIC_VALUE,
        R.IS_PERCENTAGE,
        R.RATE_NUMERATOR,
        R.RATE_DENOMINATOR,
        EXTRACT(YEAR FROM R.POU_DT) * 12
            + EXTRACT(MONTH FROM R.POU_DT) AS MONTH_KEY
    FROM DQ_DB.DQ_METRIC_RESULT R
    JOIN DQ_DB.DQ_RUN_LOG L
      ON R.RUN_ID = L.RUN_ID
     AND R.PROJECT_ID = L.PROJECT_ID
    LEFT JOIN DQ_DB.DQ_RUN_NUMBER N
      ON R.RUN_ID = N.RUN_ID
    WHERE L.STATUS = 'SUCCEEDED'
      AND R.PERIOD_LEVEL = 'MONTHLY'
      AND R.POU_DT IS NOT NULL
      AND R.MODULE_NAME IN
          ('NUMERIC_BASIC', 'NUMERIC_OUTLIERS',
           'CATEGORICAL_BASIC', 'IDENTIFIER_BASIC', 'DATE_BASIC')
),
metrics AS
(
    SELECT
        RUN_ID,
        RUN_NUMBER,
        PROJECT_ID,
        FIELD_NAME,
        FIELD_TYPE,
        MODULE_NAME,
        PERIOD_VALUE,
        POU_DT,
        MONTH_KEY,
        CAST(
            CASE S.METRIC_NAME
                WHEN 'MINIMUM'          THEN 'MIN_VALUE'
                WHEN 'MAXIMUM'          THEN 'MAX_VALUE'
                WHEN 'MEAN'             THEN 'MEAN_VALUE'
                WHEN 'STDDEV_POP'       THEN 'STDDEV_VALUE'
                WHEN 'MISSING_RATE_PCT' THEN 'MISSING_RATE'
                WHEN 'SPECIAL_RATE_PCT' THEN 'SPECIAL_RATE'
                WHEN 'ZERO_RATE_PCT'    THEN 'ZERO_RATE'
                WHEN 'OUTLIER_RATE_PCT' THEN 'OUTLIER_RATE'
                ELSE S.METRIC_NAME
            END AS VARCHAR(32)
        ) AS METRIC_NAME,
        CAST(
            CASE
                WHEN IS_PERCENTAGE = 'Y'
                    THEN METRIC_VALUE / 100.000000
                ELSE METRIC_VALUE
            END AS DECIMAL(38,6)
        ) AS OBSERVED_VALUE
    FROM saved S
    WHERE S.METRIC_NAME IN
          ('TOTAL_COUNT', 'NON_MISSING_COUNT', 'MISSING_COUNT',
           'SPECIAL_COUNT', 'ZERO_COUNT', 'DISTINCT_COUNT',
           'OUTLIER_COUNT', 'OUTLIER_VALID_COUNT',
           'MISSING_RATE_PCT', 'SPECIAL_RATE_PCT',
           'ZERO_RATE_PCT', 'OUTLIER_RATE_PCT',
           'MINIMUM', 'MAXIMUM', 'MEAN', 'STDDEV_POP')
    UNION ALL
    SELECT
        RUN_ID,
        RUN_NUMBER,
        PROJECT_ID,
        FIELD_NAME,
        FIELD_TYPE,
        MODULE_NAME,
        PERIOD_VALUE,
        POU_DT,
        MONTH_KEY,
        CAST('TOTAL_COUNT' AS VARCHAR(32)),
        CAST(RATE_DENOMINATOR AS DECIMAL(38,6))
    FROM saved
    WHERE FIELD_TYPE IN ('CATEGORICAL', 'IDENTIFIER')
      AND METRIC_NAME = 'MISSING_RATE_PCT'
    UNION ALL
    SELECT
        RUN_ID,
        RUN_NUMBER,
        PROJECT_ID,
        FIELD_NAME,
        FIELD_TYPE,
        MODULE_NAME,
        PERIOD_VALUE,
        POU_DT,
        MONTH_KEY,
        CAST('NON_MISSING_COUNT' AS VARCHAR(32)),
        CAST(RATE_DENOMINATOR - RATE_NUMERATOR AS DECIMAL(38,6))
    FROM saved
    WHERE FIELD_TYPE IN ('CATEGORICAL', 'IDENTIFIER')
      AND METRIC_NAME = 'MISSING_RATE_PCT'
),
paired AS
(
    SELECT
        C.RUN_ID,
        C.RUN_NUMBER,
        C.PROJECT_ID,
        C.FIELD_NAME,
        C.FIELD_TYPE,
        C.MODULE_NAME,
        T.COMPARISON_TYPE,
        C.POU_DT,
        P.POU_DT AS PREVIOUS_POU_DT,
        C.METRIC_NAME,
        C.OBSERVED_VALUE AS CURRENT_VALUE,
        P.OBSERVED_VALUE AS PREVIOUS_VALUE,
        C.OBSERVED_VALUE - P.OBSERVED_VALUE AS ABSOLUTE_CHANGE,
        /* Both zero: relative movement is zero.
           Missing values remain NULL.
           Zero previous with nonzero current remains NULL. */
        CASE
            WHEN C.OBSERVED_VALUE IS NULL
              OR P.OBSERVED_VALUE IS NULL
                THEN CAST(NULL AS FLOAT)
            WHEN C.OBSERVED_VALUE = 0
             AND P.OBSERVED_VALUE = 0
                THEN CAST(0 AS FLOAT)
            ELSE
                CAST(C.OBSERVED_VALUE - P.OBSERVED_VALUE AS FLOAT)
                / NULLIF(CAST(P.OBSERVED_VALUE AS FLOAT), 0)
        END AS RELATIVE_VALUE,
        CAST(
            CASE
                WHEN P.RUN_ID IS NULL
                  OR C.OBSERVED_VALUE IS NULL
                  OR P.OBSERVED_VALUE IS NULL
                    THEN 'NOT_EVALUATED'
                ELSE 'EVALUATED'
            END AS VARCHAR(16)
        ) AS COMPARISON_STATUS
    FROM metrics C
    CROSS JOIN comparison_types T
    LEFT JOIN metrics P
      ON C.RUN_ID = P.RUN_ID
     AND C.PROJECT_ID = P.PROJECT_ID
     AND C.FIELD_NAME = P.FIELD_NAME
     AND C.FIELD_TYPE = P.FIELD_TYPE
     AND C.MODULE_NAME = P.MODULE_NAME
     AND C.METRIC_NAME = P.METRIC_NAME
     AND C.MONTH_KEY - P.MONTH_KEY = T.MONTH_GAP
),
changes AS
(
    SELECT
        RUN_ID,
        RUN_NUMBER,
        PROJECT_ID,
        FIELD_NAME,
        FIELD_TYPE,
        MODULE_NAME,
        COMPARISON_TYPE,
        POU_DT,
        PREVIOUS_POU_DT,
        METRIC_NAME,
        CURRENT_VALUE,
        CAST(ABSOLUTE_CHANGE AS DECIMAL(38,6)) AS ABSOLUTE_CHANGE,
        CAST(
            CASE
                WHEN ABS(RELATIVE_VALUE) < 1E32
                    THEN RELATIVE_VALUE
            END AS DECIMAL(38,6)
        ) AS RELATIVE_CHANGE,
        CAST(
            CASE
                WHEN COMPARISON_STATUS = 'NOT_EVALUATED'
                    THEN 'NOT_EVALUATED'
                WHEN PREVIOUS_VALUE = 0
                 AND CURRENT_VALUE <> 0
                    THEN 'ZERO_BASE_MOVEMENT'
                WHEN RELATIVE_VALUE IS NULL
                    THEN 'NOT_EVALUATED'
                WHEN ABS(RELATIVE_VALUE) >= 0.20
                    THEN 'HIGH_RELATIVE_MOVEMENT'
                WHEN ABS(RELATIVE_VALUE) >= 0.10
                    THEN 'MODERATE_RELATIVE_MOVEMENT'
                ELSE 'LOW_RELATIVE_MOVEMENT'
            END AS VARCHAR(64)
        ) AS CHANGE_FLAG,
        COMPARISON_STATUS
    FROM paired
)
