/* Wide field-level review: one row per run, field and actual monthly POU_DT.
   Reads saved-result comparison view 94 only; no source scan or new storage.
   Each metric has its current value, MOM_CHANGE and YOY_CHANGE side by side.
   Changes are signed current-minus-previous, not relative changes/percentages.
   Rates and rate changes are fractions; counts are integers, other values 6dp.
   NULL means not applicable or unavailable; never replace it with zero.
   Status covers only the metrics present, combining Basic and Outliers.
   PARTIALLY_EVALUATED means some present metrics lack an evaluable comparison.
   Detailed previous values, relative changes and reasons remain in view 94.
   Filter PROJECT_ID and RUN_NUMBER when reviewing; no profiling rerun needed. */
REPLACE VIEW DQ_DB.DQ_CHANGE_REVIEW AS
SELECT C.RUN_ID,C.RUN_NUMBER,C.PROJECT_ID,C.FIELD_NAME,C.FIELD_TYPE,
       CASE WHEN MAX(CASE WHEN C.MODULE_NAME='NUMERIC_BASIC' THEN 1 ELSE 0 END)=1
                  AND MAX(CASE WHEN C.MODULE_NAME='NUMERIC_OUTLIERS' THEN 1 ELSE 0 END)=1
            THEN 'NUMERIC_BASIC+OUTLIERS' ELSE MAX(C.MODULE_NAME) END AS MODULE_NAME,
       CAST('MONTHLY' AS VARCHAR(8)) AS PERIOD_LEVEL,C.POU_DT,
       MAX(CASE WHEN C.COMPARISON_TYPE='MOM' THEN C.PREVIOUS_POU_DT END) AS MOM_PREVIOUS_POU_DT,
       MAX(CASE WHEN C.COMPARISON_TYPE='YOY' THEN C.PREVIOUS_POU_DT END) AS YOY_PREVIOUS_POU_DT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='TOTAL_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS TOTAL_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='TOTAL_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS TOTAL_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='TOTAL_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS TOTAL_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='NON_MISSING_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS NON_MISSING_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='NON_MISSING_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS NON_MISSING_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='NON_MISSING_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS NON_MISSING_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS MISSING_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS MISSING_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS MISSING_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_RATE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS MISSING_RATE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_RATE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MISSING_RATE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MISSING_RATE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MISSING_RATE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS SPECIAL_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS SPECIAL_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS SPECIAL_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_RATE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS SPECIAL_RATE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_RATE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS SPECIAL_RATE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='SPECIAL_RATE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS SPECIAL_RATE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_VALID_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS OUTLIER_VALID_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_VALID_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS OUTLIER_VALID_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_VALID_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS OUTLIER_VALID_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS OUTLIER_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS OUTLIER_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS OUTLIER_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_RATE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS OUTLIER_RATE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_RATE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS OUTLIER_RATE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='OUTLIER_RATE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS OUTLIER_RATE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='DISTINCT_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS DISTINCT_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='DISTINCT_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS DISTINCT_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='DISTINCT_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS DISTINCT_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_COUNT' THEN C.CURRENT_VALUE END) AS DECIMAL(38,0)) AS ZERO_COUNT,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_COUNT' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS ZERO_COUNT_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_COUNT' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,0)) AS ZERO_COUNT_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_RATE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS ZERO_RATE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_RATE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS ZERO_RATE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='ZERO_RATE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS ZERO_RATE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MIN_VALUE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS MIN_VALUE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MIN_VALUE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MIN_VALUE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MIN_VALUE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MIN_VALUE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MAX_VALUE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS MAX_VALUE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MAX_VALUE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MAX_VALUE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MAX_VALUE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MAX_VALUE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MEAN_VALUE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS MEAN_VALUE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MEAN_VALUE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MEAN_VALUE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='MEAN_VALUE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS MEAN_VALUE_YOY_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='STDDEV_VALUE' THEN C.CURRENT_VALUE END) AS DECIMAL(38,6)) AS STDDEV_VALUE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='STDDEV_VALUE' AND C.COMPARISON_TYPE='MOM'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS STDDEV_VALUE_MOM_CHANGE,
       CAST(MAX(CASE WHEN C.METRIC_NAME='STDDEV_VALUE' AND C.COMPARISON_TYPE='YOY'
                     THEN C.ABSOLUTE_CHANGE END) AS DECIMAL(38,6)) AS STDDEV_VALUE_YOY_CHANGE,
       CAST(CASE WHEN MAX(CASE WHEN C.COMPARISON_TYPE='MOM'
                                        AND C.COMPARISON_STATUS='EVALUATED' THEN 1 ELSE 0 END)=0
                 THEN 'NOT_EVALUATED'
                 WHEN MAX(CASE WHEN C.COMPARISON_TYPE='MOM'
                                    AND C.COMPARISON_STATUS='NOT_EVALUATED' THEN 1 ELSE 0 END)=1
                 THEN 'PARTIALLY_EVALUATED' ELSE 'EVALUATED' END AS VARCHAR(20)) AS MOM_STATUS,
       CAST(CASE WHEN MAX(CASE WHEN C.COMPARISON_TYPE='YOY'
                                        AND C.COMPARISON_STATUS='EVALUATED' THEN 1 ELSE 0 END)=0
                 THEN 'NOT_EVALUATED'
                 WHEN MAX(CASE WHEN C.COMPARISON_TYPE='YOY'
                                    AND C.COMPARISON_STATUS='NOT_EVALUATED' THEN 1 ELSE 0 END)=1
                 THEN 'PARTIALLY_EVALUATED' ELSE 'EVALUATED' END AS VARCHAR(20)) AS YOY_STATUS
FROM DQ_DB.DQ_FIELD_CHANGE_REVIEW C
GROUP BY C.RUN_ID,C.RUN_NUMBER,C.PROJECT_ID,C.FIELD_NAME,C.FIELD_TYPE,C.POU_DT;

GRANT SELECT ON DQ_DB.DQ_CHANGE_REVIEW TO DQ_DB;
