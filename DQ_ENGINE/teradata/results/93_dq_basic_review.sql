/* Final review across NUMERIC/CATEGORICAL/IDENTIFIER/DATE.
   Only SUCCEEDED runs; one row per run, field and period. No source reads.
   EARLIEST_DATE/LATEST_DATE are overall non-missing field availability dates.
   Date-field value extrema use existing MINIMUM/MAXIMUM display columns.
   MINIMUM/MAXIMUM are VARCHAR(64) here; numeric storage/view 92 stay numeric.
   NULL columns mean not applicable (or an undefined calculated statistic).
   Categorical/identifier population counts are derived from saved rate counts. */
REPLACE VIEW DQ_DB.DQ_BASIC_REVIEW AS
SELECT R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,R.MODULE_NAME,
       R.PERIOD_LEVEL,R.PERIOD_VALUE,
       MAX(CASE WHEN R.METRIC_NAME='TOTAL_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR AS DECIMAL(38,10)) END) AS "TOTAL_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='NON_MISSING_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR-R.RATE_NUMERATOR AS DECIMAL(38,10)) END) AS "NON_MISSING_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_COUNT' THEN R.METRIC_VALUE END) AS "MISSING_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_RATE_PCT' THEN R.METRIC_VALUE END) AS "MISSING_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_RATE_PCT' THEN R.DQ_COLOUR END) AS "MISSING_RATE_COLOUR",
       MAX(CASE WHEN R.METRIC_NAME='DISTINCT_COUNT' THEN R.METRIC_VALUE END) AS "DISTINCT_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_COUNT' THEN R.METRIC_VALUE END) AS "ZERO_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_RATE_PCT' THEN R.METRIC_VALUE END) AS "ZERO_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_RATE_PCT' THEN R.DQ_COLOUR END) AS "ZERO_RATE_COLOUR",
       TRIM(CAST(MAX(CASE WHEN R.METRIC_NAME='MINIMUM' THEN R.METRIC_VALUE END) AS VARCHAR(64))) AS "MINIMUM",
       TRIM(CAST(MAX(CASE WHEN R.METRIC_NAME='MAXIMUM' THEN R.METRIC_VALUE END) AS VARCHAR(64))) AS "MAXIMUM",
       MAX(CASE WHEN R.METRIC_NAME='MEAN' THEN R.METRIC_VALUE END) AS "MEAN",
       MAX(CASE WHEN R.METRIC_NAME='STDDEV_SAMP' THEN R.METRIC_VALUE END) AS "STDDEV_SAMP",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.EARLIEST_DATE END) AS "EARLIEST_DATE",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.LATEST_DATE END) AS "LATEST_DATE"
FROM DQ_DB.DQ_COMPLETED_RESULT R
LEFT JOIN DQ_DB.DQ_FIELD_AVAILABILITY F ON R.RUN_ID=F.RUN_ID AND R.FIELD_NAME=F.FIELD_NAME
WHERE R.MODULE_NAME IN ('NUMERIC_BASIC','CATEGORICAL_BASIC','IDENTIFIER_BASIC')
GROUP BY R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,R.MODULE_NAME,
         R.PERIOD_LEVEL,R.PERIOD_VALUE
UNION ALL
SELECT D.RUN_ID,N.RUN_NUMBER,D.PROJECT_ID,D.FIELD_NAME,'DATE','DATE_BASIC',
       D.PERIOD_LEVEL,D.PERIOD_VALUE,
       CAST(NULL AS DECIMAL(38,10)),CAST(NULL AS DECIMAL(38,10)),
       CAST(NULL AS DECIMAL(38,10)),CAST(NULL AS DECIMAL(38,10)),
       CAST(NULL AS VARCHAR(16)),CAST(NULL AS DECIMAL(38,10)),
       CAST(NULL AS DECIMAL(38,10)),CAST(NULL AS DECIMAL(38,10)),
       CAST(NULL AS VARCHAR(16)),
       CAST(CAST(D.EARLIEST_DATE AS DATE FORMAT 'YYYY-MM-DD') AS VARCHAR(64)),
       CAST(CAST(D.LATEST_DATE AS DATE FORMAT 'YYYY-MM-DD') AS VARCHAR(64)),
       CAST(NULL AS DECIMAL(38,10)),CAST(NULL AS DECIMAL(38,10)),
       CASE WHEN D.PERIOD_LEVEL='OVERALL' THEN F.EARLIEST_DATE END,
       CASE WHEN D.PERIOD_LEVEL='OVERALL' THEN F.LATEST_DATE END
FROM DQ_DB.DQ_DATE_REVIEW D
JOIN DQ_DB.DQ_RUN_LOG L ON D.RUN_ID=L.RUN_ID
LEFT JOIN DQ_DB.DQ_RUN_NUMBER N ON D.RUN_ID=N.RUN_ID
LEFT JOIN DQ_DB.DQ_FIELD_AVAILABILITY F ON D.RUN_ID=F.RUN_ID AND D.FIELD_NAME=F.FIELD_NAME
WHERE L.STATUS='SUCCEEDED';
