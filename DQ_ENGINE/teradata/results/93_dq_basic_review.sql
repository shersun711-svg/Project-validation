/* Final review across NUMERIC/CATEGORICAL/IDENTIFIER/DATE.
   Only SUCCEEDED runs; one row per run, field and period. No source reads.
   FIRST_AVAILABLE_FACT_DT/LAST_AVAILABLE_FACT_DT are overall non-missing field availability dates.
   Date fields expose counts/missing percentage only; value extrema are absent.
   NULL columns mean not applicable (or an undefined calculated statistic).
   Categorical/identifier population counts are derived from saved rate counts. */
REPLACE VIEW DQ_DB.DQ_BASIC_REVIEW AS
SELECT R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,
       CASE
         WHEN MAX(CASE WHEN R.MODULE_NAME='NUMERIC_BASIC' THEN 1 ELSE 0 END)=1
          AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_PERCENTILES' THEN 1 ELSE 0 END)=1
          AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_OUTLIERS' THEN 1 ELSE 0 END)=1 THEN 'NUMERIC_BASIC+PCTL+OUTLIERS'
         WHEN MAX(CASE WHEN R.MODULE_NAME='NUMERIC_BASIC' THEN 1 ELSE 0 END)=1
          AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_OUTLIERS' THEN 1 ELSE 0 END)=1 THEN 'NUMERIC_BASIC+OUTLIERS'
         WHEN MAX(CASE WHEN R.MODULE_NAME='NUMERIC_PERCENTILES' THEN 1 ELSE 0 END)=1
          AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_OUTLIERS' THEN 1 ELSE 0 END)=1 THEN 'PERCENTILES+OUTLIERS'
         WHEN MAX(CASE WHEN R.MODULE_NAME='NUMERIC_BASIC' THEN 1 ELSE 0 END)=1
          AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_PERCENTILES' THEN 1 ELSE 0 END)=1 THEN 'NUMERIC_BASIC+PERCENTILES'
         ELSE MAX(R.MODULE_NAME) END AS MODULE_NAME,
       R.PERIOD_LEVEL,R.PERIOD_VALUE,
       MAX(CASE WHEN R.METRIC_NAME='TOTAL_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR AS DECIMAL(38,10)) END) AS "TOTAL_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='NON_MISSING_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR-R.RATE_NUMERATOR AS DECIMAL(38,10)) END) AS "NON_MISSING_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_COUNT' THEN R.METRIC_VALUE END) AS "MISSING_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_RATE_PCT' THEN R.METRIC_VALUE END) AS "MISSING_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='MISSING_RATE_PCT' THEN R.DQ_COLOUR END) AS "MISSING_RATE_COLOUR",
       MAX(CASE WHEN R.METRIC_NAME='SPECIAL_COUNT' THEN R.METRIC_VALUE END) AS "SPECIAL_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='SPECIAL_RATE_PCT' THEN R.METRIC_VALUE END) AS "SPECIAL_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='SPECIAL_RATE_PCT' THEN R.DQ_COLOUR END) AS "SPECIAL_RATE_COLOUR",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_VALID_COUNT' THEN R.METRIC_VALUE END) AS "OUTLIER_VALID_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_LOWER_BOUND' THEN R.METRIC_VALUE END) AS "OUTLIER_LOWER_BOUND",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_UPPER_BOUND' THEN R.METRIC_VALUE END) AS "OUTLIER_UPPER_BOUND",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_COUNT' THEN R.METRIC_VALUE END) AS "OUTLIER_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_RATE_PCT' THEN R.METRIC_VALUE END) AS "OUTLIER_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='OUTLIER_RATE_PCT' THEN R.DQ_COLOUR END) AS "OUTLIER_RATE_COLOUR",
       MAX(CASE WHEN R.METRIC_NAME='P1' THEN R.METRIC_VALUE END) AS "P1",
       MAX(CASE WHEN R.METRIC_NAME='P5' THEN R.METRIC_VALUE END) AS "P5",
       MAX(CASE WHEN R.METRIC_NAME='P25' THEN R.METRIC_VALUE END) AS "P25",
       MAX(CASE WHEN R.METRIC_NAME='P50' THEN R.METRIC_VALUE END) AS "P50",
       MAX(CASE WHEN R.METRIC_NAME='P75' THEN R.METRIC_VALUE END) AS "P75",
       MAX(CASE WHEN R.METRIC_NAME='P95' THEN R.METRIC_VALUE END) AS "P95",
       MAX(CASE WHEN R.METRIC_NAME='P99' THEN R.METRIC_VALUE END) AS "P99",
       MAX(CASE WHEN R.METRIC_NAME='DISTINCT_COUNT' THEN R.METRIC_VALUE END) AS "DISTINCT_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_COUNT' THEN R.METRIC_VALUE END) AS "ZERO_COUNT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_RATE_PCT' THEN R.METRIC_VALUE END) AS "ZERO_RATE_PCT",
       MAX(CASE WHEN R.METRIC_NAME='ZERO_RATE_PCT' THEN R.DQ_COLOUR END) AS "ZERO_RATE_COLOUR",
       MAX(CASE WHEN R.METRIC_NAME='MINIMUM' THEN R.METRIC_VALUE END) AS "MINIMUM",
       MAX(CASE WHEN R.METRIC_NAME='MAXIMUM' THEN R.METRIC_VALUE END) AS "MAXIMUM",
       MAX(CASE WHEN R.METRIC_NAME='MEAN' THEN R.METRIC_VALUE END) AS "MEAN",
       MAX(CASE WHEN R.METRIC_NAME='STDDEV_SAMP' THEN R.METRIC_VALUE END) AS "STDDEV_SAMP",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.EARLIEST_DATE END) AS "FIRST_AVAILABLE_FACT_DT",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.LATEST_DATE END) AS "LAST_AVAILABLE_FACT_DT"
FROM DQ_DB.DQ_COMPLETED_RESULT R
LEFT JOIN DQ_DB.DQ_FIELD_AVAILABILITY F ON R.RUN_ID=F.RUN_ID AND R.FIELD_NAME=F.FIELD_NAME
WHERE R.MODULE_NAME IN ('NUMERIC_BASIC','NUMERIC_OUTLIERS','NUMERIC_PERCENTILES','CATEGORICAL_BASIC','IDENTIFIER_BASIC','DATE_BASIC')
GROUP BY R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,
         R.PERIOD_LEVEL,R.PERIOD_VALUE;
