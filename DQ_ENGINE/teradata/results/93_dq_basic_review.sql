/* Final review across NUMERIC/CATEGORICAL/IDENTIFIER/DATE.
   Only SUCCEEDED runs; one row per run, field and period. No source reads.
   Rule classifications remain separate in DQ_RULE_RESULT.
   FIRST_AVAILABLE_FACT_DT/LAST_AVAILABLE_FACT_DT are overall non-missing field availability dates.
   Date fields expose counts/missing percentage only; value extrema are absent.
   NULL columns mean not applicable (or an undefined calculated statistic).
   Counts display as integers, percentages to 2 decimals and value statistics to
   4 decimals. DQ_METRIC_RESULT retains its original DECIMAL(38,10) precision. */
REPLACE VIEW DQ_DB.DQ_BASIC_REVIEW AS
SELECT R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,
       CASE WHEN MAX(CASE WHEN R.MODULE_NAME='NUMERIC_BASIC' THEN 1 ELSE 0 END)=1
                  AND MAX(CASE WHEN R.MODULE_NAME='NUMERIC_OUTLIERS' THEN 1 ELSE 0 END)=1
            THEN 'NUMERIC_BASIC+OUTLIERS' ELSE MAX(R.MODULE_NAME) END AS MODULE_NAME,
       R.PERIOD_LEVEL,R.PERIOD_VALUE,
       CAST(MAX(CASE WHEN R.METRIC_NAME='TOTAL_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR AS DECIMAL(38,10)) END) AS DECIMAL(38,0)) AS "TOTAL_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='NON_MISSING_COUNT' THEN R.METRIC_VALUE
                WHEN R.METRIC_NAME='MISSING_RATE_PCT'
                THEN CAST(R.RATE_DENOMINATOR-R.RATE_NUMERATOR AS DECIMAL(38,10)) END) AS DECIMAL(38,0)) AS "NON_MISSING_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='MISSING_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "MISSING_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='MISSING_RATE_PCT' THEN R.METRIC_VALUE END) AS DECIMAL(9,2)) AS "MISSING_RATE_PCT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='SPECIAL_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "SPECIAL_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='SPECIAL_RATE_PCT' THEN R.METRIC_VALUE END) AS DECIMAL(9,2)) AS "SPECIAL_RATE_PCT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='OUTLIER_VALID_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "OUTLIER_VALID_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='OUTLIER_LOWER_BOUND' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "OUTLIER_LOWER_BOUND",
       CAST(MAX(CASE WHEN R.METRIC_NAME='OUTLIER_UPPER_BOUND' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "OUTLIER_UPPER_BOUND",
       CAST(MAX(CASE WHEN R.METRIC_NAME='OUTLIER_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "OUTLIER_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='OUTLIER_RATE_PCT' THEN R.METRIC_VALUE END) AS DECIMAL(9,2)) AS "OUTLIER_RATE_PCT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='DISTINCT_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "DISTINCT_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='ZERO_COUNT' THEN R.METRIC_VALUE END) AS DECIMAL(38,0)) AS "ZERO_COUNT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='ZERO_RATE_PCT' THEN R.METRIC_VALUE END) AS DECIMAL(9,2)) AS "ZERO_RATE_PCT",
       CAST(MAX(CASE WHEN R.METRIC_NAME='MINIMUM' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "MINIMUM",
       CAST(MAX(CASE WHEN R.METRIC_NAME='MAXIMUM' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "MAXIMUM",
       CAST(MAX(CASE WHEN R.METRIC_NAME='MEAN' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "MEAN",
       CAST(MAX(CASE WHEN R.METRIC_NAME='STDDEV_SAMP' THEN R.METRIC_VALUE END) AS DECIMAL(38,4)) AS "STDDEV_SAMP",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.EARLIEST_DATE END) AS "FIRST_AVAILABLE_FACT_DT",
       MAX(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN F.LATEST_DATE END) AS "LAST_AVAILABLE_FACT_DT"
FROM DQ_DB.DQ_COMPLETED_RESULT R
LEFT JOIN DQ_DB.DQ_FIELD_AVAILABILITY F ON R.RUN_ID=F.RUN_ID AND R.FIELD_NAME=F.FIELD_NAME
WHERE R.MODULE_NAME IN ('NUMERIC_BASIC','NUMERIC_OUTLIERS','CATEGORICAL_BASIC','IDENTIFIER_BASIC','DATE_BASIC')
GROUP BY R.RUN_ID,R.RUN_NUMBER,R.PROJECT_ID,R.FIELD_NAME,R.FIELD_TYPE,
         R.PERIOD_LEVEL,R.PERIOD_VALUE;
