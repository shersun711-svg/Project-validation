/* Internal prerequisite when Outliers=Y and Numeric Basic=N. Aggregates only;
   no Basic metrics or availability are emitted. Uses the captured numeric
   selection and special list, preserving source filters and row multiplicity.
   Basic=Y supplies these same unrounded statistics in its existing aggregates.
   Three sequential aggregate statements avoid GROUPING SETS detail expansion. */
/* Internal source override lets Outliers reuse its materialized projection.
   The public two-argument wrapper below remains compatible. */
REPLACE PROCEDURE DQ_DB.SP_DQ_NUMERIC_STATS_SOURCE
    (IN P_RUN_ID CHAR(36),IN P_PROJECT_ID VARCHAR(30),
     IN P_SOURCE_DATABASE VARCHAR(128),IN P_SOURCE_TABLE VARCHAR(128),
     IN P_REPORTING_DATE_FIELD VARCHAR(128))
SQL SECURITY INVOKER
main: BEGIN
    DECLARE V_DB VARCHAR(128);
    DECLARE V_SOURCE VARCHAR(128);
    DECLARE V_DATE VARCHAR(128);
    DECLARE V_SIZE INTEGER;
    DECLARE V_ATTEMPT INTEGER;
    DECLARE V_COUNT INTEGER;
    DECLARE V_FIELDS INTEGER;
    DECLARE V_FIRST INTEGER DEFAULT 1;
    DECLARE V_LAST INTEGER;
    DECLARE V_BATCH INTEGER DEFAULT 0;
    DECLARE V_EXISTS INTEGER DEFAULT 0;
    DECLARE V_OWNED INTEGER DEFAULT 0;
    DECLARE V_SQL VARCHAR(32000);
    DECLARE V_PROJECTION VARCHAR(10000);
    DECLARE V_SOURCE_PROJECTION VARCHAR(16000);
    DECLARE V_LIST VARCHAR(8000);
    DECLARE V_SUFFIX VARCHAR(12);
    DECLARE V_FIELD VARCHAR(150);
    DECLARE V_LEVEL VARCHAR(200);
    DECLARE V_PERIOD VARCHAR(1000);
    DECLARE V_PASS INTEGER;
    DECLARE V_GROUP_QUERY VARCHAR(28000);
    DECLARE V_ERROR VARCHAR(2048) CHARACTER SET UNICODE;
    DECLARE V_ERROR_CODE INTEGER;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_ERROR=MESSAGE_TEXT;
        SET V_ERROR_CODE=SQLCODE;
        IF V_OWNED=1 THEN
            UPDATE DQ_DB.DQ_MODULE_LOG
               SET STATUS='FAILED',END_TIME=CURRENT_TIMESTAMP(6),ERROR_CODE=V_ERROR_CODE,ERROR_INFORMATION=V_ERROR
             WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_STATISTICS'
               AND ATTEMPT_NO=V_ATTEMPT AND STATUS='RUNNING';
        END IF;
        BEGIN
            DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET V_EXISTS=0;
            IF V_EXISTS=1 THEN CALL DBC.SysExecSQL('DROP TABLE DQ_NS_AGG'); END IF;
        END;
        RESIGNAL;
    END;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_LOG
     WHERE RUN_ID=P_RUN_ID AND PROJECT_ID=P_PROJECT_ID AND STATUS='RUNNING';
    IF V_COUNT<>1 THEN SIGNAL SQLSTATE 'U0002' SET MESSAGE_TEXT='Statistics require an active engine run'; END IF;
    SELECT SQL_BATCH_SIZE,ATTEMPT_NO INTO V_SIZE,V_ATTEMPT
      FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID=P_RUN_ID;
    IF P_SOURCE_DATABASE IS NULL OR P_SOURCE_TABLE IS NULL OR P_REPORTING_DATE_FIELD IS NULL
       OR REGEXP_SIMILAR(P_SOURCE_DATABASE,'^[A-Za-z_][A-Za-z0-9_]*$','c')<>1
       OR REGEXP_SIMILAR(P_SOURCE_TABLE,'^[A-Za-z_][A-Za-z0-9_]*$','c')<>1
       OR REGEXP_SIMILAR(P_REPORTING_DATE_FIELD,'^[A-Za-z_][A-Za-z0-9_]*$','c')<>1 THEN
        SIGNAL SQLSTATE 'U0004' SET MESSAGE_TEXT='Unsafe statistics source identifier';
    END IF;
    SET V_DB=P_SOURCE_DATABASE;
    SET V_SOURCE=P_SOURCE_TABLE;
    SET V_DATE=P_REPORTING_DATE_FIELD;
    SET V_SIZE=LEAST(V_SIZE,10);
    INSERT INTO DQ_DB.DQ_MODULE_LOG (RUN_ID,MODULE_NAME,ATTEMPT_NO,BATCH_ID,START_TIME,STATUS)
    VALUES (P_RUN_ID,'NUMERIC_STATISTICS',V_ATTEMPT,0,CURRENT_TIMESTAMP(6),'RUNNING');
    SET V_OWNED=1;
    SELECT COUNT(*) INTO V_FIELDS FROM DQ_DB.DQ_RUN_FIELD_CONFIG WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC';
    IF V_FIELDS=0 THEN SIGNAL SQLSTATE 'U0009' SET MESSAGE_TEXT='No eligible numeric fields for statistics'; END IF;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_FIELD_CONFIG
     WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC'
       AND REGEXP_SIMILAR(FIELD_NAME,'^[A-Za-z_][A-Za-z0-9_]*$','c')<>1;
    IF V_COUNT>0 THEN SIGNAL SQLSTATE 'U0011' SET MESSAGE_TEXT='Unsafe captured numeric identifier'; END IF;
    CALL DQ_DB.SP_DQ_SPECIAL_LIST(P_RUN_ID,'NUMERIC',V_LIST);
    SET V_LEVEL='CASE WHEN A.GY=1 THEN ''OVERALL'' WHEN A.GM=1 THEN ''YEARLY'' ELSE ''MONTHLY'' END';
    SET V_PERIOD='CASE WHEN A.GY=1 THEN ''ALL'' WHEN A.DQ_YEAR IS NULL THEN ''UNKNOWN'' '
      || 'WHEN A.GM=1 THEN TRIM(CAST(A.DQ_YEAR AS CHAR(4))) ELSE TRIM(CAST(A.DQ_YEAR AS CHAR(4)))'
      || '||''-''||SUBSTR(''00''||TRIM(CAST(A.DQ_MONTH AS VARCHAR(2))),'
      || 'CHARACTER_LENGTH(''00''||TRIM(CAST(A.DQ_MONTH AS VARCHAR(2))))-1,2) END';
    WHILE V_FIRST<=V_FIELDS DO
        SET V_BATCH=V_BATCH+1;
        SET V_LAST=LEAST(V_FIRST+V_SIZE-1,V_FIELDS);
        INSERT INTO DQ_DB.DQ_MODULE_LOG (RUN_ID,MODULE_NAME,ATTEMPT_NO,BATCH_ID,START_TIME,STATUS,FIELD_COUNT)
        VALUES (P_RUN_ID,'NUMERIC_STATISTICS',V_ATTEMPT,V_BATCH,CURRENT_TIMESTAMP(6),'RUNNING',V_LAST-V_FIRST+1);
        SET V_PROJECTION='';
        SET V_SOURCE_PROJECTION='"' || V_DATE || '" AS DQ_DT';
        FOR F AS FIELDS_CURSOR CURSOR FOR
            SELECT FIELD_NAME,FIELD_ORDINAL FROM DQ_DB.DQ_RUN_FIELD_CONFIG
             WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC' AND FIELD_ORDINAL BETWEEN V_FIRST AND V_LAST ORDER BY FIELD_ORDINAL
        DO
            SET V_SUFFIX=TRIM(CAST(F.FIELD_ORDINAL AS VARCHAR(12)));
            IF CHARACTER_LENGTH(V_SOURCE_PROJECTION)+CHARACTER_LENGTH(V_LIST)+2*CHARACTER_LENGTH(TRIM(F.FIELD_NAME))+100>16000 THEN
                SIGNAL SQLSTATE 'U0034' SET MESSAGE_TEXT='Statistics SQL too long; reduce batch size or special list';
            END IF;
            SET V_SOURCE_PROJECTION=V_SOURCE_PROJECTION || ',CASE WHEN "' || TRIM(F.FIELD_NAME) || '" IN ' || V_LIST
              || ' THEN NULL ELSE "' || TRIM(F.FIELD_NAME) || '" END AS DQ_C' || V_SUFFIX;
            SET V_FIELD='S.DQ_C' || V_SUFFIX;
            SET V_PROJECTION=V_PROJECTION
              || ',COALESCE(SUM(CAST(CASE WHEN ' || V_FIELD || ' IS NOT NULL THEN 1 ELSE 0 END AS BIGINT)),0) AS N' || V_SUFFIX
              || ',AVG(CAST(' || V_FIELD || ' AS FLOAT)) AS AV' || V_SUFFIX
              || ',STDDEV_SAMP(CAST(' || V_FIELD || ' AS FLOAT)) AS SD' || V_SUFFIX;
        END FOR;
        SET V_PASS=1;
        WHILE V_PASS<=3 DO
            IF V_PASS=1 THEN
                SET V_GROUP_QUERY='SELECT CAST(NULL AS INTEGER) AS DQ_YEAR,CAST(NULL AS INTEGER) AS DQ_MONTH,'
                  || '1 AS GY,1 AS GM,COALESCE(SUM(CAST(1 AS BIGINT)),0) AS TOTAL_N' || V_PROJECTION
                  || ' FROM (SELECT ' || V_SOURCE_PROJECTION || ' FROM "' || V_DB || '"."' || V_SOURCE || '") S';
            ELSEIF V_PASS=2 THEN
                SET V_GROUP_QUERY='SELECT EXTRACT(YEAR FROM S.DQ_DT) AS DQ_YEAR,CAST(NULL AS INTEGER) AS DQ_MONTH,'
                  || '0 AS GY,1 AS GM,COALESCE(SUM(CAST(1 AS BIGINT)),0) AS TOTAL_N' || V_PROJECTION
                  || ' FROM (SELECT ' || V_SOURCE_PROJECTION || ' FROM "' || V_DB || '"."' || V_SOURCE
                  || '") S GROUP BY EXTRACT(YEAR FROM S.DQ_DT)';
            ELSE
                SET V_GROUP_QUERY='SELECT EXTRACT(YEAR FROM S.DQ_DT) AS DQ_YEAR,EXTRACT(MONTH FROM S.DQ_DT) AS DQ_MONTH,'
                  || '0 AS GY,0 AS GM,COALESCE(SUM(CAST(1 AS BIGINT)),0) AS TOTAL_N' || V_PROJECTION
                  || ' FROM (SELECT ' || V_SOURCE_PROJECTION || ' FROM "' || V_DB || '"."' || V_SOURCE
                  || '") S GROUP BY EXTRACT(YEAR FROM S.DQ_DT),EXTRACT(MONTH FROM S.DQ_DT)';
            END IF;
            IF V_PASS=1 THEN
                SET V_SQL='CREATE VOLATILE TABLE DQ_NS_AGG AS (' || V_GROUP_QUERY
                  || ') WITH DATA PRIMARY INDEX (DQ_YEAR) ON COMMIT PRESERVE ROWS';
            ELSE
                SET V_SQL='INSERT INTO DQ_NS_AGG ' || V_GROUP_QUERY;
            END IF;
            UPDATE DQ_DB.DQ_MODULE_LOG SET SQL_TEXT=V_SQL
             WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_STATISTICS' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=V_BATCH;
            CALL DBC.SysExecSQL(V_SQL);
            SET V_EXISTS=1;
            SET V_PASS=V_PASS+1;
        END WHILE;
        FOR R AS RESULTS_CURSOR CURSOR FOR
            SELECT FIELD_NAME,FIELD_ORDINAL FROM DQ_DB.DQ_RUN_FIELD_CONFIG
             WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC' AND FIELD_ORDINAL BETWEEN V_FIRST AND V_LAST ORDER BY FIELD_ORDINAL
        DO
            SET V_SUFFIX=TRIM(CAST(R.FIELD_ORDINAL AS VARCHAR(12)));
            SET V_SQL='INSERT INTO DQ_DB.DQ_NUMERIC_STATISTICS '
              || '(RUN_ID,FIELD_NAME,PERIOD_LEVEL,PERIOD_VALUE,TOTAL_COUNT,VALID_COUNT,MEAN_VALUE,STDDEV_VALUE) '
              || 'SELECT ''' || P_RUN_ID || ''',''' || TRIM(R.FIELD_NAME) || ''',' || V_LEVEL || ',' || V_PERIOD
              || ',A.TOTAL_N,A.N' || V_SUFFIX || ',A.AV' || V_SUFFIX || ',A.SD' || V_SUFFIX || ' FROM DQ_NS_AGG A';
            CALL DBC.SysExecSQL(V_SQL);
        END FOR;
        CALL DBC.SysExecSQL('DROP TABLE DQ_NS_AGG');
        SET V_EXISTS=0;
        UPDATE DQ_DB.DQ_MODULE_LOG SET STATUS='SUCCEEDED',END_TIME=CURRENT_TIMESTAMP(6)
         WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_STATISTICS' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=V_BATCH;
        SET V_FIRST=V_LAST+1;
    END WHILE;
    UPDATE DQ_DB.DQ_MODULE_LOG SET STATUS='SUCCEEDED',END_TIME=CURRENT_TIMESTAMP(6),FIELD_COUNT=V_FIELDS
     WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_STATISTICS' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=0;
END main;

/* Execute after compiling the complete procedure above. Replace DQ_DB in
   both ON and TO with the approved engine schema. */
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_NUMERIC_STATS_SOURCE TO DQ_DB;

/* Existing public API. Compile AFTER the helper and its grant above. */
REPLACE PROCEDURE DQ_DB.SP_DQ_NUMERIC_STATISTICS
    (IN P_RUN_ID CHAR(36),IN P_PROJECT_ID VARCHAR(30))
SQL SECURITY INVOKER
BEGIN
    DECLARE V_DB VARCHAR(128);
    DECLARE V_SOURCE VARCHAR(128);
    DECLARE V_DATE VARCHAR(128);
    DECLARE V_COUNT INTEGER;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_LOG
     WHERE RUN_ID=P_RUN_ID AND PROJECT_ID=P_PROJECT_ID AND STATUS='RUNNING';
    IF V_COUNT<>1 THEN SIGNAL SQLSTATE 'U0002' SET MESSAGE_TEXT='Statistics require an active engine run'; END IF;
    SELECT SOURCE_DATABASE,SOURCE_TABLE,REPORTING_DATE_FIELD INTO V_DB,V_SOURCE,V_DATE
      FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID=P_RUN_ID;
    CALL DQ_DB.SP_DQ_NUMERIC_STATS_SOURCE(P_RUN_ID,P_PROJECT_ID,V_DB,V_SOURCE,V_DATE);
END;
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_NUMERIC_STATISTICS TO DQ_DB;
