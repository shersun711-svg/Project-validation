/* Deploy AFTER basic, outlier/statistics and special-list procedures and SP_DQ_CLASSIFY.
   Submit EACH REPLACE PROCEDURE below separately: EXTENDED, PROFILE, BASIC, ENGINE.
   Run each following GRANT before compiling the next wrapper.
   SP_DQ_RUN_ENGINE keeps the original two-argument Numeric Basic API.
   SAS uses SP_DQ_RUN_EXTENDED for independent module switches.
   The seventh EXTENDED argument is reserved and must be N for API compatibility.
   Use Teradata mode without an enclosing transaction. */
REPLACE PROCEDURE DQ_DB.SP_DQ_RUN_EXTENDED
    (IN P_RUN_ID CHAR(36), IN P_PROJECT_ID VARCHAR(30),
     IN P_NUMERIC CHAR(1), IN P_CATEGORICAL CHAR(1),
     IN P_DATE CHAR(1), IN P_IDENTIFIER CHAR(1),IN P_RESERVED CHAR(1),IN P_OUTLIERS CHAR(1))
SQL SECURITY INVOKER
main: BEGIN
    DECLARE V_COUNT INTEGER;
    DECLARE V_OWNED INTEGER DEFAULT 0;
    DECLARE V_STATUS VARCHAR(16);
    DECLARE V_DB VARCHAR(128);
    DECLARE V_SOURCE VARCHAR(128);
    DECLARE V_DATE VARCHAR(128);
    DECLARE V_GREEN DECIMAL(9,4);
    DECLARE V_RED DECIMAL(9,4);
    DECLARE V_SIZE INTEGER;
    DECLARE V_PROFILE_OVERALL CHAR(1);
    DECLARE V_PROFILE_MONTHLY CHAR(1);
    DECLARE V_PROFILE_YEARLY CHAR(1);
    DECLARE V_MULTIPLIER DECIMAL(9,4);
    DECLARE V_ERROR VARCHAR(2048) CHARACTER SET UNICODE;
    DECLARE V_ERROR_CODE INTEGER;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_ERROR = MESSAGE_TEXT;
        SET V_ERROR_CODE = SQLCODE;
        IF V_OWNED = 1 THEN
            DELETE FROM DQ_DB.DQ_RULE_RESULT WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_METRIC_RESULT WHERE RUN_ID = P_RUN_ID;
            DELETE FROM DQ_DB.DQ_OUTLIER_CHUNK_YEAR WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_NUMERIC_STATISTICS WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_FIELD_AVAILABILITY WHERE RUN_ID = P_RUN_ID;
            UPDATE DQ_DB.DQ_MODULE_LOG
               SET STATUS = 'FAILED',END_TIME = CURRENT_TIMESTAMP(6),
                   ERROR_CODE = V_ERROR_CODE,ERROR_INFORMATION = V_ERROR
             WHERE RUN_ID = P_RUN_ID AND STATUS = 'RUNNING';
            UPDATE DQ_DB.DQ_RUN_LOG
               SET STATUS = 'FAILED',END_TIME = CURRENT_TIMESTAMP(6),
                   ERROR_CODE = V_ERROR_CODE,ERROR_INFORMATION = V_ERROR
             WHERE RUN_ID = P_RUN_ID;
        ELSE
            RESIGNAL;
        END IF;
    END;
    IF P_RUN_ID IS NULL OR P_PROJECT_ID IS NULL
       OR REGEXP_SIMILAR(TRIM(P_RUN_ID),
       '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$','c') <> 1
       OR REGEXP_SIMILAR(TRIM(P_PROJECT_ID),'^[A-Za-z_][A-Za-z0-9_]{0,29}$','c') <> 1 THEN
        SIGNAL SQLSTATE 'U0001' SET MESSAGE_TEXT = 'Invalid run UUID or project identifier';
    END IF;
    IF P_RESERVED IS NULL OR P_RESERVED<>'N' THEN
        SIGNAL SQLSTATE 'U0043' SET MESSAGE_TEXT='Retired module switch must be N';
    END IF;
    IF P_NUMERIC IS NULL OR P_CATEGORICAL IS NULL OR P_DATE IS NULL OR P_IDENTIFIER IS NULL
       OR P_OUTLIERS IS NULL OR P_OUTLIERS NOT IN ('Y','N')
       OR P_NUMERIC NOT IN ('Y','N') OR P_CATEGORICAL NOT IN ('Y','N')
       OR P_DATE NOT IN ('Y','N') OR P_IDENTIFIER NOT IN ('Y','N') THEN
        SIGNAL SQLSTATE 'U0012' SET MESSAGE_TEXT = 'Every profiling module switch must be Y or N';
    END IF;
    IF P_OUTLIERS='N' AND P_NUMERIC='N' AND P_CATEGORICAL='N' AND P_DATE='N' AND P_IDENTIFIER='N' THEN
        SIGNAL SQLSTATE 'U0013' SET MESSAGE_TEXT = 'No profiling module selected';
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID = P_RUN_ID;
    IF V_COUNT = 0 THEN
        INSERT INTO DQ_DB.DQ_RUN_LOG
          (RUN_ID,PROJECT_ID,START_TIME,STATUS,ATTEMPT_NO)
        VALUES (P_RUN_ID,P_PROJECT_ID,CURRENT_TIMESTAMP(6),'RUNNING',1);
        SET V_OWNED = 1;
    ELSE
        UPDATE DQ_DB.DQ_RUN_LOG
           SET STATUS = 'RUNNING',END_TIME = NULL,ERROR_CODE = NULL,
               ERROR_INFORMATION = NULL,ATTEMPT_NO = ATTEMPT_NO + 1
         WHERE RUN_ID = P_RUN_ID AND PROJECT_ID = P_PROJECT_ID AND STATUS = 'FAILED';
        IF ACTIVITY_COUNT <> 1 THEN
            SIGNAL SQLSTATE 'U0002' SET MESSAGE_TEXT = 'Run is completed, active, or belongs to another project';
        END IF;
        SET V_OWNED = 1;
    END IF;
    CALL DQ_DB.SP_DQ_ASSIGN_RUN_NUMBER(P_RUN_ID);
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_PROJECT_CONFIG
     WHERE PROJECT_ID=P_PROJECT_ID AND ACTIVE_IND='Y';
    IF V_COUNT <> 1 THEN
        SIGNAL SQLSTATE 'U0003' SET MESSAGE_TEXT = 'Active project configuration not found';
    END IF;
    SELECT SOURCE_DATABASE,SOURCE_TABLE,REPORTING_DATE_FIELD
      INTO V_DB,V_SOURCE,V_DATE FROM DQ_DB.DQ_PROJECT_CONFIG
     WHERE PROJECT_ID=P_PROJECT_ID;
    IF REGEXP_SIMILAR(V_DB,'^[A-Za-z_][A-Za-z0-9_]*$','c') <> 1
       OR REGEXP_SIMILAR(V_SOURCE,'^[A-Za-z_][A-Za-z0-9_]*$','c') <> 1
       OR REGEXP_SIMILAR(V_DATE,'^[A-Za-z_][A-Za-z0-9_]*$','c') <> 1 THEN
        SIGNAL SQLSTATE 'U0004' SET MESSAGE_TEXT = 'Unsafe source or reporting date identifier';
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_ENGINE_SETTINGS
     WHERE PROJECT_ID IN ('*',P_PROJECT_ID);
    IF V_COUNT=0 THEN
        SIGNAL SQLSTATE 'U0007' SET MESSAGE_TEXT = 'Engine settings not configured';
    END IF;
    SELECT GREEN_THRESHOLD,RED_THRESHOLD,SQL_BATCH_SIZE,OUTLIER_SD_MULTIPLIER,
           PROFILE_OVERALL,PROFILE_MONTHLY,PROFILE_YEARLY
      INTO V_GREEN,V_RED,V_SIZE,V_MULTIPLIER,V_PROFILE_OVERALL,V_PROFILE_MONTHLY,V_PROFILE_YEARLY FROM DQ_DB.DQ_ENGINE_SETTINGS
     WHERE PROJECT_ID IN ('*',P_PROJECT_ID)
     QUALIFY ROW_NUMBER() OVER
       (ORDER BY CASE WHEN PROJECT_ID=P_PROJECT_ID THEN 0 ELSE 1 END)=1;
    IF V_PROFILE_OVERALL IS NULL OR V_PROFILE_MONTHLY IS NULL OR V_PROFILE_YEARLY IS NULL
       OR V_PROFILE_OVERALL NOT IN ('Y','N') OR V_PROFILE_MONTHLY NOT IN ('Y','N')
       OR V_PROFILE_YEARLY NOT IN ('Y','N')
       OR (V_PROFILE_OVERALL='N' AND V_PROFILE_MONTHLY='N' AND V_PROFILE_YEARLY='N') THEN
        SIGNAL SQLSTATE 'U0046' SET MESSAGE_TEXT='Select at least one reporting level; every PROFILE setting must be Y or N';
    END IF;
    IF P_OUTLIERS='Y' AND V_MULTIPLIER<>3 THEN
        SIGNAL SQLSTATE 'U0042' SET MESSAGE_TEXT='Outlier rule requires OUTLIER_SD_MULTIPLIER=3 in Settings';
    END IF;
    UPDATE DQ_DB.DQ_RUN_LOG
       SET SOURCE_DATABASE=V_DB,SOURCE_TABLE=V_SOURCE,REPORTING_DATE_FIELD=V_DATE,
           GREEN_THRESHOLD=V_GREEN,RED_THRESHOLD=V_RED,SQL_BATCH_SIZE=V_SIZE,
           PROFILE_OVERALL=V_PROFILE_OVERALL,PROFILE_MONTHLY=V_PROFILE_MONTHLY,PROFILE_YEARLY=V_PROFILE_YEARLY
     WHERE RUN_ID=P_RUN_ID;
    /* Refresh all selected types for a new attempt. No source snapshot is
       implied; keep source and configuration stable during execution. */
    DELETE FROM DQ_DB.DQ_RULE_RESULT WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_METRIC_RESULT WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_OUTLIER_CHUNK_YEAR WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_NUMERIC_STATISTICS WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_FIELD_AVAILABILITY WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_RUN_FIELD_CONFIG WHERE RUN_ID=P_RUN_ID;
    DELETE FROM DQ_DB.DQ_RUN_SPECIAL_VALUE WHERE RUN_ID=P_RUN_ID;
    INSERT INTO DQ_DB.DQ_RUN_SPECIAL_VALUE
    SELECT P_RUN_ID,FIELD_TYPE,SPECIAL_VALUE,NUMERIC_VALUE
      FROM DQ_DB.DQ_SPECIAL_VALUE_CONFIG WHERE PROJECT_ID=P_PROJECT_ID AND ACTIVE_IND='Y';
    INSERT INTO DQ_DB.DQ_RUN_FIELD_CONFIG
    SELECT P_RUN_ID,FIELD_NAME,FIELD_TYPE,
           ROW_NUMBER() OVER (PARTITION BY FIELD_TYPE ORDER BY FIELD_NAME)
      FROM DQ_DB.DQ_FIELD_CONFIG
     WHERE PROJECT_ID=P_PROJECT_ID AND ACTIVE_IND='Y'
       AND (((P_NUMERIC='Y' OR P_OUTLIERS='Y') AND FIELD_TYPE='NUMERIC')
         OR (P_CATEGORICAL='Y' AND FIELD_TYPE='CATEGORICAL')
         OR (P_DATE='Y' AND FIELD_TYPE='DATE')
         OR (P_IDENTIFIER='Y' AND FIELD_TYPE='IDENTIFIER'));
    IF P_NUMERIC='Y' THEN
        CALL DQ_DB.SP_DQ_NUMERIC_BASIC(P_RUN_ID,P_PROJECT_ID);
        SELECT STATUS INTO V_STATUS FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID=P_RUN_ID;
        IF V_STATUS <> 'RUNNING' THEN
            DELETE FROM DQ_DB.DQ_RULE_RESULT WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_METRIC_RESULT WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_OUTLIER_CHUNK_YEAR WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_NUMERIC_STATISTICS WHERE RUN_ID=P_RUN_ID;
            DELETE FROM DQ_DB.DQ_FIELD_AVAILABILITY WHERE RUN_ID=P_RUN_ID;
            LEAVE main; /* Retain the numeric module's original failure detail. */
        END IF;
    END IF;
    IF P_OUTLIERS='Y' THEN
        CALL DQ_DB.SP_DQ_NUMERIC_OUTLIERS(P_RUN_ID,P_PROJECT_ID);
    END IF;
    IF P_CATEGORICAL='Y' THEN
        CALL DQ_DB.SP_DQ_CATEGORICAL_BASIC(P_RUN_ID,P_PROJECT_ID);
    END IF;
    IF P_DATE='Y' THEN
        CALL DQ_DB.SP_DQ_DATE_BASIC(P_RUN_ID,P_PROJECT_ID);
    END IF;
    IF P_IDENTIFIER='Y' THEN
        CALL DQ_DB.SP_DQ_IDENTIFIER_BASIC(P_RUN_ID,P_PROJECT_ID);
    END IF;
    CALL DQ_DB.SP_DQ_CLASSIFY(P_RUN_ID);
    UPDATE DQ_DB.DQ_RUN_LOG SET STATUS='SUCCEEDED',END_TIME=CURRENT_TIMESTAMP(6)
     WHERE RUN_ID=P_RUN_ID AND STATUS='RUNNING';
END main;

/* Execute after compiling the complete procedure above. Replace DQ_DB in
   both ON and TO with the approved engine schema. */
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_RUN_EXTENDED TO DQ_DB;

/* Keep the seven-argument legacy API. Its reserved final switch must be N. */
REPLACE PROCEDURE DQ_DB.SP_DQ_RUN_PROFILE
    (IN P_RUN_ID CHAR(36),IN P_PROJECT_ID VARCHAR(30),IN P_NUMERIC CHAR(1),IN P_CATEGORICAL CHAR(1),
     IN P_DATE CHAR(1),IN P_IDENTIFIER CHAR(1),IN P_RESERVED CHAR(1))
SQL SECURITY INVOKER
BEGIN
    IF P_RESERVED IS NULL OR P_RESERVED<>'N' THEN
        SIGNAL SQLSTATE 'U0043' SET MESSAGE_TEXT='Retired module switch must be N';
    END IF;
    CALL DQ_DB.SP_DQ_RUN_EXTENDED(P_RUN_ID,P_PROJECT_ID,P_NUMERIC,P_CATEGORICAL,P_DATE,P_IDENTIFIER,'N','N');
END;
/* Execute after compiling the complete procedure above. Replace DQ_DB in
   both ON and TO with the approved engine schema. */
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_RUN_PROFILE TO DQ_DB;


/* Preserve the six-argument basic API for SQL callers and existing fixtures. */
REPLACE PROCEDURE DQ_DB.SP_DQ_RUN_BASIC
    (IN P_RUN_ID CHAR(36),IN P_PROJECT_ID VARCHAR(30),
     IN P_NUMERIC CHAR(1),IN P_CATEGORICAL CHAR(1),IN P_DATE CHAR(1),IN P_IDENTIFIER CHAR(1))
SQL SECURITY INVOKER
BEGIN
    CALL DQ_DB.SP_DQ_RUN_PROFILE(P_RUN_ID,P_PROJECT_ID,P_NUMERIC,P_CATEGORICAL,P_DATE,P_IDENTIFIER,'N');
END;
/* Execute after compiling the complete procedure above. Replace DQ_DB in
   both ON and TO with the approved engine schema. */
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_RUN_BASIC TO DQ_DB;


/* Backwards-compatible Numeric Basic entry for existing SQL integrations. */
REPLACE PROCEDURE DQ_DB.SP_DQ_RUN_ENGINE
    (IN P_RUN_ID CHAR(36), IN P_PROJECT_ID VARCHAR(30))
SQL SECURITY INVOKER
BEGIN
    CALL DQ_DB.SP_DQ_RUN_BASIC(P_RUN_ID,P_PROJECT_ID,'Y','N','N','N');
END;
/* Execute after compiling the complete procedure above. Replace DQ_DB in
   both ON and TO with the approved engine schema. */
GRANT EXECUTE PROCEDURE ON DQ_DB.SP_DQ_RUN_ENGINE TO DQ_DB;
