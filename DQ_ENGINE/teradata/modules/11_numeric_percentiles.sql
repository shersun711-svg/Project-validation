/* Continuous percentile positions: h=1+(n-1)*p (Hyndman-Fan type 7).
   This differs from SAS default PCTLDEF=5; reconciliation uses this formula.
   Sort native numeric values, then interpolate using FLOAT and
   persist DECIMAL(38,10). NULL/configured specials are excluded.
   One configured-source read per batch (max 5 fields) into a session-local
   wide volatile table. No raw rows leave Teradata. Each field expands its
   retained rows into three period levels and sorts once for all 7 quantiles.
   Explicit periods avoid DISTINCT/GROUPING SETS issues on the user's server.
   Standalone percentiles do not require Numeric Basic. */
REPLACE PROCEDURE DQ_DB.SP_DQ_NUMERIC_PERCENTILES
    (IN P_RUN_ID CHAR(36),IN P_PROJECT_ID VARCHAR(30))
SQL SECURITY INVOKER
main: BEGIN
    DECLARE V_DB VARCHAR(128);
    DECLARE V_SOURCE VARCHAR(128);
    DECLARE V_DATE VARCHAR(128);
    DECLARE V_ATTEMPT INTEGER;
    DECLARE V_COUNT INTEGER;
    DECLARE V_FIELDS INTEGER;
    DECLARE V_SIZE INTEGER;
    DECLARE V_FIRST INTEGER DEFAULT 1;
    DECLARE V_LAST INTEGER;
    DECLARE V_BATCH INTEGER DEFAULT 0;
    DECLARE V_SOURCE_EXISTS INTEGER DEFAULT 0;
    DECLARE V_PERIOD_EXISTS INTEGER DEFAULT 0;
    DECLARE V_ORDER_EXISTS INTEGER DEFAULT 0;
    DECLARE V_OWNED INTEGER DEFAULT 0;
    DECLARE V_SQL VARCHAR(32000);
    DECLARE V_PROJECTION VARCHAR(16000);
    DECLARE V_LIST VARCHAR(8000);
    DECLARE V_FIELD VARCHAR(150);
    DECLARE V_YEAR VARCHAR(500);
    DECLARE V_MONTH VARCHAR(800);
    DECLARE V_OVERALL VARCHAR(2500);
    DECLARE V_YEARLY VARCHAR(2500);
    DECLARE V_MONTHLY VARCHAR(2500);
    DECLARE V_ERROR VARCHAR(2048) CHARACTER SET UNICODE;
    DECLARE V_ERROR_CODE INTEGER;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_ERROR=MESSAGE_TEXT;
        SET V_ERROR_CODE=SQLCODE;
        IF V_OWNED=1 THEN
            UPDATE DQ_DB.DQ_MODULE_LOG
               SET STATUS='FAILED',END_TIME=CURRENT_TIMESTAMP(6),ERROR_CODE=V_ERROR_CODE,ERROR_INFORMATION=V_ERROR
             WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_PERCENTILES'
               AND ATTEMPT_NO=V_ATTEMPT AND STATUS='RUNNING';
        END IF;
        BEGIN
            DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET V_COUNT=0;
            IF V_ORDER_EXISTS=1 THEN CALL DBC.SysExecSQL('DROP TABLE DQ_NP_ORDERED'); END IF;
            IF V_PERIOD_EXISTS=1 THEN CALL DBC.SysExecSQL('DROP TABLE DQ_NP_PERIOD'); END IF;
            IF V_SOURCE_EXISTS=1 THEN CALL DBC.SysExecSQL('DROP TABLE DQ_NP_SOURCE'); END IF;
        END;
        RESIGNAL; /* Shared orchestrator clears every partial module result. */
    END;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_LOG
     WHERE RUN_ID=P_RUN_ID AND PROJECT_ID=P_PROJECT_ID AND STATUS='RUNNING';
    IF V_COUNT<>1 THEN
        SIGNAL SQLSTATE 'U0002' SET MESSAGE_TEXT='Percentiles require an active engine run';
    END IF;
    SELECT SOURCE_DATABASE,SOURCE_TABLE,REPORTING_DATE_FIELD,SQL_BATCH_SIZE,ATTEMPT_NO
      INTO V_DB,V_SOURCE,V_DATE,V_SIZE,V_ATTEMPT FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID=P_RUN_ID;
    SET V_SIZE=LEAST(V_SIZE,5);
    INSERT INTO DQ_DB.DQ_MODULE_LOG
        (RUN_ID,MODULE_NAME,ATTEMPT_NO,BATCH_ID,START_TIME,STATUS)
    VALUES (P_RUN_ID,'NUMERIC_PERCENTILES',V_ATTEMPT,0,CURRENT_TIMESTAMP(6),'RUNNING');
    SET V_OWNED=1;
    SELECT COUNT(*) INTO V_FIELDS FROM DQ_DB.DQ_RUN_FIELD_CONFIG WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC';
    IF V_FIELDS=0 THEN
        SIGNAL SQLSTATE 'U0009' SET MESSAGE_TEXT='Selected percentiles module has no eligible numeric fields';
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_RUN_FIELD_CONFIG
     WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC'
       AND REGEXP_SIMILAR(FIELD_NAME,'^[A-Za-z_][A-Za-z0-9_]*$','c')<>1;
    IF V_COUNT>0 THEN SIGNAL SQLSTATE 'U0011' SET MESSAGE_TEXT='Unsafe percentile field identifier'; END IF;
    SELECT COUNT(*) INTO V_COUNT FROM DQ_DB.DQ_METRIC_DEFINITION
     WHERE MODULE_NAME='NUMERIC_PERCENTILES' AND METRIC_ORDINAL BETWEEN 1 AND 7;
    IF V_COUNT<>7 THEN SIGNAL SQLSTATE 'U0010' SET MESSAGE_TEXT='Percentile metadata incomplete'; END IF;
    CALL DQ_DB.SP_DQ_SPECIAL_LIST(P_RUN_ID,'NUMERIC',V_LIST);
    SET V_YEAR='CASE WHEN DQ_DT IS NULL THEN ''UNKNOWN'' ELSE TRIM(CAST(EXTRACT(YEAR FROM DQ_DT) AS CHAR(4))) END';
    SET V_MONTH='CASE WHEN DQ_DT IS NULL THEN ''UNKNOWN'' ELSE TRIM(CAST(EXTRACT(YEAR FROM DQ_DT) AS CHAR(4)))'
      || '||''-''||SUBSTR(''00''||TRIM(CAST(EXTRACT(MONTH FROM DQ_DT) AS VARCHAR(2))),'
      || 'CHARACTER_LENGTH(''00''||TRIM(CAST(EXTRACT(MONTH FROM DQ_DT) AS VARCHAR(2))))-1,2) END';
    WHILE V_FIRST<=V_FIELDS DO
        SET V_BATCH=V_BATCH+1;
        SET V_LAST=LEAST(V_FIRST+V_SIZE-1,V_FIELDS);
        INSERT INTO DQ_DB.DQ_MODULE_LOG
            (RUN_ID,MODULE_NAME,ATTEMPT_NO,BATCH_ID,START_TIME,STATUS,FIELD_COUNT)
        VALUES (P_RUN_ID,'NUMERIC_PERCENTILES',V_ATTEMPT,V_BATCH,CURRENT_TIMESTAMP(6),'RUNNING',V_LAST-V_FIRST+1);
        SET V_PROJECTION='CAST("' || V_DATE || '" AS DATE) AS DQ_DT';
        FOR F AS FIELDS_CURSOR CURSOR FOR
            SELECT FIELD_NAME,FIELD_ORDINAL FROM DQ_DB.DQ_RUN_FIELD_CONFIG
             WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC' AND FIELD_ORDINAL BETWEEN V_FIRST AND V_LAST
             ORDER BY FIELD_ORDINAL
        DO
            IF CHARACTER_LENGTH(V_PROJECTION)+CHARACTER_LENGTH(V_LIST)+2*CHARACTER_LENGTH(TRIM(F.FIELD_NAME))+100>16000 THEN
                SIGNAL SQLSTATE 'U0034' SET MESSAGE_TEXT='Percentile SQL too long; reduce SQL_BATCH_SIZE or special list';
            END IF;
            SET V_PROJECTION=V_PROJECTION || ',CASE WHEN "' || TRIM(F.FIELD_NAME) || '" IN ' || V_LIST
              || ' THEN NULL ELSE "' || TRIM(F.FIELD_NAME) || '" END AS DQ_C' || TRIM(CAST(F.FIELD_ORDINAL AS VARCHAR(12)));
        END FOR;
        SET V_SQL='CREATE MULTISET VOLATILE TABLE DQ_NP_SOURCE AS (SELECT ' || V_PROJECTION
          || ' FROM "' || V_DB || '"."' || V_SOURCE || '") WITH DATA NO PRIMARY INDEX ON COMMIT PRESERVE ROWS';
        UPDATE DQ_DB.DQ_MODULE_LOG SET SQL_TEXT=V_SQL
         WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_PERCENTILES' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=V_BATCH;
        CALL DBC.SysExecSQL(V_SQL);
        SET V_SOURCE_EXISTS=1;
        /* Domain comes from ALL rows, so all-NULL/all-special periods survive.
           Aggregate without GROUP BY provides OVERALL even for an empty source. */
        SET V_SQL='CREATE MULTISET VOLATILE TABLE DQ_NP_PERIOD AS ('
          || 'SELECT CAST(''OVERALL'' AS VARCHAR(8)) AS PERIOD_LEVEL,CAST(''ALL'' AS VARCHAR(10)) AS PERIOD_VALUE'
          || ' FROM (SELECT SUM(CAST(1 AS BIGINT)) AS N FROM DQ_NP_SOURCE) A UNION ALL '
          || 'SELECT ''YEARLY'',' || V_YEAR || ' FROM DQ_NP_SOURCE GROUP BY 1,2 UNION ALL '
          || 'SELECT ''MONTHLY'',' || V_MONTH || ' FROM DQ_NP_SOURCE GROUP BY 1,2'
          || ') WITH DATA PRIMARY INDEX (PERIOD_LEVEL,PERIOD_VALUE) ON COMMIT PRESERVE ROWS';
        CALL DBC.SysExecSQL(V_SQL);
        SET V_PERIOD_EXISTS=1;
        FOR R AS RESULTS_CURSOR CURSOR FOR
            SELECT FIELD_NAME,FIELD_ORDINAL FROM DQ_DB.DQ_RUN_FIELD_CONFIG
             WHERE RUN_ID=P_RUN_ID AND FIELD_TYPE='NUMERIC' AND FIELD_ORDINAL BETWEEN V_FIRST AND V_LAST
             ORDER BY FIELD_ORDINAL
        DO
            SET V_FIELD='DQ_C' || TRIM(CAST(R.FIELD_ORDINAL AS VARCHAR(12)));
            SET V_OVERALL='SELECT CAST(''OVERALL'' AS VARCHAR(8)) AS PERIOD_LEVEL,CAST(''ALL'' AS VARCHAR(10)) AS PERIOD_VALUE,'
              || V_FIELD || ' AS DQ_VALUE FROM DQ_NP_SOURCE WHERE ' || V_FIELD || ' IS NOT NULL';
            SET V_YEARLY='SELECT ''YEARLY'',' || V_YEAR || ',' || V_FIELD || ' FROM DQ_NP_SOURCE WHERE ' || V_FIELD || ' IS NOT NULL';
            SET V_MONTHLY='SELECT ''MONTHLY'',' || V_MONTH || ',' || V_FIELD || ' FROM DQ_NP_SOURCE WHERE ' || V_FIELD || ' IS NOT NULL';
            SET V_SQL='CREATE MULTISET VOLATILE TABLE DQ_NP_ORDERED AS ('
              || 'SELECT T.*,ROW_NUMBER() OVER (PARTITION BY PERIOD_LEVEL,PERIOD_VALUE ORDER BY DQ_VALUE) AS RN,'
              || 'SUM(CAST(1 AS BIGINT)) OVER (PARTITION BY PERIOD_LEVEL,PERIOD_VALUE) AS N FROM ('
              || V_OVERALL || ' UNION ALL ' || V_YEARLY || ' UNION ALL ' || V_MONTHLY || ') T'
              || ') WITH DATA PRIMARY INDEX (PERIOD_LEVEL,PERIOD_VALUE) ON COMMIT PRESERVE ROWS';
            CALL DBC.SysExecSQL(V_SQL);
            SET V_ORDER_EXISTS=1;
            /* h is calculated once in a derived table. Both bounding ranks are
               selected by MAX; duplicates retain their sample multiplicity. */
            SET V_SQL='INSERT INTO DQ_DB.DQ_METRIC_RESULT '
              || '(RUN_ID,PROJECT_ID,FIELD_NAME,FIELD_TYPE,MODULE_NAME,PERIOD_LEVEL,PERIOD_VALUE,'
              || 'METRIC_NAME,METRIC_VALUE,IS_PERCENTAGE,EXECUTION_TIMESTAMP) '
              || 'SELECT ''' || P_RUN_ID || ''',''' || P_PROJECT_ID || ''',''' || TRIM(R.FIELD_NAME)
              || ''',''NUMERIC'',''NUMERIC_PERCENTILES'',D.PERIOD_LEVEL,D.PERIOD_VALUE,M.METRIC_NAME,'
              || 'CAST(Q.P_VALUE AS DECIMAL(38,10)),''N'',CURRENT_TIMESTAMP(6) '
              || 'FROM DQ_NP_PERIOD D CROSS JOIN DQ_DB.DQ_METRIC_DEFINITION M LEFT JOIN ('
              || 'SELECT PERIOD_LEVEL,PERIOD_VALUE,METRIC_NAME,'
              || 'MAX(CASE WHEN RN=FLOOR(H) THEN CAST(DQ_VALUE AS FLOAT) END)'
              || '+(MAX(H)-FLOOR(MAX(H)))*(MAX(CASE WHEN RN=CEILING(H) THEN CAST(DQ_VALUE AS FLOAT) END)'
              || '-MAX(CASE WHEN RN=FLOOR(H) THEN CAST(DQ_VALUE AS FLOAT) END)) AS P_VALUE FROM ('
              || 'SELECT O.*,K.METRIC_NAME,1.0+(CAST(O.N AS FLOAT)-1.0)*'
              || 'CASE K.METRIC_ORDINAL WHEN 1 THEN 0.01 WHEN 2 THEN 0.05 WHEN 3 THEN 0.25 '
              || 'WHEN 4 THEN 0.50 WHEN 5 THEN 0.75 WHEN 6 THEN 0.95 WHEN 7 THEN 0.99 END AS H '
              || 'FROM DQ_NP_ORDERED O CROSS JOIN DQ_DB.DQ_METRIC_DEFINITION K '
              || 'WHERE K.MODULE_NAME=''NUMERIC_PERCENTILES'' AND K.METRIC_ORDINAL BETWEEN 1 AND 7) X '
              || 'GROUP BY PERIOD_LEVEL,PERIOD_VALUE,METRIC_NAME) Q '
              || 'ON D.PERIOD_LEVEL=Q.PERIOD_LEVEL AND D.PERIOD_VALUE=Q.PERIOD_VALUE AND M.METRIC_NAME=Q.METRIC_NAME '
              || 'WHERE M.MODULE_NAME=''NUMERIC_PERCENTILES'' AND M.METRIC_ORDINAL BETWEEN 1 AND 7';
            CALL DBC.SysExecSQL(V_SQL);
            CALL DBC.SysExecSQL('DROP TABLE DQ_NP_ORDERED');
            SET V_ORDER_EXISTS=0;
        END FOR;
        CALL DBC.SysExecSQL('DROP TABLE DQ_NP_PERIOD');
        SET V_PERIOD_EXISTS=0;
        CALL DBC.SysExecSQL('DROP TABLE DQ_NP_SOURCE');
        SET V_SOURCE_EXISTS=0;
        UPDATE DQ_DB.DQ_MODULE_LOG SET STATUS='SUCCEEDED',END_TIME=CURRENT_TIMESTAMP(6)
         WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_PERCENTILES' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=V_BATCH;
        SET V_FIRST=V_LAST+1;
    END WHILE;
    UPDATE DQ_DB.DQ_MODULE_LOG SET STATUS='SUCCEEDED',END_TIME=CURRENT_TIMESTAMP(6),FIELD_COUNT=V_FIELDS
     WHERE RUN_ID=P_RUN_ID AND MODULE_NAME='NUMERIC_PERCENTILES' AND ATTEMPT_NO=V_ATTEMPT AND BATCH_ID=0;
END main;
