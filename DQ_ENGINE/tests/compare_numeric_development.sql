/* READ ONLY: compare the final DQ_BASIC_REVIEW with development run 1.
   Replace DQ_DB with LAB_T_ORION_MVT in your copy; edit OUR_RUN_NUMBER below.
   Submit this complete statement. No profiling rerun or new database objects.
   One row per field/period/metric: OUR_VALUE, DEV_VALUE, DIFFERENCE, STATUS.
   Rates are already fractions; no division by 100 is needed.
   SHOW_MATCHES=Y displays all comparisons; N displays exceptions only.
   Both engines' saved results are read from DQ_DB. MDT result table names
   are assumed unchanged. CDAO classifies BRANCH_ORIGIN_ID, BROKER_CD,
   SECURITISED_DEAL_ID and BOR2_CUSTOMER_AGE as CATEGORICAL. If captured as
   numeric in this run, their numeric results are replication evidence only.
   This query follows the saved run field types; it does not coerce categories
   or create numeric results that were not calculated.
   Numeric Basic + Outliers, overall/monthly only. See
   documentation/DEVELOPMENT_COMPARISON.md for scope and known differences. */
WITH
PARAMS AS
(
    SELECT CAST('RDS' AS VARCHAR(30)) AS PROJECT_ID,
           CAST(17 AS BIGINT) AS OUR_RUN_NUMBER,
           CAST(1 AS BIGINT) AS DEV_RUN_ID,
           CAST(0.000001 AS DECIMAL(18,12)) AS RATE_ABS_TOL,
           CAST(0.000001 AS DECIMAL(18,12)) AS VALUE_ABS_TOL,
           CAST(0.000000000001 AS DECIMAL(18,12)) AS VALUE_REL_TOL,
           CAST('Y' AS CHAR(1)) AS SHOW_MATCHES
    FROM (SELECT COUNT(*) AS SEED_COUNT FROM DQ_DB.DQ_RUN_NUMBER) SEED
),
CHOSEN_RUN AS
(
    SELECT L.*,N.RUN_NUMBER FROM DQ_DB.DQ_RUN_LOG L
    JOIN DQ_DB.DQ_RUN_NUMBER N ON L.RUN_ID=N.RUN_ID
    JOIN PARAMS P ON L.PROJECT_ID=P.PROJECT_ID AND N.RUN_NUMBER=P.OUR_RUN_NUMBER
    WHERE L.STATUS='SUCCEEDED'
),
FIELD_SCOPE AS
(
    SELECT DISTINCT UPPER(TRIM(F.FIELD_NAME)) AS FIELD_NAME
    FROM DQ_DB.DQ_RUN_FIELD_CONFIG F JOIN CHOSEN_RUN L ON F.RUN_ID=L.RUN_ID
    WHERE F.FIELD_TYPE='NUMERIC'
),
METRIC_MAP AS
(
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('TOTAL_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,1 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('NON_MISSING_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,2 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('MISSING_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,3 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('MISSING_RATE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('RATE' AS VARCHAR(8)) AS VALUE_KIND,4 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('ZERO_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,5 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('ZERO_RATE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('RATE' AS VARCHAR(8)) AS VALUE_KIND,6 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('MIN_VALUE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('EXACT' AS VARCHAR(8)) AS VALUE_KIND,7 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('MAX_VALUE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('EXACT' AS VARCHAR(8)) AS VALUE_KIND,8 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('MEAN_VALUE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('VALUE' AS VARCHAR(8)) AS VALUE_KIND,9 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('STDDEV_VALUE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('VALUE' AS VARCHAR(8)) AS VALUE_KIND,10 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('SPECIAL_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,11 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_BASIC' AS VARCHAR(32)) AS MODULE_NAME,CAST('SPECIAL_RATE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('RATE' AS VARCHAR(8)) AS VALUE_KIND,12 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_OUTLIERS' AS VARCHAR(32)) AS MODULE_NAME,CAST('OUTLIER_LOWER_BOUND' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('VALUE' AS VARCHAR(8)) AS VALUE_KIND,13 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_OUTLIERS' AS VARCHAR(32)) AS MODULE_NAME,CAST('OUTLIER_UPPER_BOUND' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('VALUE' AS VARCHAR(8)) AS VALUE_KIND,14 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_OUTLIERS' AS VARCHAR(32)) AS MODULE_NAME,CAST('OUTLIER_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,15 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_OUTLIERS' AS VARCHAR(32)) AS MODULE_NAME,CAST('OUTLIER_RATE' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('RATE' AS VARCHAR(8)) AS VALUE_KIND,16 AS METRIC_ORDINAL
    FROM PARAMS
    UNION ALL
    SELECT CAST('NUMERIC_OUTLIERS' AS VARCHAR(32)) AS MODULE_NAME,CAST('OUTLIER_VALID_COUNT' AS VARCHAR(32)) AS METRIC_NAME,
           CAST('COUNT' AS VARCHAR(8)) AS VALUE_KIND,17 AS METRIC_ORDINAL
    FROM PARAMS
),
ENABLED_METRICS AS
(
    SELECT M.* FROM METRIC_MAP M
    WHERE EXISTS
      (SELECT 1 FROM DQ_DB.DQ_MODULE_LOG G JOIN CHOSEN_RUN L ON G.RUN_ID=L.RUN_ID
       WHERE G.MODULE_NAME=M.MODULE_NAME AND G.ATTEMPT_NO=L.ATTEMPT_NO
         AND G.BATCH_ID=0 AND G.STATUS='SUCCEEDED')
),
ENGINE_REVIEW AS
(
    SELECT R.* FROM DQ_DB.DQ_BASIC_REVIEW R
    JOIN CHOSEN_RUN L ON R.RUN_ID=L.RUN_ID AND R.PROJECT_ID=L.PROJECT_ID
    WHERE R.FIELD_TYPE='NUMERIC'
      AND ((R.PERIOD_LEVEL='OVERALL' AND L.PROFILE_OVERALL='Y')
        OR (R.PERIOD_LEVEL='MONTHLY' AND L.PROFILE_MONTHLY='Y'))
),
ENGINE_VALUES AS
(
    /* Fractions and six-decimal statistics come directly from the final view. */
    SELECT UPPER(TRIM(R.FIELD_NAME)) AS FIELD_NAME,R.PERIOD_LEVEL,
           CAST(CASE WHEN R.PERIOD_LEVEL='OVERALL' THEN 'ALL'
                     WHEN R.POU_DT IS NULL THEN 'UNKNOWN'
                     ELSE TRIM(CAST(EXTRACT(YEAR FROM R.POU_DT) AS CHAR(4)))||'-'
                       ||SUBSTR('00'||TRIM(CAST(EXTRACT(MONTH FROM R.POU_DT) AS VARCHAR(2))),
                          CHARACTER_LENGTH('00'||TRIM(CAST(EXTRACT(MONTH FROM R.POU_DT) AS VARCHAR(2))))-1,2)
                END AS VARCHAR(10)) AS PERIOD_VALUE,
           M.MODULE_NAME,M.METRIC_NAME,COUNT(*) AS ROW_COPIES,MAX(R.POU_DT) AS POU_DT,
           MAX(CASE M.METRIC_ORDINAL
             WHEN 1 THEN CAST(R.TOTAL_COUNT AS DECIMAL(38,6))
             WHEN 2 THEN CAST(R.NON_MISSING_COUNT AS DECIMAL(38,6))
             WHEN 3 THEN CAST(R.MISSING_COUNT AS DECIMAL(38,6))
             WHEN 4 THEN CAST(R.MISSING_RATE AS DECIMAL(38,6))
             WHEN 5 THEN CAST(R.ZERO_COUNT AS DECIMAL(38,6))
             WHEN 6 THEN CAST(R.ZERO_RATE AS DECIMAL(38,6))
             WHEN 7 THEN CAST(R.MIN_VALUE AS DECIMAL(38,6))
             WHEN 8 THEN CAST(R.MAX_VALUE AS DECIMAL(38,6))
             WHEN 9 THEN CAST(R.MEAN_VALUE AS DECIMAL(38,6))
             WHEN 10 THEN CAST(R.STDDEV_VALUE AS DECIMAL(38,6))
             WHEN 11 THEN CAST(R.SPECIAL_COUNT AS DECIMAL(38,6))
             WHEN 12 THEN CAST(R.SPECIAL_RATE AS DECIMAL(38,6))
             WHEN 13 THEN CAST(R.OUTLIER_LOWER_BOUND AS DECIMAL(38,6))
             WHEN 14 THEN CAST(R.OUTLIER_UPPER_BOUND AS DECIMAL(38,6))
             WHEN 15 THEN CAST(R.OUTLIER_COUNT AS DECIMAL(38,6))
             WHEN 16 THEN CAST(R.OUTLIER_RATE AS DECIMAL(38,6))
             WHEN 17 THEN CAST(R.OUTLIER_VALID_COUNT AS DECIMAL(38,6))
           END) AS METRIC_VALUE,
           MAX(R.TOTAL_COUNT) AS TOTAL_COUNT,MAX(R.OUTLIER_VALID_COUNT) AS VALID_COUNT
    FROM ENGINE_REVIEW R
    JOIN FIELD_SCOPE F ON UPPER(TRIM(R.FIELD_NAME))=F.FIELD_NAME
    CROSS JOIN ENABLED_METRICS M
    GROUP BY 1,2,3,4,5
),
DEV_RUN_VALUES AS
(
    SELECT D.* FROM DQ_DB.IRB_RDS_DQ_NUMERIC_PROFILE_RESULT D
    JOIN PARAMS P ON D.RUN_ID=P.DEV_RUN_ID
),
DEV_SCOPED AS
(
    SELECT D.*,UPPER(TRIM(D.FIELD_NAME)) AS FIELD_KEY,
           CAST(UPPER(TRIM(D.RUN_TYPE)) AS VARCHAR(8)) AS PERIOD_LEVEL,
           CAST(CASE WHEN UPPER(TRIM(D.RUN_TYPE))='OVERALL' THEN 'ALL'
                     WHEN D.POU_DT IS NULL THEN 'UNKNOWN'
                     ELSE TRIM(CAST(EXTRACT(YEAR FROM D.POU_DT) AS CHAR(4)))||'-'
                       ||SUBSTR('00'||TRIM(CAST(EXTRACT(MONTH FROM D.POU_DT) AS VARCHAR(2))),
                          CHARACTER_LENGTH('00'||TRIM(CAST(EXTRACT(MONTH FROM D.POU_DT) AS VARCHAR(2))))-1,2)
                END AS VARCHAR(10)) AS PERIOD_KEY
    FROM DEV_RUN_VALUES D JOIN FIELD_SCOPE F ON UPPER(TRIM(D.FIELD_NAME))=F.FIELD_NAME
    CROSS JOIN CHOSEN_RUN L
    WHERE (UPPER(TRIM(D.RUN_TYPE))='OVERALL' AND L.PROFILE_OVERALL='Y')
       OR (UPPER(TRIM(D.RUN_TYPE))='MONTHLY' AND L.PROFILE_MONTHLY='Y')
),
DEV_GROUPS AS
(
    /* MAX avoids row multiplication but is NEVER compared when copies>1. */
    SELECT D.FIELD_KEY AS FIELD_NAME,D.PERIOD_LEVEL,D.PERIOD_KEY,
           COUNT(*) AS ROW_COPIES,COUNT(DISTINCT D.POU_DT) AS SNAPSHOT_DATES,
           MAX(D.POU_DT) AS POU_DT,
           MAX(D.ROW_COUNT) AS ROW_COUNT,
           MAX(D.MISSING_COUNT) AS MISSING_COUNT,
           MAX(D.MISSING_PCT) AS MISSING_PCT,
           MAX(D.ZERO_COUNT) AS ZERO_COUNT,
           MAX(D.ZERO_PCT) AS ZERO_PCT,
           MAX(D.MIN_VALUE) AS MIN_VALUE,
           MAX(D.MAX_VALUE) AS MAX_VALUE,
           MAX(D.MEAN_VALUE) AS MEAN_VALUE,
           MAX(D.STDDEV_VALUE) AS STDDEV_VALUE,
           MAX(D.SPECIAL_COUNT) AS SPECIAL_COUNT,
           MAX(D.SPECIAL_PCT) AS SPECIAL_PCT,
           MAX(D.VALID_COUNT) AS VALID_COUNT,
           MAX(D.OUTLIER_COUNT) AS OUTLIER_COUNT,
           MAX(D.OUTLIER_PCT) AS OUTLIER_PCT,
           MAX(D.OUTLIER_VALUE_LOWER) AS OUTLIER_VALUE_LOWER,
           MAX(D.OUTLIER_VALUE_UPPER) AS OUTLIER_VALUE_UPPER
    FROM DEV_SCOPED D GROUP BY 1,2,3
),
PERIOD_SCOPE AS
(
    SELECT PERIOD_LEVEL,PERIOD_VALUE AS PERIOD_KEY FROM ENGINE_VALUES
    UNION
    SELECT PERIOD_LEVEL,PERIOD_KEY FROM DEV_GROUPS
    UNION
    SELECT CAST('OVERALL' AS VARCHAR(8)),CAST('ALL' AS VARCHAR(10))
    FROM CHOSEN_RUN WHERE PROFILE_OVERALL='Y'
),
INPUT_CHECK AS
(
    SELECT P.*,C.RUNS,F.FIELDS,M.METRICS,D.DEV_ROWS,T.PERIODS,
           CAST(CASE WHEN P.DEV_RUN_ID IS NULL THEN 'Set DEV_RUN_ID in PARAMS'
                WHEN P.RATE_ABS_TOL<0 OR P.VALUE_ABS_TOL<0 OR P.VALUE_REL_TOL<0
                  THEN 'Comparison tolerances must be nonnegative'
                WHEN P.SHOW_MATCHES NOT IN ('Y','N') THEN 'SHOW_MATCHES must be Y or N'
                WHEN C.RUNS<>1 THEN 'Engine run not found, wrong project, or not SUCCEEDED'
                WHEN F.FIELDS=0 THEN 'No captured numeric fields in this engine run'
                WHEN M.METRICS=0 THEN 'No successful Numeric Basic/Outliers module in this attempt'
                WHEN D.DEV_ROWS=0 THEN 'Development run ID has no rows in the configured numeric table'
                WHEN T.PERIODS=0 THEN 'No supported periods found; this comparison covers overall/monthly only'
                ELSE NULL END AS VARCHAR(256)) AS INPUT_ERROR
    FROM PARAMS P
    CROSS JOIN (SELECT COUNT(*) AS RUNS FROM CHOSEN_RUN) C
    CROSS JOIN (SELECT COUNT(*) AS FIELDS FROM FIELD_SCOPE) F
    CROSS JOIN (SELECT COUNT(*) AS METRICS FROM ENABLED_METRICS) M
    CROSS JOIN (SELECT COUNT(*) AS DEV_ROWS FROM DEV_RUN_VALUES) D
    CROSS JOIN (SELECT COUNT(*) AS PERIODS FROM PERIOD_SCOPE) T
),
PAIRED AS
(
    SELECT P.PROJECT_ID,P.OUR_RUN_NUMBER,P.DEV_RUN_ID,F.FIELD_NAME,T.PERIOD_LEVEL,T.PERIOD_KEY,
           M.METRIC_NAME,M.VALUE_KIND,M.MODULE_NAME AS COMPARED_MODULE,E.POU_DT AS ENGINE_POU_DT,
           CASE WHEN D.ROW_COPIES=1 THEN D.POU_DT END AS DEV_POU_DT,
           E.ROW_COPIES AS ENGINE_COPIES,D.ROW_COPIES AS DEV_COPIES,
           D.SNAPSHOT_DATES,
           E.TOTAL_COUNT AS ENGINE_TOTAL,D.ROW_COUNT AS DEV_TOTAL,
           E.VALID_COUNT AS ENGINE_VALID,D.VALID_COUNT AS DEV_VALID,
           CASE WHEN E.ROW_COPIES=1 THEN E.METRIC_VALUE END AS ENGINE_VALUE,
           CASE WHEN D.ROW_COPIES=1 THEN CASE M.METRIC_ORDINAL
             WHEN 1 THEN CAST(D.ROW_COUNT AS DECIMAL(38,10))
             WHEN 2 THEN CAST(D.ROW_COUNT-D.MISSING_COUNT AS DECIMAL(38,10))
             WHEN 3 THEN CAST(D.MISSING_COUNT AS DECIMAL(38,10))
             WHEN 4 THEN CAST(D.MISSING_PCT AS DECIMAL(38,10))
             WHEN 5 THEN CAST(D.ZERO_COUNT AS DECIMAL(38,10))
             WHEN 6 THEN CAST(D.ZERO_PCT AS DECIMAL(38,10))
             WHEN 7 THEN CAST(ROUND(D.MIN_VALUE,6) AS DECIMAL(38,6))
             WHEN 8 THEN CAST(ROUND(D.MAX_VALUE,6) AS DECIMAL(38,6))
             WHEN 9 THEN CAST(ROUND(D.MEAN_VALUE,6) AS DECIMAL(38,6))
             WHEN 10 THEN CAST(ROUND(D.STDDEV_VALUE,6) AS DECIMAL(38,6))
             WHEN 11 THEN CAST(D.SPECIAL_COUNT AS DECIMAL(38,10))
             WHEN 12 THEN CAST(D.SPECIAL_PCT AS DECIMAL(38,10))
             WHEN 13 THEN CAST(ROUND(D.OUTLIER_VALUE_LOWER,6) AS DECIMAL(38,6))
             WHEN 14 THEN CAST(ROUND(D.OUTLIER_VALUE_UPPER,6) AS DECIMAL(38,6))
             WHEN 15 THEN CAST(D.OUTLIER_COUNT AS DECIMAL(38,10))
             WHEN 16 THEN CAST(D.OUTLIER_PCT AS DECIMAL(38,10))
             WHEN 17 THEN CAST(D.VALID_COUNT AS DECIMAL(38,10))
           END END AS DEV_VALUE,
           P.RATE_ABS_TOL,P.VALUE_ABS_TOL,P.VALUE_REL_TOL
    FROM INPUT_CHECK P CROSS JOIN FIELD_SCOPE F CROSS JOIN PERIOD_SCOPE T
    CROSS JOIN ENABLED_METRICS M
    LEFT JOIN ENGINE_VALUES E ON E.FIELD_NAME=F.FIELD_NAME AND E.PERIOD_LEVEL=T.PERIOD_LEVEL
      AND E.PERIOD_VALUE=T.PERIOD_KEY AND E.MODULE_NAME=M.MODULE_NAME AND E.METRIC_NAME=M.METRIC_NAME
    LEFT JOIN DEV_GROUPS D ON D.FIELD_NAME=F.FIELD_NAME AND D.PERIOD_LEVEL=T.PERIOD_LEVEL
      AND D.PERIOD_KEY=T.PERIOD_KEY
    WHERE P.INPUT_ERROR IS NULL
),
MEASURED AS
(
    SELECT A.*,
           CASE WHEN VALUE_KIND='COUNT' THEN CAST(ENGINE_VALUE-DEV_VALUE AS DECIMAL(38,0)) END AS COUNT_DELTA,
           CAST(ENGINE_VALUE AS FLOAT)-CAST(DEV_VALUE AS FLOAT) AS VALUE_DELTA,
           CASE WHEN VALUE_KIND='RATE' THEN CAST(RATE_ABS_TOL AS FLOAT)
                WHEN VALUE_KIND='VALUE' THEN CAST(VALUE_ABS_TOL AS FLOAT)
                   +CAST(VALUE_REL_TOL AS FLOAT)*ABS(CAST(DEV_VALUE AS FLOAT))
                ELSE CAST(0 AS FLOAT) END AS ALLOWED_TOLERANCE
    FROM PAIRED A
),
EVALUATED AS
(
    SELECT A.*,
           CAST(CASE
             WHEN COALESCE(ENGINE_COPIES,0)>1 THEN 'DUPLICATE_ENGINE'
             WHEN PERIOD_LEVEL='MONTHLY' AND DEV_COPIES>1 AND SNAPSHOT_DATES>1 THEN 'PERIOD_SCOPE_MISMATCH'
             WHEN DEV_COPIES>1 THEN 'DUPLICATE_DEVELOPMENT'
             WHEN ENGINE_COPIES IS NULL AND DEV_COPIES IS NULL THEN 'MISSING_BOTH'
             WHEN ENGINE_COPIES IS NULL THEN 'MISSING_ENGINE'
             WHEN DEV_COPIES IS NULL THEN 'MISSING_DEVELOPMENT'
             WHEN PERIOD_LEVEL='MONTHLY' AND
                  (ENGINE_POU_DT<>DEV_POU_DT OR (ENGINE_POU_DT IS NULL AND DEV_POU_DT IS NOT NULL)
                   OR (ENGINE_POU_DT IS NOT NULL AND DEV_POU_DT IS NULL)) THEN 'SNAPSHOT_MISMATCH'
             WHEN DEV_TOTAL IS NULL OR (ENGINE_TOTAL IS NULL AND COMPARED_MODULE='NUMERIC_BASIC')
                  THEN 'POPULATION_UNAVAILABLE'
             WHEN ENGINE_TOTAL<>DEV_TOTAL THEN 'POPULATION_MISMATCH'
             WHEN METRIC_NAME='OUTLIER_COUNT' AND ENGINE_VALUE IS NULL AND DEV_VALUE=0
                  AND ENGINE_VALID=0 AND DEV_VALID=0 THEN 'DEFINITION_DIFFERENCE'
             WHEN ENGINE_VALUE IS NULL AND DEV_VALUE IS NULL THEN 'MATCH'
             WHEN ENGINE_VALUE IS NULL OR DEV_VALUE IS NULL THEN 'DIFFERENT'
             WHEN VALUE_KIND IN ('COUNT','EXACT') AND ENGINE_VALUE=DEV_VALUE THEN 'MATCH'
             WHEN VALUE_KIND IN ('COUNT','EXACT') THEN 'DIFFERENT'
             WHEN VALUE_KIND='RATE' AND ROUND(ABS(ENGINE_VALUE-DEV_VALUE),10)<=RATE_ABS_TOL THEN 'MATCH'
             WHEN VALUE_KIND='RATE' THEN 'DIFFERENT'
             WHEN ABS(VALUE_DELTA)<=ALLOWED_TOLERANCE THEN 'MATCH'
             ELSE 'DIFFERENT' END AS VARCHAR(32)) AS COMPARISON_STATUS
    FROM MEASURED A
),
DETAIL AS
(
    SELECT PROJECT_ID,OUR_RUN_NUMBER,DEV_RUN_ID,FIELD_NAME,PERIOD_LEVEL,PERIOD_KEY,
           ENGINE_POU_DT,DEV_POU_DT,METRIC_NAME,VALUE_KIND,ENGINE_VALUE,DEV_VALUE,
           COUNT_DELTA,VALUE_DELTA,ALLOWED_TOLERANCE,COMPARISON_STATUS,
           CAST(CASE COMPARISON_STATUS
             WHEN 'MATCH' THEN 'Values agree at review precision within the configured tolerance'
             WHEN 'DIFFERENT' THEN 'Unequal values, NULL mismatch, or tolerance exceeded'
             WHEN 'DUPLICATE_ENGINE' THEN 'More than one final review row for this field/month'
             WHEN 'PERIOD_SCOPE_MISMATCH' THEN 'Development has multiple actual snapshot dates within this engine month; no pooling performed'
             WHEN 'DUPLICATE_DEVELOPMENT' THEN 'More than one development row for the same normalized field/period key'
             WHEN 'MISSING_BOTH' THEN 'Expected field/period/metric absent on both sides'
             WHEN 'MISSING_ENGINE' THEN 'Captured numeric field is missing this engine metric/period'
             WHEN 'MISSING_DEVELOPMENT' THEN 'Selected field/period is absent in development; UNKNOWN dates may be omitted by its joins'
             WHEN 'SNAPSHOT_MISMATCH' THEN 'Monthly actual source snapshot dates differ'
             WHEN 'POPULATION_UNAVAILABLE' THEN 'Missing row count in the final review or development result'
             WHEN 'POPULATION_MISMATCH' THEN 'Row counts differ; establish the same source population before comparing statistics'
             WHEN 'DEFINITION_DIFFERENCE' THEN 'No valid observations: engine outlier count is undefined (NULL), development records zero'
             END AS VARCHAR(256)) AS REASON
    FROM EVALUATED
    UNION ALL
    SELECT P.PROJECT_ID,P.OUR_RUN_NUMBER,P.DEV_RUN_ID,CAST(NULL AS VARCHAR(128)),
           CAST(NULL AS VARCHAR(8)),CAST(NULL AS VARCHAR(10)),CAST(NULL AS DATE),CAST(NULL AS DATE),
           CAST(NULL AS VARCHAR(32)),CAST(NULL AS VARCHAR(8)),CAST(NULL AS DECIMAL(38,10)),CAST(NULL AS DECIMAL(38,10)),
           CAST(NULL AS DECIMAL(38,0)),CAST(NULL AS FLOAT),CAST(NULL AS FLOAT),
           CAST('NOT_EVALUATED' AS VARCHAR(32)),CAST(P.INPUT_ERROR AS VARCHAR(256))
    FROM INPUT_CHECK P WHERE P.INPUT_ERROR IS NOT NULL
)
SELECT D.FIELD_NAME,D.PERIOD_LEVEL,D.ENGINE_POU_DT AS POU_DT,D.DEV_POU_DT,
       D.METRIC_NAME,CAST(D.ENGINE_VALUE AS DECIMAL(38,6)) AS OUR_VALUE,
       CAST(D.DEV_VALUE AS DECIMAL(38,6)) AS DEV_VALUE,
       CASE WHEN D.VALUE_KIND='COUNT' THEN CAST(D.COUNT_DELTA AS DECIMAL(38,6))
            ELSE CAST(D.ENGINE_VALUE-D.DEV_VALUE AS DECIMAL(38,6)) END AS DIFFERENCE,
       D.COMPARISON_STATUS AS STATUS,D.REASON,
       D.OUR_RUN_NUMBER,D.DEV_RUN_ID,D.PROJECT_ID
FROM DETAIL D CROSS JOIN PARAMS P
WHERE D.COMPARISON_STATUS<>'MATCH' OR P.SHOW_MATCHES='Y'
ORDER BY FIELD_NAME,PERIOD_LEVEL,POU_DT,METRIC_NAME;
