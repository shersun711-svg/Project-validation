/* Isolated test engine, after fixture 01. Run once. Every assertion returns
   ZERO rows; CALL/DDL errors fail the test. These queries do not count a
   missing run/result as a pass: scalar aggregate checks always execute. */
CALL DQ_DB.SP_DQ_RUN_BASIC('20000000-0000-4000-8000-000000000001','DQ_BASIC_TEST','Y','Y','Y','Y');
SELECT 'mixed_run' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_RUN_LOG WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND STATUS='SUCCEEDED')<>1
   OR (SELECT COUNT(*) FROM DQ_DB.DQ_METRIC_RESULT WHERE RUN_ID='20000000-0000-4000-8000-000000000001')<>264
   OR (SELECT COUNT(*) FROM DQ_DB.DQ_BASIC_REVIEW WHERE RUN_ID='20000000-0000-4000-8000-000000000001')<>48
   OR (SELECT COUNT(*) FROM DQ_DB.DQ_RUN_FIELD_CONFIG WHERE RUN_ID='20000000-0000-4000-8000-000000000001')<>6;
SELECT 'category_identifier_values' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_COMPLETED_RESULT
 WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL='OVERALL'
   AND FIELD_NAME IN ('CATEGORY','CUSTOMER_ID')
   AND ((METRIC_NAME='MISSING_COUNT' AND METRIC_VALUE=1)
     OR (METRIC_NAME='MISSING_RATE_PCT' AND METRIC_VALUE=25 AND DQ_COLOUR='RED')
     OR (METRIC_NAME='DISTINCT_COUNT' AND METRIC_VALUE=2)))<>6;
SELECT 'null_category' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_COMPLETED_RESULT
 WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL='OVERALL'
   AND FIELD_NAME='NULL_CATEGORY'
   AND ((METRIC_NAME='MISSING_COUNT' AND METRIC_VALUE=4)
     OR (METRIC_NAME='MISSING_RATE_PCT' AND METRIC_VALUE=100 AND DQ_COLOUR='RED')
     OR (METRIC_NAME='DISTINCT_COUNT' AND METRIC_VALUE=0)))<>3;
SELECT 'date_counts' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_BASIC_REVIEW
 WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL='OVERALL' AND FIELD_TYPE='DATE'
   AND TOTAL_COUNT=4 AND NON_MISSING_COUNT=3 AND MISSING_COUNT=1
   AND MISSING_RATE_PCT=25 AND MISSING_RATE_COLOUR='RED')<>2;
SELECT 'date_only_requested_metrics' AS ASSERTION_NAME FROM DQ_DB.DQ_METRIC_RESULT
WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND FIELD_TYPE='DATE'
  AND METRIC_NAME NOT IN ('TOTAL_COUNT','NON_MISSING_COUNT','MISSING_COUNT','MISSING_RATE_PCT');
SELECT 'period_distinct_not_summed' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_COMPLETED_RESULT
