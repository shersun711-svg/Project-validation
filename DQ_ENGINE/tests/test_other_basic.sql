CREATE VOLATILE TABLE QA_BASIC_NUMBER AS
(SELECT N.RUN_NUMBER,C.LAST_NUMBER FROM DQ_DB.DQ_RUN_NUMBER N
 CROSS JOIN DQ_DB.DQ_RUN_COUNTER C
 WHERE N.RUN_ID='20000000-0000-4000-8000-000000000005')
WITH DATA NO PRIMARY INDEX ON COMMIT PRESERVE ROWS;
UPDATE DQ_DB.DQ_FIELD_CONFIG SET ACTIVE_IND='N'
WHERE PROJECT_ID='DQ_BASIC_BAD' AND FIELD_NAME='Z_MISSING_DATE';
