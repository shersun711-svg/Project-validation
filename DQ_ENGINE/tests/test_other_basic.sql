/* Availability dates describe FACT_DT coverage, not a date field's own values.
   Non-missing zeros count as available; rows with NULL FACT_DT do not extend it. */
SELECT 'overall_availability' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_BASIC_REVIEW
 WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL='OVERALL'
   AND FIRST_AVAILABLE_FACT_DT=DATE '2000-01-31'
   AND ((FIELD_NAME IN ('AMOUNT','CUSTOMER_ID','EVENT_DATE') AND LAST_AVAILABLE_FACT_DT=DATE '2001-01-31')
     OR (FIELD_NAME IN ('CATEGORY','EVENT_TS') AND LAST_AVAILABLE_FACT_DT=DATE '2000-02-29')))<>5
   OR (SELECT COUNT(*) FROM DQ_DB.DQ_BASIC_REVIEW
       WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL='OVERALL'
         AND FIELD_NAME='NULL_CATEGORY' AND FIRST_AVAILABLE_FACT_DT IS NULL AND LAST_AVAILABLE_FACT_DT IS NULL)<>1
   OR (SELECT COUNT(*) FROM DQ_DB.DQ_FIELD_AVAILABILITY
       WHERE RUN_ID='20000000-0000-4000-8000-000000000001')<>6;
SELECT 'coverage_overall_only' AS ASSERTION_NAME
FROM DQ_DB.DQ_BASIC_REVIEW
WHERE RUN_ID='20000000-0000-4000-8000-000000000001' AND PERIOD_LEVEL<>'OVERALL'
  AND (FIRST_AVAILABLE_FACT_DT IS NOT NULL OR LAST_AVAILABLE_FACT_DT IS NOT NULL);
SELECT 'empty_availability' AS ASSERTION_NAME
FROM (SELECT COUNT(*) AS N FROM DQ_DB.DQ_ENGINE_SETTINGS) AS CHECK_ANCHOR
WHERE (SELECT COUNT(*) FROM DQ_DB.DQ_FIELD_AVAILABILITY
       WHERE RUN_ID='20000000-0000-4000-8000-000000000004'
         AND EARLIEST_DATE IS NULL AND LATEST_DATE IS NULL)<>5;
