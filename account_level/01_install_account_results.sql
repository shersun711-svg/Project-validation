/* Persisted account results. Replace DQ_DB globally. Run each statement separately. */
REPLACE VIEW DQ_DB.DQ_ACCOUNT_REVIEW AS
SELECT S.RUN_ID,N.RUN_NUMBER,L.PROJECT_ID,S.FIELD_NAME,S.FIELD_TYPE,S.POU_DT,
       S.TEST_STATUS,L.SOURCE_DATABASE,L.SOURCE_TABLE,L.REPORTING_DATE_FIELD,
       S.ACCOUNT_ID_FIELD,S.WINDOW_START,S.WINDOW_END,S.STABLE_VALUE_IND,
       CAST(CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.ABS_CHANGE_MIN END AS DECIMAL(38,6)) AS ABS_CHANGE_MIN,
       CAST(CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.REL_CHANGE_MIN END AS DECIMAL(38,6)) AS REL_CHANGE_MIN,
       CAST(CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.RETURN_ABS_TOL END AS DECIMAL(38,6)) AS RETURN_ABS_TOL,
       CAST(CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.RETURN_REL_TOL END AS DECIMAL(38,6)) AS RETURN_REL_TOL,
       S.TOTAL_COUNT AS TOTAL_COUNT,
       S.PAIR_COUNT AS PAIR_COUNT,
       S.TRIPLE_COUNT AS TRIPLE_COUNT,
       S.VALID_PAIR_COUNT AS VALID_PAIR_COUNT,
       S.VALID_REFERENCE_PAIR_COUNT AS VALID_REFERENCE_PAIR_COUNT,
       S.VALID_NEIGHBOUR_TRIPLE_COUNT AS VALID_NEIGHBOUR_TRIPLE_COUNT,
       S.VALID_TRIPLE_COUNT AS VALID_TRIPLE_COUNT,
       CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.NUMERIC_JUMP_COUNT END AS NUMERIC_JUMP_COUNT,
       CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.NUMERIC_REVERSION_COUNT END AS NUMERIC_REVERSION_COUNT,
       CASE WHEN S.FIELD_TYPE<>'NUMERIC' THEN S.VALUE_REVERSION_COUNT END AS VALUE_REVERSION_COUNT,
       S.MISSING_REVERSION_COUNT AS MISSING_REVERSION_COUNT,
       CASE WHEN S.FIELD_TYPE IN ('NUMERIC','CATEGORICAL') THEN S.SPECIAL_REVERSION_COUNT END AS SPECIAL_REVERSION_COUNT,
       S.BECAME_MISSING_COUNT AS BECAME_MISSING_COUNT,
       CASE WHEN S.FIELD_TYPE IN ('NUMERIC','CATEGORICAL') THEN S.BECAME_SPECIAL_COUNT END AS BECAME_SPECIAL_COUNT,
       CASE WHEN S.STABLE_VALUE_IND='Y' THEN S.STABLE_VALUE_CHANGE_COUNT END AS STABLE_VALUE_CHANGE_COUNT,
       S.FLAGGED_ROW_COUNT AS FLAGGED_ROW_COUNT,
       CAST(CAST((CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.NUMERIC_JUMP_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_PAIR_COUNT) AS DECIMAL(18,6)) AS NUMERIC_JUMP_RATE,
       CAST(CAST((CASE WHEN S.FIELD_TYPE='NUMERIC' THEN S.NUMERIC_REVERSION_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_TRIPLE_COUNT) AS DECIMAL(18,6)) AS NUMERIC_REVERSION_RATE,
       CAST(CAST((CASE WHEN S.FIELD_TYPE<>'NUMERIC' THEN S.VALUE_REVERSION_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_TRIPLE_COUNT) AS DECIMAL(18,6)) AS VALUE_REVERSION_RATE,
       CAST(CAST((S.MISSING_REVERSION_COUNT) AS FLOAT)/NULLIFZERO(S.VALID_NEIGHBOUR_TRIPLE_COUNT) AS DECIMAL(18,6)) AS MISSING_REVERSION_RATE,
       CAST(CAST((CASE WHEN S.FIELD_TYPE IN ('NUMERIC','CATEGORICAL') THEN S.SPECIAL_REVERSION_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_NEIGHBOUR_TRIPLE_COUNT) AS DECIMAL(18,6)) AS SPECIAL_REVERSION_RATE,
       CAST(CAST((S.BECAME_MISSING_COUNT) AS FLOAT)/NULLIFZERO(S.VALID_REFERENCE_PAIR_COUNT) AS DECIMAL(18,6)) AS BECAME_MISSING_RATE,
       CAST(CAST((CASE WHEN S.FIELD_TYPE IN ('NUMERIC','CATEGORICAL') THEN S.BECAME_SPECIAL_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_REFERENCE_PAIR_COUNT) AS DECIMAL(18,6)) AS BECAME_SPECIAL_RATE,
       CAST(CAST((CASE WHEN S.STABLE_VALUE_IND='Y' THEN S.STABLE_VALUE_CHANGE_COUNT END) AS FLOAT)/NULLIFZERO(S.VALID_PAIR_COUNT) AS DECIMAL(18,6)) AS STABLE_VALUE_CHANGE_RATE,
       S.CREATED_TIMESTAMP
FROM DQ_DB.DQ_ACCOUNT_SUMMARY S
JOIN DQ_DB.DQ_RUN_LOG L ON L.RUN_ID=S.RUN_ID
JOIN DQ_DB.DQ_RUN_NUMBER N ON N.RUN_ID=S.RUN_ID
WHERE L.STATUS='SUCCEEDED';

REPLACE VIEW DQ_DB.DQ_ACCOUNT_DETAIL_REVIEW AS
SELECT D.RUN_ID,N.RUN_NUMBER,L.PROJECT_ID,D.FIELD_NAME,S.FIELD_TYPE,D.AGMT_ID,
       D.PREVIOUS_POU_DT,D.POU_DT,D.NEXT_POU_DT,
       D.PREVIOUS_VALUE,D.CURRENT_VALUE,D.NEXT_VALUE,
       D.PREVIOUS_STATE,D.CURRENT_STATE,D.NEXT_STATE,
       D.CHANGE_VALUE,
       D.RELATIVE_CHANGE,
       D.NEXT_CHANGE_VALUE,
       D.NUMERIC_JUMP,D.NUMERIC_REVERSION,D.VALUE_REVERSION,D.MISSING_REVERSION,D.SPECIAL_REVERSION,D.BECAME_MISSING,D.BECAME_SPECIAL,D.STABLE_VALUE_CHANGE,
       D.CREATED_TIMESTAMP
FROM DQ_DB.DQ_ACCOUNT_DETAIL D
JOIN DQ_DB.DQ_ACCOUNT_SUMMARY S ON S.RUN_ID=D.RUN_ID AND S.FIELD_NAME=D.FIELD_NAME
 AND EXTRACT(YEAR FROM S.POU_DT)=EXTRACT(YEAR FROM D.POU_DT)
 AND EXTRACT(MONTH FROM S.POU_DT)=EXTRACT(MONTH FROM D.POU_DT)
JOIN DQ_DB.DQ_RUN_LOG L ON L.RUN_ID=D.RUN_ID
JOIN DQ_DB.DQ_RUN_NUMBER N ON N.RUN_ID=D.RUN_ID
WHERE L.STATUS='SUCCEEDED';

REPLACE VIEW DQ_DB.DQ_ACCOUNT_PROGRESS AS
SELECT L.RUN_ID,N.RUN_NUMBER,L.PROJECT_ID,L.STATUS AS RUN_STATUS,
       M.BATCH_ID,CAST(M.SQL_TEXT AS VARCHAR(128)) AS FIELD_NAME,
       M.STATUS AS FIELD_STATUS,CAST(M.START_TIME AS TIMESTAMP(0)) AS START_TIME,
       CAST(M.END_TIME AS TIMESTAMP(0)) AS END_TIME,M.FIELD_COUNT,
       M.ERROR_CODE,M.ERROR_INFORMATION
FROM DQ_DB.DQ_RUN_LOG L
JOIN DQ_DB.DQ_MODULE_LOG M ON M.RUN_ID=L.RUN_ID
LEFT JOIN DQ_DB.DQ_RUN_NUMBER N ON N.RUN_ID=L.RUN_ID
WHERE M.MODULE_NAME='ACCOUNT_CHECKS';

GRANT SELECT ON DQ_DB.DQ_ACCOUNT_REVIEW TO DQ_DB;
GRANT SELECT ON DQ_DB.DQ_ACCOUNT_DETAIL_REVIEW TO DQ_DB;
GRANT SELECT ON DQ_DB.DQ_ACCOUNT_PROGRESS TO DQ_DB;

